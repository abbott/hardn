// searchInUse is the search domains in use on the host s describes, as
// the screens and the reviews show them: the file's, or resolved's global
// ones and then each link's, which dns.Read does not keep, so they are
// the fake's (dnsLinkDomains).
func searchInUse(s dns.State) []string {
	if s.Manager != dns.ManagerResolved {
		return s.Search
	}
	return append(slices.Clone(s.Resolved.Domains), dnsLinkDomains...)
}

// TestDNSScreensAreReal checks that each DNS screen shows what dns.Read
// establishes of its host: the manager, in the screen's proposed words;
// the nameservers in use, the file's, or systemd-resolved's global ones
// and each link's after it, and Unknown where pkg/host/dns reads none, as
// of a manager it only reports; the search domains in use, the file's, or
// resolved's global ones and then each link's, which are the fake's
// (searchInUse; "None" for none); and hardn.yml's list, or P-30 (b)'s
// muted item for none, item 3 then left out. Every DNS screen is one of
// these.
func TestDNSScreensAreReal(t *testing.T) {
	managers := map[dns.Manager]component.KeyValue{
		dns.ManagerFile:     {Key: "DNS Implementation", Value: "direct (/etc/resolv.conf)"},
		dns.ManagerProxmox:  {Key: "DNS Implementation", Value: "Proxmox VE (/etc/resolv.conf)"},
		dns.ManagerResolved: {Key: "DNS Implementation", Value: "systemd-resolved"},
		dns.ManagerNetworkManager: {Key: "DNS Implementation", Value: "NetworkManager,", State: component.ValueWarn,
			Note: "reported only"},
	}
	shown := func(key string, values []string, read bool) component.KeyValue {
		switch {
		case !read:
			return component.KeyValue{Key: key, State: component.ValueUnknown}
		case len(values) == 0:
			return component.KeyValue{Key: key, Value: "None"}
		}
		return component.KeyValue{Key: key, Value: strings.Join(values, ", ")}
	}
	for _, m := range screen.Mocks() {
		if strings.HasPrefix(m.Name, "sub-menu/03-dns") {
			if _, ok := dnsScreens[m.Name]; !ok {
				t.Errorf("%s: a DNS screen with no host here", m.Name)
			}
		}
	}
	for name, hostName := range dnsScreens {
		h := newDNSFake(t, hostName)
		s := h.read(t)
		inUse, search, read := s.Nameservers, searchInUse(s), s.Manager == dns.ManagerFile || s.Manager == dns.ManagerProxmox
		if s.Manager == dns.ManagerResolved {
			inUse, read = slices.Clone(s.Resolved.Global), true
			for _, l := range s.Resolved.Links {
				for _, a := range l.Servers {
					inUse = append(inUse, a+" ("+l.Name+")")
				}
			}
		}
		listed := []component.KeyValue{{Key: "No nameservers configured", State: component.ValueNone}}
		if len(h.configured) > 0 {
			listed = nil
			for i, ns := range h.configured {
				listed = append(listed, component.KeyValue{Key: fmt.Sprintf("Nameserver %d", i+1), Value: ns})
			}
		}
		vm, _ := dnsMock(t, name).Screen.(screen.SubMenu)
		want := [][]component.KeyValue{{managers[s.Manager], shown("Nameservers", inUse, read), shown("Search Domains", search, read)}, listed}
		if len(vm.Sections) != 2 || !slices.Equal(vm.Sections[0].Rows.Items, want[0]) || !slices.Equal(vm.Sections[1].Rows.Items, want[1]) {
			t.Errorf("%s: shows %+v; dns.Read gives %s, %v, %v, configured %v, want %+v", name, vm.Sections, s.Manager, inUse, search, h.configured, want)
		}
		removes := slices.ContainsFunc(vm.Menu.Items, func(it component.MenuItem) bool { return it.Key == "3" })
		if removes != (len(h.configured) > 0) {
			t.Errorf("%s: item 3 shown %v, with %d nameservers configured", name, removes, len(h.configured))
		}
	}
}

// TestDNSRefusalsAreReal checks each DNS screen's refusals against
// dns.PlanDNS: on the NetworkManager host every item refuses, naming the
// manager dns.Read found, where PlanDNS refuses with ErrManaged
// (DNS_MANAGED); with no nameserver configured, Configure DNS refuses,
// where PlanDNS refuses with ErrNoNameservers (DNS_NO_NAMESERVERS); with
// one, Remove nameserver refuses, where PlanDNS refuses the list without
// it with ErrNoNameservers; no other screen refuses anything, and every
// host it plans for plans.
func TestDNSRefusalsAreReal(t *testing.T) {
	for name, hostName := range dnsScreens {
		h := newDNSFake(t, hostName)
		s := h.read(t)
		m := dnsMock(t, name)
		vm, _ := m.Screen.(screen.SubMenu)
		_, err := dns.PlanDNS(s, dns.Config{Nameservers: h.configured})
		var want []string
		switch hostName {
		case "networkmanager":
			for _, it := range vm.Menu.Items {
				want = append(want, it.Key)
			}
			if !errors.Is(err, dns.ErrManaged) || output.CodeOf(err) != "DNS_MANAGED" || s.Manager != dns.ManagerNetworkManager {
				t.Errorf("%s: PlanDNS = %v (%s), manager %s; want DNS_MANAGED for NetworkManager", name, err, output.CodeOf(err), s.Manager)
			}
		case "empty":
			want = []string{"1"}
			if !errors.Is(err, dns.ErrNoNameservers) || output.CodeOf(err) != "DNS_NO_NAMESERVERS" {
				t.Errorf("%s: PlanDNS = %v (%s); want DNS_NO_NAMESERVERS", name, err, output.CodeOf(err))
			}
		case "one":
			want = []string{"3"}
			_, rerr := dns.PlanDNS(s, dns.Config{Nameservers: h.configured[1:]})
			if err != nil || len(h.configured) != 1 || !errors.Is(rerr, dns.ErrNoNameservers) || output.CodeOf(rerr) != "DNS_NO_NAMESERVERS" {
				t.Errorf("%s: PlanDNS = %v; less its one nameserver %v (%s); want it to plan, then DNS_NO_NAMESERVERS", name, err, rerr, output.CodeOf(rerr))
			}
		default:
			if err != nil {
				t.Errorf("%s: PlanDNS = %v", name, err)
			}
		}
		var keys []string
		for k, msg := range m.Refusals {
			keys = append(keys, k)
			if hostName == "networkmanager" && !strings.Contains(msg.Text, "NetworkManager") || msg.Kind != component.MessageWarn {
				t.Errorf("%s/%s: refuses with %+v; want a warning naming the manager", name, k, msg)
			}
		}
		slices.Sort(keys)
		if !slices.Equal(keys, want) {
			t.Errorf("%s: refuses %v, want %v", name, keys, want)
		}
	}
}

