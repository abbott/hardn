// dnsConfigured is hardn.yml's list on the hosts that have one.
var dnsConfigured = []string{"192.0.2.54", "2001:db8::54"}

// dnsFake is one host: its facts, its system and hardn.yml's list.
type dnsFake struct {
	facts      detect.Facts
	sys        *hostfake.System
	configured []string
	// globals is what resolvectl lists as systemd-resolved's global
	// servers: it never changes, as after a reload with no effect.
	globals string
}

// eth0Domain is eth0's own search domain, which resolvectl lists on the
// Ubuntu host and dns.Read drops (Resolved keeps a link's servers alone;
// gallery-dns.md §8); dnsLinkDomains are the screens' words for it, the
// one reading they show that is the fake's script, not dns.Read's.
const eth0Domain = "example.net"

var dnsLinkDomains = []string{eth0Domain + " (eth0)"}

// dnsFacts are detect's facts for distro on init, outside a container.
func dnsFacts(distro detect.Distro, version string, init detect.InitKind) detect.Facts {
	return detect.Facts{Platform: detect.Platform{Distro: distro, Version: version, Support: detect.Supported},
		Init: detect.Init{Kind: init, Running: detect.Yes}, Container: detect.Container{Detected: detect.No}}
}

// newDNSFake returns the host name names, by the DNS screen's suffix.
func newDNSFake(t *testing.T, name string) *dnsFake {
	t.Helper()
	h := &dnsFake{sys: hostfake.New(host.Options{}), configured: dnsConfigured,
		facts: dnsFacts(detect.DistroDebian, "13", detect.Systemd)}
	active := "inactive"
	for _, d := range []string{"/etc", "/var/lib", "/var/backups", "/run", "/var/log"} {
		h.sys.AddDir(d, 0o755, 0, 0)
	}
	file := func(s string) { h.sys.AddFile(dns.ResolvConf, []byte(s), 0o644, 0, 0) }
	debian := "# Generated by dhcpcd from eth0.dhcp\nsearch example.net\n"
	switch name {
	case "", "empty", "one":
		file(debian + "nameserver 192.0.2.1\n")
		h.sys.AddFile("/usr/sbin/dhcpcd", nil, 0o755, 0, 0)
		switch name {
		case "empty":
			h.configured = nil
		case "one":
			h.configured = dnsConfigured[:1:1]
		}
	case "configured":
		file(debian + "nameserver 192.0.2.54\nnameserver 2001:db8::54\n")
		h.sys.AddFile("/usr/sbin/dhcpcd", nil, 0o755, 0, 0)
	case "alpine324":
		h.facts = dnsFacts(detect.DistroAlpine, "3.24", detect.OpenRC)
		file("search example.net\nnameserver 192.0.2.1\n")
		h.sys.AddFile(dns.UDHCPCConf, []byte("# Do not overwrite /etc/resolv.conf\n#RESOLV_CONF=\"no\"\n\n#NO_DNS=\"eth1 wlan1\"\n"), 0o644, 0, 0)
	case "pve9":
		h.facts = dnsFacts(detect.DistroProxmox, "9", detect.Systemd)
		file("search example.net\nnameserver 192.0.2.1\n")
	case "networkmanager":
		h.sys.AddSymlink(dns.ResolvConf, "/run/NetworkManager/resolv.conf")
	case "ubuntu2604":
		h.facts = dnsFacts(detect.DistroUbuntu, "26.04", detect.Systemd)
		active = "active"
		h.sys.AddSymlink(dns.ResolvConf, "../run/systemd/resolve/stub-resolv.conf")
		h.sys.AddFile("/etc/systemd/resolved.conf", []byte("[Resolve]\n#DNS=\n#Domains=\n"), 0o644, 0, 0)
	default:
		t.Fatalf("no DNS host %q", name)
	}
	h.sys.Handler = func(argv []string, _ []byte) hostfake.Response {
		switch strings.Join(argv, " ") {
		case "systemctl is-active " + dns.ResolvedUnit:
			if active == "active" {
				return hostfake.Response{Stdout: "active\n"}
			}
			return hostfake.Response{Stdout: active + "\n", ExitCode: 3}
		case "resolvectl --no-pager dns":
			return hostfake.Response{Stdout: "Global:" + h.globals + "\nLink 2 (eth0): 192.0.2.1\n"}
		case "resolvectl --no-pager domain":
			return hostfake.Response{Stdout: "Global:\nLink 2 (eth0): " + eth0Domain + "\n"}
		case "systemctl try-reload-or-restart " + dns.ResolvedUnit, "systemctl reload-or-restart " + dns.ResolvedUnit:
			return hostfake.Response{} // exits 0, and loads nothing new
		}
		return hostfake.Response{Err: hostfake.ErrUnscripted}
	}
	return h
}

// read is what dns.Read establishes of h.
func (h *dnsFake) read(t *testing.T) dns.State {
	t.Helper()
	s, err := dns.Read(context.Background(), h.sys, h.facts)
	if err != nil || s.Err != nil {
		t.Fatalf("dns.Read: %v, %v", err, s.Err)
	}
	return s
}

