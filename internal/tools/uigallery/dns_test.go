// collected is sequence seq's flow with its form answered, all but the
// confirmation, as the flow collects them before it reviews and plans.
func collected(t *testing.T, seq screen.Sequence) flow.Flow {
	t.Helper()
	_, f := seq.Build()
	var lines []string
	for _, a := range seq.Answers {
		if a.Step != "confirm" {
			lines = append(lines, a.Line)
		}
	}
	env := term.Fixed(80, colorprofile.NoTTY, false, true)
	p := nav.Prompter{Ctx: component.NewCtx(env), In: prompt.New(strings.NewReader(strings.Join(lines, "\n")+"\n"), false), Out: io.Discard}
	if err := f.Form.Run(p); err != nil {
		t.Fatalf("%s: the form: %v", seq.Name, err)
	}
	return f
}

// sequenceNamed returns mock m's sequence name.
func sequenceNamed(t *testing.T, m screen.Mock, name string) screen.Sequence {
	t.Helper()
	i := slices.IndexFunc(m.Sequences, func(s screen.Sequence) bool { return s.Name == name })
	if i < 0 {
		t.Fatalf("%s: no sequence %s", m.Name, name)
	}
	return m.Sequences[i]
}

// fixedDiff is the diff of p's file changes as steps.DNS should take it:
// a file the plan creates against /dev/null, so that it reads as created
// (gallery-dns.md records steps.DNS taking it against "", for unit (b)).
func fixedDiff(p dns.Plan) string {
	var out string
	for _, c := range p.Changes {
		if c.Path == "" {
			continue
		}
		after := string(c.After)
		var before *string
		if c.Before != nil {
			s := string(c.Before)
			before = &s
		}
		out += engine.FileDiff(c.Path, before, &after)
	}
	return out
}

// findingNames reports whether line warns of f: it names the link and
// its servers, the DHCP client, udhcpc, or Proxmox VE's settings when
// saved, as dns's detail has them rewrite the file "on save".
func findingNames(f dns.Finding, s dns.State, line string) bool {
	switch f.Kind {
	case dns.FindingPerLink:
		for _, l := range s.Resolved.Links {
			if strings.Contains(f.Detail, l.String()) {
				return strings.Contains(line, l.Name) && strings.Contains(line, strings.Join(l.Servers, ", "))
			}
		}
	case dns.FindingDHCPClient:
		return strings.HasPrefix(line, path.Base(f.Path)+" ")
	case dns.FindingUDHCPC:
		return strings.HasPrefix(line, "udhcpc ")
	case dns.FindingProxmox:
		return strings.Contains(f.Detail, "rewrite it on save") && strings.HasPrefix(line, "Saving Proxmox VE's ")
	}
	return false
}

// TestDNSPlansAreReal checks every DNS sequence's review and plan against
// dns.PlanDNS for its host and list, through steps.DNS, as the engine
// shows a change (output.FlowEngine): the change's title, its target, its
// diff (a created file's against /dev/null) and its commands, or no
// change where PlanDNS plans none; the save of hardn.yml after it exactly
// when the list changes; the review's nameservers, PlanDNS's canonical
// list, and the search domains the host keeps; and a warning line for
// each of the plan's findings, whose code pkg/output's registry holds,
// then the save's.
func TestDNSPlansAreReal(t *testing.T) {
	for _, tt := range dnsCases {
		name := tt.mock + "/" + tt.sequence
		h := newDNSFake(t, tt.host)
		s := h.read(t)
		p, err := dns.PlanDNS(s, dns.Config{Nameservers: tt.nameservers, UDHCPCNoResolv: tt.udhcpc})
		if err != nil {
			t.Fatalf("%s: PlanDNS: %v", name, err)
		}
		f := collected(t, sequenceNamed(t, dnsMock(t, tt.mock), tt.sequence))
		fp, err := f.Engine.Plan(context.Background())
		if err != nil {
			t.Fatalf("%s: plan: %v", name, err)
		}
		changes := fp.View.Changes
		if len(p.Changes) > 0 {
			if len(changes) == 0 {
				t.Fatalf("%s: plans nothing; PlanDNS plans %d steps", name, len(p.Changes))
			}
			got := changes[0]
			ch, err := steps.DNS("dns", p, got.Title)
			if err != nil {
				t.Fatalf("%s: steps.DNS: %v", name, err)
			}
			want := component.PlanChange{Title: ch.Heading(), Target: ch.Target, Diff: fixedDiff(p), Commands: ch.Commands}
			if !slices.Equal(got.Commands, want.Commands) || got.Title != want.Title || got.Target != want.Target || got.Diff != want.Diff {
				t.Errorf("%s: plans\n%+v\nsteps.DNS makes\n%+v", name, got, want)
			}
			if ch.Stage != engine.StageFiles || ch.Risk != engine.RiskPlain {
				t.Errorf("%s: steps.DNS's stage %v, risk %v; want files, plain (brief 2.4)", name, ch.Stage, ch.Risk)
			}
			// steps.DNS's own diff differs only where unit (b) fixes it.
			if ch.Diff != want.Diff && strings.Replace(ch.Diff, "--- "+dns.DropIn+"\n", "--- /dev/null\n", 1) != want.Diff {
				t.Errorf("%s: steps.DNS's diff\n%s\nwant\n%s", name, ch.Diff, want.Diff)
			}
			changes = changes[1:]
		}
		saved := !slices.Equal(tt.nameservers, h.configured)
		if saved != (len(changes) == 1 && changes[0].Target == "/etc/hardn/hardn.yml") || len(changes) > 1 {
			t.Errorf("%s: after the change plans %+v; want the save of hardn.yml %v", name, changes, saved)
		}
		r := f.Review()
		search := "None"
		if in := searchInUse(s); len(in) > 0 {
			search = strings.Join(in, ", ")
		}
		rows := []component.KeyValue{{Key: "Nameservers", Value: strings.Join(p.Want.Nameservers, ", ")}, {Key: "Search Domains", Value: search}}
		if len(r.Items) < 2 || !slices.Equal(r.Items[:2], rows) {
			t.Errorf("%s: reviews %+v; want %+v first", name, r.Items, rows)
			continue
		}
		lines := r.Items[2:]
		if saved {
			if n := len(lines) - 1; n < 0 || lines[n].Key != "Saving hardn.yml loses its comments" {
				t.Errorf("%s: the review does not say hardn.yml's comments are lost: %+v", name, lines)
			} else {
				lines = lines[:n]
			}
		}
		if len(lines) != len(p.Findings) {
			t.Errorf("%s: reviews %d findings, PlanDNS has %+v", name, len(lines), p.Findings)
			continue
		}
		for i, f := range p.Findings {
			code := steps.FindingCode("DNS", f.Kind.String())
			if _, ok := output.Lookup(code); !ok || lines[i].State != component.ValueWarn || !findingNames(f, s, lines[i].Key) {
				t.Errorf("%s: review line %+v for %s (%s)", name, lines[i], f.Kind, code)
			}
		}
	}
}

// TestDNSCheckIsValidate checks Add nameserver's check against
// dns.Validate for the main host's list and one more entry, on each kind
// of address dns.Validate refuses, a duplicate, and some it takes: the
// check refuses exactly what dns.Validate refuses, each kind of refusal in
// its own words, origin/main's where it has them (an empty entry, one
// that is no address, a duplicate), else the proposed one for an address
// a resolver cannot use.
func TestDNSCheckIsValidate(t *testing.T) {
	f := collected(t, sequenceNamed(t, dnsMock(t, "workflow-step/dns-add-nameserver"), "normal"))
	var check func(string) error
	for _, fl := range f.Form.Fields {
		if tf, ok := fl.(*form.Text); ok {
			check = tf.Validate
		}
	}
	if check == nil {
		t.Fatal("Add nameserver asks no text with a check")
	}
	for _, entry := range []string{"999.1.1.1", "192.0.2.54", "192.0.2.53", "2001:db8::53", "2001:DB8::54", "web-01.example.net",
		"192.0.2.53:53", "", "fe80::1", "fe80::1%eth0", "::ffff:192.0.2.53", "::", "0.0.0.0", "0.1.2.3", "255.255.255.255",
		"224.0.0.251", "ff02::1", "127.0.0.53", "169.254.0.53", "192.0.2.054"} {
		_, verr := dns.Validate(dns.Config{Nameservers: append(slices.Clone(dnsConfigured), entry)}, dns.ManagerFile)
		var want string
		switch {
		case verr == nil:
		case !errors.Is(verr, dns.ErrInvalid):
			t.Fatalf("dns.Validate(%q): %v, not ErrInvalid", entry, verr)
		case entry == "":
			want = "Nameserver cannot be empty"
		case strings.Contains(verr.Error(), "not an IPv4 or IPv6 address"):
			want = "Invalid IP address format"
		case strings.Contains(verr.Error(), "given twice"):
			want = "Nameserver " + canonicalOf(entry) + " is already configured"
		default:
			want = "Not a usable nameserver address"
		}
		got := check(entry)
		if (got == nil) != (verr == nil) || got != nil && got.Error() != want {
			t.Errorf("check(%q) = %v; want %q, as dns.Validate: %v", entry, got, want, verr)
		}
	}
}

// canonicalOf is entry as dns.Validate keeps it, or entry itself when it
// takes none.
func canonicalOf(entry string) string {
	c, err := dns.Validate(dns.Config{Nameservers: []string{entry}}, dns.ManagerFile)
	if err != nil {
		return entry
	}
	return c.Nameservers[0]
}

// dnsControl plans the change it holds, as the DNS control will (unit
// (b)).
type dnsControl struct{ change engine.Change }

func (dnsControl) ID() string                                    { return "dns" }
func (dnsControl) Title() string                                 { return "DNS" }
func (dnsControl) Applies(detect.Facts) (ok bool, reason string) { return true, "" }
func (dnsControl) Check(context.Context, host.System, detect.Facts) (engine.Status, error) {
	return engine.Status{State: engine.NotConfigured}, nil
}
func (c dnsControl) Plan(context.Context, host.System, engine.Input) ([]engine.Change, error) {
	return []engine.Change{c.change}, nil
}

// reports is what an Apply reported, step by step.
type reports []string

func (r *reports) report(step int, state component.StepState, detail string) {
	*r = append(*r, fmt.Sprint(step, state, detail))
}

// TestDNSFailureIsTheEngines checks the Ubuntu host's failure sequence
// against the real engine on the fake host, whose systemd-resolved reloads
// with no effect: through output.FlowEngine, as the flow will apply it,
// the change fails with DNS_NOT_EFFECTIVE, dns.Apply puts the drop-in
// back, and the engine reports nothing rolled back (gallery-dns.md records
// it for unit (b)); the mock's fixture reports the same steps and fails
// with the same report. The proposed sequence, failure-proposed, reports
// the same steps, then the change rolled back, which dns.Apply did, with
// the same log.
func TestDNSFailureIsTheEngines(t *testing.T) {
	ctx := context.Background()
	h := newDNSFake(t, "ubuntu2604")
	p, err := dns.PlanDNS(h.read(t), dns.Config{Nameservers: dnsConfigured})
	if err != nil {
		t.Fatal(err)
	}
	ch, err := steps.DNS("dns", p, "Set the nameservers")
	if err != nil {
		t.Fatal(err)
	}
	a := &output.FlowEngine{Controls: []engine.Control{dnsControl{ch}}, LogPath: output.LegacyLogPath}
	a.Engine = engine.New(h.sys, engine.Options{
		Revert:   revert.Options{Now: func() time.Time { return time.Date(2026, 10, 21, 12, 0, 0, 0, time.UTC) }, Hardn: "/usr/local/bin/hardn"},
		Detect:   func(context.Context, host.System) (detect.Facts, error) { return h.facts, nil },
		Hold:     func() func() { return func() {} },
		PID:      5000,
		Backups:  backup.Settings{Path: backup.DefaultPath, Enabled: true},
		Progress: a.Progress,
	})
	if _, err := a.Plan(ctx); err != nil {
		t.Fatal(err)
	}
	var real reports
	realErr := a.Apply(ctx, real.report)
	var rf *flow.Failure
	if !errors.As(realErr, &rf) || !errors.Is(realErr, dns.ErrNotEffective) {
		t.Fatalf("the engine: %v; want a flow failure, DNS_NOT_EFFECTIVE", realErr)
	}
	apply := func(sequence string) (reports, *flow.Failure) {
		f := collected(t, sequenceNamed(t, dnsMock(t, "workflow-step/dns-configure-dns-ubuntu2604"), sequence))
		if _, err := f.Engine.Plan(ctx); err != nil {
			t.Fatal(err)
		}
		var mock reports
		var mf *flow.Failure
		if err := f.Engine.Apply(ctx, mock.report); !errors.As(err, &mf) {
			t.Fatalf("%s: the mock: %v; want a flow failure", sequence, err)
		}
		return mock, mf
	}
	mock, mf := apply("failure")
	if rf.Error() != mf.Error() || rf.Command != mf.Command || rf.Output != mf.Output || rf.LogPath != mf.LogPath || rf.Next != mf.Next {
		t.Errorf("the mock fails with\n%+v\nthe engine with\n%+v", *mf, *rf)
	}
	// The mock reports running, then failed: the engine's running comes
	// from the change's start.
	if !slices.Equal(real, mock) {
		t.Errorf("the mock reports %q, the engine %q", mock, real)
	}
	proposed, pf := apply("failure-proposed")
	if want := append(slices.Clone(real), fmt.Sprint(0, component.StepRolledBack, "")); !slices.Equal(proposed, want) || pf.LogPath != rf.LogPath {
		t.Errorf("the proposed sequence reports %q, logged at %s; want %q, logged at %s", proposed, pf.LogPath, want, rf.LogPath)
	}
	if _, err := h.sys.Lstat(ctx, dns.DropIn); !errors.Is(err, fs.ErrNotExist) {
		t.Errorf("the drop-in is left after the failure: %v", err)
	}
}
