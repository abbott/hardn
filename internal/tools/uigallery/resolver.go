// The simulated hosts' resolvers (refactor plan slice 2,
// next/s2-engine-gallery): what manages /etc/resolv.conf on each platform
// as the release installs it, and a model of systemd-resolved that answers
// systemctl and resolvectl as pkg/host/dns asks them, so that the DNS
// control plans from what dns.Read reads on the simulated host. Ported
// from pkg/host/dns's test model (helpers_test.go: world, answer, load),
// which a main package cannot share, and extending it: loadResolved skips
// hidden drop-ins and reads a link to /dev/null as a mask, where load
// takes every *.conf and reads a mask as an empty file. Written from
// docs/safety/dns.md §3, not captured from a host. Synthetic
// values only: eth0's lease from the DHCP server 192.0.2.1, the search
// domain example.net, hardn.yml listing 192.0.2.54 and 2001:db8::54.

// resolverKind is what manages /etc/resolv.conf as a release installs it
// (dns.md §3, its first row).
type resolverKind uint8

const (
	// resolverDHCPCD is a file dhcpcd wrote from eth0's lease, dhcpcd
	// installed (Debian 13, ifupdown's dhcpcd-base).
	resolverDHCPCD resolverKind = iota + 1
	// resolverStub is the link to systemd-resolved's stub file (Ubuntu).
	resolverStub
	// resolverUplink is the link to systemd-resolved's uplink file
	// (Debian 12's cloud image).
	resolverUplink
	// resolverUDHCPC is a file udhcpc wrote from eth0's lease, and Alpine's
	// stock udhcpc.conf, every line commented out; no hook.
	resolverUDHCPC
	// resolverStatic is the installer's static file (Proxmox VE).
	resolverStatic
)

// The resolver model's paths and values.
const (
	resolvedConf = "/etc/systemd/resolved.conf"
	dhcpServer   = "192.0.2.1"
	searchDomain = "example.net"
	// udhcpcStock is Alpine's udhcpc.conf as installed.
	udhcpcStock = "# Do not overwrite /etc/resolv.conf\n#RESOLV_CONF=\"no\"\n\n#NO_DNS=\"eth1 wlan1\"\n"
)

// dnsList is hardn.yml's nameservers on the DNS hosts.
var dnsList = []string{"192.0.2.54", "2001:db8::54"}

// resolved is systemd-resolved on a simulated host: whether it runs, the
// global lists it loaded from its files, and each link's, from DHCP.
type resolved struct {
	active          bool
	global, domains []string
	// links are the links' servers and search domains, and the delegates'
	// (Index 0), as resolvectl lists them.
	links []dns.Link
	// reload: the release's unit reloads its files (systemd 256 and later,
	// Type=notify-reload); before, try-reload-or-restart restarts it.
	reload bool
	// inert is how many try-reload-or-restart calls to answer with exit 0
	// having read nothing, so that the change has no effect, as dns.md §4
	// would make one on a host (a DNS= line resolved rejects, which it
	// only logs).
	inert int
	// reloads and restarts count how often it read its files each way.
	reloads, restarts int
}

// addResolver adds what manages /etc/resolv.conf on the platform, as the
// release installs it, with eth0's lease: a file naming the DHCP server
// and the search domain, or systemd-resolved's link, running, with the
// stock resolved.conf, which sets no global list, and eth0's server and
// domain on the link. resolved's stub and uplink files are not added:
// dns.Read reads the link, never what it points to.
func (h *fakeHost) addResolver() {
	f := h.f
	file := func(s string) { f.AddFile(dns.ResolvConf, []byte(s), 0o644, 0, 0) }
	lease := "search " + searchDomain + "\nnameserver " + dhcpServer + "\n"
	switch h.resolver {
	case resolverDHCPCD:
		file("# Generated by dhcpcd from eth0.dhcp\n" + lease)
		f.AddFile("/usr/sbin/dhcpcd", []byte("ELF"), 0o755, 0, 0)
	case resolverUDHCPC:
		file(lease)
		f.AddFile(dns.UDHCPCConf, []byte(udhcpcStock), 0o644, 0, 0)
	case resolverStatic:
		file(lease)
	case resolverStub, resolverUplink:
		link := "../run/systemd/resolve/stub-resolv.conf"
		if h.resolver == resolverUplink {
			link = "/run/systemd/resolve/resolv.conf"
		}
		f.AddSymlink(dns.ResolvConf, link)
		f.AddFile(resolvedConf, []byte("[Resolve]\n#DNS=\n#Domains=\n"), 0o644, 0, 0)
		h.resolved = &resolved{active: true, reload: h.resolvedReload,
			links: []dns.Link{{Index: 2, Name: "eth0", Servers: []string{dhcpServer}, Domains: []string{searchDomain}}}}
	}
}

// nameserversYML is hardn.yml's settings on the DNS hosts, as the DNS
// control's tests write them: alice, and list as the nameservers.
func nameserversYML(list []string) string {
	if len(list) == 0 {
		return "username: alice\nnameservers: []\n"
	}
	var b strings.Builder
	b.WriteString("username: alice\nnameservers:\n")
	for _, ns := range list {
		b.WriteString("  - \"" + ns + "\"\n")
	}
	return b.String()
}

// loadResolved is systemd-resolved reading its files (dns.md §3): the main
// resolved.conf, then each drop-in by name in C byte order across the four
// directories (dns.DropInDirs), a name in an earlier directory hiding it
// in the later ones, a link to /dev/null there masking it, hidden names
// skipped. The DNS= and Domains= lists collect, and an empty assignment
// resets one; a key and its value are stripped of blanks, and a line
// starting with # or ; is a comment. A continued line is not modelled.
func (h *fakeHost) loadResolved() {
	ctx := context.Background()
	byName := map[string]string{}
	for _, dir := range slices.Backward(dns.DropInDirs()) {
		des, _ := h.f.ReadDir(ctx, dir)
		for _, de := range des {
			if n := de.Name(); strings.HasSuffix(n, ".conf") && !strings.HasPrefix(n, ".") {
				byName[n] = dir + "/" + n // the first directory, read last, wins
			}
		}
	}
	files := []string{resolvedConf}
	for _, n := range slices.Sorted(maps.Keys(byName)) {
		files = append(files, byName[n])
	}
	r := h.resolved
	r.global, r.domains = nil, nil
	for _, name := range files {
		e, ok := h.f.Entry(name)
		if ok && e.Mode&fs.ModeSymlink != 0 {
			if e.Target == "/dev/null" {
				continue // masked
			}
			data, err := h.f.ReadFile(ctx, name)
			e.Data, ok = data, err == nil
		}
		if !ok {
			continue
		}
		for _, l := range strings.Split(string(e.Data), "\n") {
			k, v, ok := strings.Cut(strings.TrimSpace(l), "=")
			list := map[string]*[]string{"DNS": &r.global, "Domains": &r.domains}[strings.TrimSpace(k)]
			if !ok || list == nil {
				continue
			}
			if v = strings.TrimSpace(v); v == "" {
				*list = nil
			}
			*list = append(*list, strings.Fields(v)...)
		}
	}
}

// resolvedCommand answers systemctl's and resolvectl's commands about
// systemd-resolved, and reports whether it did: is-active, as for a unit
// not installed where none runs; try-reload-or-restart, which reloads or
// restarts it, as its release does (resolved.reload), and does nothing
// while it does not run; reload-or-restart, the undo's, which starts it
// too; and resolvectl's dns and domain lists.
func (h *fakeHost) resolvedCommand(argv []string) (hostfake.Response, bool) {
	r := h.resolved
	switch cmd := strings.Join(argv, " "); {
	case cmd == "systemctl is-active "+dns.ResolvedUnit:
		if r != nil && r.active {
			return hostfake.Response{Stdout: "active\n"}, true
		}
		return hostfake.Response{Stdout: "inactive\n", ExitCode: 3}, true
	case r == nil:
	case cmd == "systemctl try-reload-or-restart "+dns.ResolvedUnit:
		if r.inert > 0 && r.active {
			r.inert--
			return hostfake.Response{}, true
		}
		h.readResolved(false)
		return hostfake.Response{}, true
	case cmd == "systemctl reload-or-restart "+dns.ResolvedUnit:
		h.readResolved(true)
		return hostfake.Response{}, true
	case cmd == "resolvectl --no-pager dns", cmd == "resolvectl --no-pager domain":
		if !r.active {
			return hostfake.Response{Stderr: "Failed to get global data: Unit dbus-org.freedesktop.resolve1.service not found.\n", ExitCode: 1}, true
		}
		return hostfake.Response{Stdout: r.list(argv[2] == "domain")}, true
	}
	return hostfake.Response{}, false
}

// readResolved makes systemd-resolved read its files: by a reload where its
// release has one and it runs, else by a (re)start; with start false, as
// try-reload-or-restart, nothing while it does not run.
func (h *fakeHost) readResolved(start bool) {
	r := h.resolved
	switch {
	case !r.active && !start:
		return
	case r.active && r.reload:
		r.reloads++
	default:
		r.restarts++
	}
	r.active = true
	h.loadResolved()
}

// list is resolvectl's dns, or with domains its domain, output, in its
// form (resolvectl.c, status_print_strv_ifindex): the global list, then a
// line per delegate ("Delegate <id>:", systemd 259) and per link ("Link
// <index> (<name>):"), each with what it holds.
func (r *resolved) list(domains bool) string {
	words := func(l []string) string {
		if len(l) == 0 {
			return ""
		}
		return " " + strings.Join(l, " ")
	}
	global := r.global
	if domains {
		global = r.domains
	}
	out := "Global:" + words(global) + "\n"
	for _, delegates := range []bool{true, false} {
		for _, l := range r.links {
			if (l.Index == 0) != delegates {
				continue
			}
			held := l.Servers
			if domains {
				held = l.Domains
			}
			head := "Link " + strconv.Itoa(l.Index) + " (" + l.Name + "):"
			if delegates {
				head = "Delegate " + l.Name + ":"
			}
			out += head + words(held) + "\n"
		}
	}
	return out
}

// dnsHost returns the builder of a host of platform p whose hardn.yml
// lists dnsList.
func dnsHost(p platform) func() *fakeHost {
	return func() *fakeHost { return simulate(p).withHardnYML(nameserversYML(dnsList)) }
}

// networkManagerHost is Debian 13 with NetworkManager, which links
// /etc/resolv.conf to its own file.
func networkManagerHost() *fakeHost {
	h := dnsHost(debian13Platform)()
	h.f.AddSymlink(dns.ResolvConf, "/run/NetworkManager/resolv.conf")
	return h
}

// noListHost is Debian 13 whose hardn.yml lists no nameserver.
func noListHost() *fakeHost { return simulate(debian13Platform).withHardnYML(nameserversYML(nil)) }

// configuredDNSHost is Debian 13 whose /etc/resolv.conf lists hardn.yml's
// nameservers already, as Configure DNS leaves it.
func configuredDNSHost() *fakeHost {
	h := dnsHost(debian13Platform)()
	h.f.AddFile(dns.ResolvConf, []byte("# Generated by dhcpcd from eth0.dhcp\nsearch "+searchDomain+"\nnameserver 192.0.2.54\nnameserver 2001:db8::54\n"), 0o644, 0, 0)
	return h
}

// inertReload is Ubuntu 26.04 whose systemd-resolved's next reload loads
// nothing new.
func inertReload() *fakeHost {
	h := dnsHost(ubuntu2604Platform)()
	h.resolved.inert = 1
	return h
}

// immutableHardnYML is Debian 13 whose hardn.yml is immutable, so that
// saving it fails.
func immutableHardnYML() *fakeHost {
	h := dnsHost(debian13Platform)()
	h.immutable = []string{hardnYML}
	return h
}
