// findRAHost returns the host named name, after raPrefix.
func findRAHost(name string) (raHost, bool) {
	all := raHosts()
	i := slices.IndexFunc(all, func(h raHost) bool { return h.name == name })
	if i < 0 {
		return raHost{}, false
	}
	return all[i], true
}

