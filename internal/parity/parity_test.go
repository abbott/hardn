// TestReadRepository: the repository's layout read, $TMP as the root: the
// V-number of the KNOWN-DEFECT line alone, Start, the repository's calls
// under the backup path in order (a write's content skipped), then the
// screen's own write test on its second draw, marked, After, the temp dir,
// ./hardn.yml whole with its paths absolute and its mode not recorded,
// made in memory; a call that failed is the run's refusal, and adds
// nothing under the backup path; a draw whose write test wrote nothing
// adds nothing; the pairs of paths taken in order, $TMP/home as $HOME
// before $TMP as the root.
func TestReadRepository(t *testing.T) {
	root := []string{"$TMP", ""}
	r, err := parseLegacy([]byte(repoGolden), "menu/example.golden", reader{paths: root})
	if err != nil {
		t.Fatal(err)
	}
	l := r.Live
	if !slices.Equal(r.Vs, []string{"V18"}) || r.Start != "enableBackups false, backupPath /var/backups/example (nothing there), dryRun false" ||
		r.Tree != "hardn.yml var/ var/backups/ var/backups/example/" {
		t.Errorf("V-numbers %q, start %q, tree %q", r.Vs, r.Start, r.Tree)
	}
	if want := []string{"mkdir /var/backups/example 0755", "write /var/backups/example/.write_test 0644", "remove /var/backups/example/.write_test",
		"write /var/backups/example/.write_test 0644 (screen)", "remove /var/backups/example/.write_test (screen)"}; !slices.Equal(l.Under, want) {
		t.Errorf("under %q, want %q", l.Under, want)
	}
	if l.After != "/var/backups/example: a directory, empty" || l.Refusal != "" || !l.Memory || len(l.Files) > 0 {
		t.Errorf("after %q, refusal %q, memory %t, files %v", l.After, l.Refusal, l.Memory, l.Files)
	}
	if y := l.YML; y == nil || y.Path != "./hardn.yml" || !y.NoMode || y.String() != "./hardn.yml (mode not recorded)" || y.Atomic ||
		!slices.Equal(y.Lines, []string{"username: alice", "enableBackups: true", "backupPath: /var/backups/example"}) {
		t.Errorf("hardn.yml %+v", y)
	}
	failed := strings.Replace(strings.Replace(repoGolden, "  1 mkdir  $TMP/var/backups/example mode=0755 -> ok\n  2 write  $TMP/var/backups/example/.write_test mode=0644 -> ok\n        | test\n        \\ no newline at end of content\n  3 remove $TMP/var/backups/example/.write_test -> ok\n",
		"  1 mkdir  $TMP/var/backups/example mode=0755 -> error: mkdir $TMP/var/backups/example: not a directory\n", 1),
		"exists and is writable$\n 3)", "doesn't exist or isn't writable$\n 3)", 1)
	r, err = parseLegacy([]byte(failed), "menu/example.golden", reader{paths: root})
	if err != nil || r.Live.Refusal != "failed: mkdir /var/backups/example: not a directory" || len(r.Live.Under) != 0 {
		t.Errorf("a call that failed: %v, refusal %q, under %q", err, r.Live.Refusal, r.Live.Under)
	}
	home := strings.ReplaceAll(repoGolden, "$TMP/var/backups/example", "$TMP/home/alice/backups")
	r, err = parseLegacy([]byte(home), "menu/example.golden", reader{paths: []string{"$TMP/home", "$HOME", "$TMP", ""}})
	if err != nil {
		t.Fatal(err)
	}
	if r.Live.Under[0] != "mkdir $HOME/alice/backups 0755" || r.Live.YML.Lines[2] != "backupPath: $HOME/alice/backups" {
		t.Errorf("$TMP/home as $HOME: under %q, hardn.yml %q", r.Live.Under, r.Live.YML.Lines)
	}
}

