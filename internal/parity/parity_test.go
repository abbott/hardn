// TestNewState: the new path's end state from the fake's calls after the
// nth: the host's files as they are now, in the order first written, the
// directories, the commands apart from those that only read, hardn.yml
// apart, the journal and the backups from the run's manifest; the
// engine's run directory left out.
func TestNewState(t *testing.T) {
	ctx := context.Background()
	h := hostfake.New(host.Options{})
	for _, d := range []string{"/etc", "/etc/hardn", "/run", "/var/lib", "/var/lib/hardn", "/var/backups"} {
		h.AddDir(d, 0o755, 0, 0)
	}
	h.AddFile("/etc/hardn/hardn.yml", []byte("username: alice\n"), 0o600, 0, 0)
	h.Handler = func([]string, []byte) hostfake.Response { return hostfake.Response{} }
	n := len(h.Calls())
	const run = backup.DefaultPath + "/20261027T120000Z-0a1b2c3d"
	manifest := `{"entries": [{"path": "/etc/example.conf", "kind": "file"}, {"path": "/etc/new.conf", "kind": "absent"}]}`
	for _, step := range []func() error{
		func() error { return h.MkdirAll(ctx, "/run/hardn/x", 0o700) },
		func() error { return h.WriteFileAtomic(ctx, "/var/lib/hardn/journal.json", []byte("{}"), 0o600, 0, 0) },
		func() error { return h.MkdirAll(ctx, run, 0o700) },
		func() error { return h.WriteFileAtomic(ctx, run+"/manifest.json", []byte(manifest), 0o600, 0, 0) },
		func() error { return h.WriteFileAtomic(ctx, "/etc/example.conf", []byte("a\nb\n"), 0o644, 0, 0) },
		func() error { return h.MkdirAll(ctx, "/etc/example.d", 0o755) },
		func() error { return h.WriteFileInPlace(ctx, "/etc/hardn/hardn.yml", []byte("username: bob\n"), 0o600) },
		func() error { _, err := h.Run(ctx, "systemctl", "is-active", "example"); return err },
		func() error { _, err := h.Run(ctx, "systemctl", "reload", "example"); return err },
		func() error { return h.WriteFileAtomic(ctx, "/etc/example.conf", []byte("a\nc\n"), 0o644, 0, 0) },
	} {
		if err := step(); err != nil {
			t.Fatal(err)
		}
	}
	s := NewState(t, h, n, []string{"systemctl is-active example"}, "/etc/hardn/hardn.yml")
	if len(s.Files) != 1 || s.Files[0].String() != "/etc/example.conf 0644" || !s.Files[0].Atomic || !slices.Equal(s.Files[0].Lines, []string{"a", "c"}) {
		t.Errorf("files %+v", s.Files)
	}
	if s.YML == nil || s.YML.Atomic || !slices.Equal(s.YML.Lines, []string{"username: bob"}) {
		t.Errorf("hardn.yml %+v", s.YML)
	}
	if !slices.Equal(s.Dirs, []string{"/etc/example.d 0755"}) || !slices.Equal(s.Actions, []string{"systemctl reload example"}) ||
		!slices.Equal(s.Probes, []string{"systemctl is-active example"}) {
		t.Errorf("dirs %q, actions %q, probes %q", s.Dirs, s.Actions, s.Probes)
	}
	if want := []string{"/etc/example.conf", "/etc/new.conf (absent before: the rollback removes it)"}; !s.Journal || !slices.Equal(s.Backups, want) {
		t.Errorf("journal %t, backups %q; want journalled, %q", s.Journal, s.Backups, want)
	}
	if got := HostText(s); !strings.Contains(got, "/etc/example.conf 0644\na\nc\n") || !strings.Contains(got, "/etc/hardn/hardn.yml 0600\nusername: bob\n") {
		t.Errorf("HostText:\n%s", got)
	}
	if s.Under != nil {
		t.Errorf("NewState recorded under the backup path: %q", s.Under)
	}
}

// TestNewStateUnder: with the backup path given, what was written under
// it is recorded in order, each run's directory as <run id>, reads left
// out; the backups are still read from the run's manifest, one taken
// with backups off said so; a run that wrote nothing there has an empty
// record, not none.
func TestNewStateUnder(t *testing.T) {
	ctx := context.Background()
	h := hostfake.New(host.Options{})
	for _, d := range []string{"/etc", "/etc/hardn", "/var/backups"} {
		h.AddDir(d, 0o755, 0, 0)
	}
	n := len(h.Calls())
	if s := NewStateUnder(t, h, n, nil, "/etc/hardn/hardn.yml", backup.DefaultPath); s.Under == nil || len(s.Under) != 0 {
		t.Errorf("nothing written: under %#v, want empty", s.Under)
	}
	const run = backup.DefaultPath + "/20261027T120000Z-0a1b2c3d"
	manifest := `{"entries": [{"path": "/etc/hardn/hardn.yml", "kind": "file", "takenAnyway": true}]}`
	for _, step := range []func() error{
		func() error { return h.MkdirAll(ctx, backup.DefaultPath, 0o700) },
		func() error { _, err := h.Lstat(ctx, backup.DefaultPath); return err },
		func() error { return h.MkdirAll(ctx, run, 0o700) },
		func() error { return h.WriteFileAtomic(ctx, run+"/0001-hardn.yml", []byte("x\n"), 0o600, 0, 0) },
		func() error { return h.WriteFileAtomic(ctx, run+"/manifest.json", []byte(manifest), 0o600, 0, 0) },
	} {
		if err := step(); err != nil {
			t.Fatal(err)
		}
	}
	s := NewStateUnder(t, h, n, nil, "/etc/hardn/hardn.yml", backup.DefaultPath)
	want := []string{"mkdir /var/backups/hardn 0700", "mkdir /var/backups/hardn/<run id> 0700",
		"write /var/backups/hardn/<run id>/0001-hardn.yml 0600", "write /var/backups/hardn/<run id>/manifest.json 0600"}
	if !slices.Equal(s.Under, want) || len(s.Dirs) != 0 || s.Wrote() {
		t.Errorf("under %q, dirs %q, wrote %t; want %q under it alone", s.Under, s.Dirs, s.Wrote(), want)
	}
	if want := []string{"/etc/hardn/hardn.yml (taken anyway: backups off)"}; !slices.Equal(s.Backups, want) {
		t.Errorf("backups %q, want %q", s.Backups, want)
	}
}

// TestCompareUnder: with UnderBackupPath, what each path made and wrote
// under the backup path and what is there after are aspects of their
// own, and a scenario's setting is compared apart from the others; a save
// whole of a configuration made in memory drops no comment.
func TestCompareUnder(t *testing.T) {
	loaded := []string{"# a comment", "enableBackups: true", "backupPath: /var/backups/example"}
	l := EndState{Memory: true, Loaded: loaded, Under: []string{"mkdir /var/backups/example 0755", "write /var/backups/example/.write_test 0644"},
		After: "/var/backups/example: a directory, empty",
		YML:   &FileWrite{Path: "./hardn.yml", Mode: 0o644, Lines: []string{"enableBackups: false", "backupPath: /var/backups/example"}}}
	n := EndState{Loaded: loaded, Under: []string{}, After: "/var/backups/example: a directory, empty",
		YML: &FileWrite{Path: "/etc/hardn/hardn.yml", Mode: 0o644, Atomic: true, Lines: []string{"# a comment", "enableBackups: false", "backupPath: /var/backups/example"}}}
	diffs, agree := compare(t, Slice{UnderBackupPath: true}, "enableBackups", l, n)
	got := map[string]string{}
	for _, a := range append(diffs, agree...) {
		got[a.Name] = a.Legacy + " | " + a.New
	}
	for name, want := range map[string]string{
		"backupPath dirs":         "/var/backups/example 0755 | none",
		"backupPath files":        "write /var/backups/example/.write_test 0644 | none",
		"backupPath after":        "/var/backups/example: a directory, empty | /var/backups/example: a directory, empty",
		"hardn.yml enableBackups": "false | false",
		"hardn.yml settings":      "as loaded | as loaded",
		"hardn.yml rest":          "2 settings, written whole; no file was loaded | the enableBackups lines alone changed; the file's other 2 lines kept (2 settings, 1 comment lines)",
	} {
		if got[name] != want {
			t.Errorf("%s: %q, want %q", name, got[name], want)
		}
	}
	if diffs, agree := compare(t, Slice{}, "enableBackups", l, n); slices.ContainsFunc(append(diffs, agree...), func(a aspect) bool { return strings.HasPrefix(a.Name, "backupPath") }) {
		t.Error("compared under the backup path without UnderBackupPath")
	}
}

