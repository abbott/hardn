// TestCompareUnder: with UnderBackupPath, what each path made and wrote
// under the backup path and what is there after are aspects of their
// own, and a scenario's setting is compared apart from the others; a save
// whole of a configuration made in memory drops no comment; hardn.yml's
// mode is compared only where both record it.
func TestCompareUnder(t *testing.T) {
	loaded := []string{"# a comment", "enableBackups: true", "backupPath: /var/backups/example"}
	l := EndState{Memory: true, Loaded: loaded, Under: []string{"mkdir /var/backups/example 0755", "write /var/backups/example/.write_test 0644"},
		After: "/var/backups/example: a directory, empty",
		YML:   &FileWrite{Path: "./hardn.yml", Mode: 0o644, Lines: []string{"enableBackups: false", "backupPath: /var/backups/example"}}}
	n := EndState{Loaded: loaded, Under: []string{}, After: "/var/backups/example: a directory, empty",
		YML: &FileWrite{Path: "/etc/hardn/hardn.yml", Mode: 0o644, Atomic: true, Lines: []string{"# a comment", "enableBackups: false", "backupPath: /var/backups/example"}}}
	diffs, agree := compare(t, Slice{UnderBackupPath: true}, "enableBackups", l, n)
	got := map[string]string{}
	for _, a := range append(diffs, agree...) {
		got[a.Name] = a.Legacy + " | " + a.New
	}
	for name, want := range map[string]string{
		"backupPath dirs":         "/var/backups/example 0755 | none",
		"backupPath files":        "write /var/backups/example/.write_test 0644 | none",
		"backupPath after":        "/var/backups/example: a directory, empty | /var/backups/example: a directory, empty",
		"hardn.yml enableBackups": "false | false",
		"hardn.yml settings":      "as loaded | as loaded",
		"hardn.yml rest":          "2 settings, written whole; no file was loaded | the enableBackups lines alone changed; the file's other 2 lines kept (2 settings, 1 comment lines)",
	} {
		if got[name] != want {
			t.Errorf("%s: %q, want %q", name, got[name], want)
		}
	}
	if diffs, agree := compare(t, Slice{}, "enableBackups", l, n); slices.ContainsFunc(append(diffs, agree...), func(a aspect) bool { return strings.HasPrefix(a.Name, "backupPath") }) {
		t.Error("compared under the backup path without UnderBackupPath")
	}
	if got["hardn.yml mode"] != "0644 | 0644" {
		t.Errorf("hardn.yml mode, both recorded: %q", got["hardn.yml mode"])
	}
	l.YML.NoMode = true
	if diffs, agree := compare(t, Slice{}, "enableBackups", l, n); slices.ContainsFunc(append(diffs, agree...), func(a aspect) bool { return a.Name == "hardn.yml mode" }) {
		t.Error("compared a mode origin/main's golden does not record")
	}
}

