// The hosts, as the gallery's Run All hosts (raHosts), each as its note
// there says; Auto Updates' model is not copied, so hardn.yml asks it
// nothing here but on Proxmox VE, where its check says Not Applicable
// before anything is read (the gallery holds it planned and refused).

// debianMain is the Debian 13 VM's sshd_config as sshd reads it.
const debianMain = sshd.IncludeLine + "\n\nKbdInteractiveAuthentication no\nPasswordAuthentication no\nUsePAM yes\n"

// yml is where a host keeps hardn.yml.
const yml = "/etc/hardn/hardn.yml"

// clock is the hosts' clock.
var clock = func() time.Time { return time.Date(2026, 11, 4, 12, 0, 0, 0, time.UTC) }

// nameservers are hardn.yml's, as the gallery's dnsList.
var nameservers = []string{"192.0.2.54", "2001:db8::54"}

// askYML is hardn.yml asking user with the key of seed, sshPort port, the
// two nameservers, backups on, and enableUfwSshPolicy, configureDns and
// disableRootSSH true; enableUnattendedUpgrades as updates says.
func askYML(user string, seed byte, port int, updates bool) string {
	return "username: " + user + "\nsshKeys:\n  - \"" + synthKey(seed, user+"@laptop-1") + "\"\n" +
		fmt.Sprintf("sshPort: %d\n", port) +
		"nameservers:\n  - \"" + nameservers[0] + "\"\n  - \"" + nameservers[1] + "\"\n" +
		"enableBackups: true\nbackupPath: /var/backups/hardn\n" +
		fmt.Sprintf("enableUnattendedUpgrades: %v\n", updates) +
		"enableUfwSshPolicy: true\nconfigureDns: true\ndisableRootSSH: true\n"
}

// defaultYML is hardn.yml as origin/main's SaveConfig writes it with no
// answer given: it asks Run All for nothing.
const defaultYML = "username: \"\"\nsshKeys: []\nsshPort: 22\nnameservers: []\nenableBackups: true\nbackupPath: /var/backups/hardn\n" +
	"enableUnattendedUpgrades: false\nenableUfwSshPolicy: false\nconfigureDns: false\ndisableRootSSH: false\n"

// runHost is a host with its hardn.yml as loaded.
type runHost struct {
	*sshHost
	cfg *config.Config
}

// withYML writes data as hardn.yml on h, root's 0600, and loads it as hardn
// does.
func withYML(t *testing.T, h *sshHost, data string) *runHost {
	t.Helper()
	h.AddDir("/etc/hardn", 0o755, 0, 0)
	h.AddFile(yml, []byte(data), 0o600, 0, 0)
	cfg, err := config.Read(context.Background(), h, yml)
	if err != nil {
		t.Fatal(err)
	}
	return &runHost{sshHost: h, cfg: cfg}
}

// dhcpcd writes resolv.conf as dhcpcd leaves it on the Debian VM, listing
// list.
func dhcpcd(h *sshHost, list ...string) *sshHost {
	data := "# Generated by dhcpcd from eth0.dhcp\nsearch example.net\n"
	for _, ns := range list {
		data += "nameserver " + ns + "\n"
	}
	h.AddFile(hostdns.ResolvConf, []byte(data), 0o644, 0, 0)
	h.AddFile("/usr/sbin/dhcpcd", nil, 0o755, 0, 0)
	return h
}

// vm is the Debian 13 or Ubuntu 26.04 VM: george (two keys, "!", sudo by
// cloud-init), alice, root "*" with george's first key, ufw allowing 22,
// dhcpcd's resolv.conf; george's session through sudo.
func vm(p platform) *sshHost {
	h := usersOn(p, true, george(p), alice()).rootLike("*")
	h.env = map[string]string{"SUDO_USER": "george"}
	return dhcpcd(h.sshFile(sshd.MainConfig, debianMain, 0o644), "192.0.2.1")
}

// runHosts are the hosts, by name, in the gallery's order.
var runHosts = []string{"debian13", "ubuntu2604", "alpine323", "fresh", "hardened", "partial", "port", "pve9", "container",
	"nothing-asked", "refused", "pending", "ufw-inactive", "new-admin", "george-no-sudo", "carol-ufw-inactive"}

// newHost is the host name names, with its hardn.yml.
func newHost(t *testing.T, name string) *runHost {
	t.Helper()
	ask := askYML("george", 1, 22, false)
	switch name {
	case "debian13", "pending":
		h := withYML(t, vm(debian13()).withLog("publickey", "george", 1), ask)
		if name == "pending" {
			confirmWindow(t, h)
		}
		return h
	case "ubuntu2604":
		return withYML(t, vm(ubuntu2604()).sshFile(sshd.DropInDir+"/60-cloudimg-settings.conf", "PasswordAuthentication no\n", 0o644).withLog("publickey", "george", 1), ask)
	case "alpine323":
		p := alpine323()
		h := usersOn(p, true, simUser{name: "alpine", uid: 1000, groups: []string{"wheel"}, pw: "*", shell: "/bin/ash"}, george(p)).rootLike("!")
		h.env = map[string]string{"DOAS_USER": "george"}
		h.sshFile(sshd.MainConfig, sshd.IncludeLine+"\n\nUsePAM yes\nAuthorizedKeysFile .ssh/authorized_keys\nAllowTcpForwarding no\n", 0o644)
		h.sshFile(sshd.DropInDir+"/50-cloud-init.conf", "PasswordAuthentication no\n", 0o600)
		h.AddFile(hostdns.ResolvConf, []byte("search example.net\nnameserver 192.0.2.1\n"), 0o644, 0, 0)
		return withYML(t, h.withLog("publickey", "george", 1), ask)
	case "fresh":
		p := debian13()
		p.noUFW = true
		h := usersOn(p, false).rootLike(syntheticHash)
		h.env = nil
		return withYML(t, dhcpcd(h, "192.0.2.1").withLog("publickey", "root", 1), ask)
	case "hardened":
		h := vm(debian13()).sshFile(sshd.HardnDropIn, "Port 2230\nPermitRootLogin no\nPasswordAuthentication no\n", 0o644)
		h.rules, h.sess = []rule{{port: 2230}}, confirmSession
		h.saveRules()
		return withYML(t, dhcpcd(h, nameservers...).withLog("publickey", "george", 1), askYML("george", 1, 2230, false))
	case "partial":
		return withYML(t, dhcpcd(vm(debian13()), nameservers...).withLog("publickey", "george", 1), ask)
	case "port":
		return withYML(t, vm(debian13()).withLog("publickey", "george", 1), askYML("george", 1, 2230, false))
	case "pve9":
		h := usersOn(pve9(), false).rootLike("*")
		h.sshFile(sshd.MainConfig, sshd.IncludeLine+"\n\nUsePAM yes\nPermitRootLogin yes\n", 0o644) // as installed
		h.env = nil
		h.AddFile(hostdns.ResolvConf, []byte("search example.net\nnameserver 192.0.2.1\n"), 0o644, 0, 0)
		return withYML(t, h.withLog("publickey", "root", 1), askYML("george", 1, 22, true))
	case "container":
		h := vm(debian13()).withLog("publickey", "george", 1)
		h.plat.facts.Container = detect.Container{Detected: detect.Yes, Signal: "/proc/1/environ", Manager: "lxc"}
		return withYML(t, h, ask)
	case "refused":
		h := vm(debian13()).withLog("publickey", "george", 1)
		h.aptBroken = true
		return withYML(t, h, askYML("george", 1, 22, true))
	case "nothing-asked":
		return withYML(t, vm(debian13()).withLog("publickey", "george", 1), defaultYML)
	case "ufw-inactive":
		h := dhcpcd(vm(debian13()), nameservers...)
		h.inactive, h.rules = true, nil
		h.saveRules()
		return withYML(t, h.withLog("publickey", "george", 1), ask)
	case "new-admin":
		return withYML(t, dhcpcd(vm(debian13()), nameservers...).withLog("publickey", "george", 1), askYML("carol", 3, 22, false))
	case "carol-ufw-inactive":
		h := vm(debian13())
		h.inactive, h.rules = true, nil
		h.saveRules()
		return withYML(t, h.withLog("publickey", "george", 1), askYML("carol", 3, 22, false))
	case "george-no-sudo":
		g := george(debian13())
		g.groups = []string{"adm"}
		h := usersOn(debian13(), false, g, alice()).rootLike(syntheticHash)
		h.env = nil
		h.sshFile(sshd.MainConfig, debianMain, 0o644)
		return withYML(t, dhcpcd(h, "192.0.2.1").withLog("publickey", "george", 1), ask)
	}
	t.Fatalf("no host %q", name)
	return nil
}

// newEngine is the engine on h as cmd/hardn builds it: its clock, the
// facts, hardn.yml's backups, the host's session.
func (h *runHost) newEngine(progress func(engine.Event)) *engine.Engine {
	return engine.New(h, engine.Options{
		Revert:   revert.Options{Now: clock, Hardn: hardnBinary},
		Detect:   func(context.Context, host.System) (detect.Facts, error) { return h.facts(), nil },
		Hold:     func() func() { return func() {} },
		PID:      5000,
		Session:  h.sess,
		Backups:  backup.Settings{Path: h.cfg.BackupPath, Enabled: h.cfg.EnableBackups},
		Progress: progress,
	})
}

// input is Read's input on h, as the screen and -r give it.
func (h *runHost) input() runall.Input {
	return runall.Input{System: h, Facts: h.facts(), Config: h.cfg, Session: h.sess, Getenv: h.getenv,
		Revert: revert.Options{Now: clock, Hardn: hardnBinary}, Version: "v0.4.0", NewEngine: h.newEngine}
}

// read reads h for Run All, failing t on an error or a command the fake
// does not answer.
func (h *runHost) read(t *testing.T, name string) runall.Reading {
	t.Helper()
	r, err := runall.Read(context.Background(), h.input())
	if err != nil {
		t.Fatalf("%s: %v", name, err)
	}
	checkHost(t, name, h.sshHost)
	return r
}

// confirmWindow applies the port change to 2230 on h, not confirmed:
// hardn confirm pending, as the gallery's confirm-window.
func confirmWindow(t *testing.T, h *runHost) {
	t.Helper()
	ctx := context.Background()
	e := h.newEngine(nil)
	p, err := e.Plan(ctx, []engine.Control{sshchange.Port{To: 2230}}, &config.Config{})
	if err != nil || len(p.Refused) > 0 {
		t.Fatalf("confirm-window: plan: %v, refused %v", err, p.Refused)
	}
	if _, err := e.Apply(ctx, p); err != nil {
		t.Fatalf("confirm-window: apply: %v", err)
	}
}

// readOnlyRun reports whether argv only reads: sshd -T and -t, journalctl,
// ss, ufw status, the tools' checks, systemctl's questions and the package
// tools' (apt-config dump, dpkg-query, apk info).
func readOnlyRun(argv []string) bool {
	cmd := strings.Join(argv, " ")
	switch {
	case path.Base(argv[0]) == "sshd" && (slices.Contains(argv, "-T") || slices.Contains(argv, "-t")), argv[0] == "journalctl", argv[0] == "ss",
		cmd == "ufw status verbose", cmd == "visudo -c", strings.HasPrefix(cmd, "doas -C "), argv[0] == "dpkg-query",
		strings.HasPrefix(cmd, "apt-config dump "), strings.HasPrefix(cmd, "apk info "),
		strings.HasPrefix(cmd, "systemctl is-"), strings.HasPrefix(cmd, "systemctl show "), strings.HasPrefix(cmd, "systemd-analyze verify "):
		return true
	}
	return false
}

// writes are the calls on h, from the nth on, that could change the host
// outside /run/hardn, the engine's run directory: every call but a read or
// a lookup, every command but those that only read (readOnlyRun).
func writes(h *runHost, n int) []string {
	var out []string
	for _, c := range h.Calls()[n:] {
		switch c.Op {
		case "read", "read-nofollow", "stat", "lstat", "readdir", "readlink", "resolve-symlink", "lookup-user", "lookup-group":
		case "run", "start-detached":
			if !readOnlyRun(c.Argv) {
				out = append(out, strings.Join(c.Argv, " "))
			}
		default:
			if !strings.HasPrefix(c.Path, revert.DefaultRunDir+"/") && c.Path != revert.DefaultRunDir {
				out = append(out, c.Op+" "+c.Path)
			}
		}
	}
	return out
}
