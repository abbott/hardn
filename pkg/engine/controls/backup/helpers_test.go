// The hosts Backup's control reads and plans on, on hostfake, as the
// gallery's Backup mocks draw them (gallery-backup.md §3.1). Synthetic
// values only: web-01.example.net, alice, 192.0.2.0/24.

const (
	hostname    = "web-01.example.net"
	hardnYML    = "/etc/hardn/hardn.yml"
	hardnBinary = "/usr/local/bin/hardn"
	elsewhere   = "/srv/backups/hardn"
	unsafePath  = "/tmp/hardn-backups"
)

// now is the engine's clock and the reports'.
var now = time.Date(2026, 10, 27, 12, 0, 0, 0, time.UTC)

// debian13 are the facts of every host.
var debian13 = detect.Facts{Platform: detect.Platform{Distro: detect.DistroDebian, Version: "13", Support: detect.Supported},
	Init: detect.Init{Kind: detect.Systemd, Running: detect.Yes}, Container: detect.Container{Detected: detect.No}}

// yml is hardn.yml as hardn.yml.example writes the two keys, with a
// nameserver, under a comment.
func yml(enabled bool, path string) []byte {
	return []byte("# hardn's configuration (web-01.example.net)\nusername: alice\n" +
		"enableBackups: " + map[bool]string{true: "true", false: "false"}[enabled] + "               # Backup files before modifying them\n" +
		"backupPath: \"" + path + "\"  # Path to store backups\n" +
		"nameservers:\n  - \"192.0.2.54\"\n")
}

// newHost returns a Debian 13 host whose hardn.yml has backups as enabled
// and path say, with /var/backups (root's, 0755), /srv/backups/hardn
// (root's, 0700), /tmp (sticky, anyone can write), and /etc/resolv.conf,
// a plain file dhcpcd wrote; and hardn.yml as loaded.
func newHost(t *testing.T, enabled bool, path string) (*hostfake.System, *config.Config) {
	t.Helper()
	h := hostfake.New(host.Options{})
	for _, d := range []string{"/etc", "/etc/hardn", "/var/lib", "/var/backups", "/run", "/var/log", "/srv", "/srv/backups"} {
		h.AddDir(d, 0o755, 0, 0)
	}
	h.AddDir(elsewhere, 0o700, 0, 0)
	h.AddDir("/tmp", fs.ModeSticky|0o777, 0, 0)
	h.AddFile("/etc/os-release", []byte("ID=debian\nVERSION_ID=\"13\"\n"), 0o644, 0, 0)
	h.AddFile("/etc/resolv.conf", []byte("# Generated by dhcpcd from eth0.dhcp\nnameserver 192.0.2.1\n"), 0o644, 0, 0)
	h.AddFile(hardnYML, yml(enabled, path), 0o600, 0, 0)
	h.Handler = func(argv []string, _ []byte) hostfake.Response {
		if strings.Join(argv, " ") == "systemctl is-active systemd-resolved.service" {
			return hostfake.Response{Stdout: "inactive\n", ExitCode: 3}
		}
		return hostfake.Response{Err: hostfake.ErrUnscripted}
	}
	cfg, err := config.Read(context.Background(), h, hardnYML)
	if err != nil {
		t.Fatal(err)
	}
	return h, cfg
}

// edited is a copy of cfg changed by edit, as a screen's change edits it.
func edited(cfg *config.Config, edit func(c *config.Config)) *config.Config {
	c := *cfg
	edit(&c)
	return &c
}

// engineOn is the engine on h as cmd/hardn builds it: its backups as
// hardn.yml was loaded (loaded), its clock, facts and hold, and the
// apply's progress to events when set.
func engineOn(h host.System, loaded hostbackup.Settings, events *[]engine.Event) *engine.Engine {
	return engine.New(h, engine.Options{
		Revert:  revert.Options{Now: func() time.Time { return now }, Hardn: hardnBinary},
		Detect:  func(context.Context, host.System) (detect.Facts, error) { return debian13, nil },
		Hold:    func() func() { return func() {} },
		PID:     5000,
		Backups: loaded,
		Progress: func(ev engine.Event) {
			if events != nil {
				*events = append(*events, ev)
			}
		},
	})
}

// writesAfter are the calls after the first n that changed something
// outside /run/hardn.
func writesAfter(h *hostfake.System, n int) []string {
	var out []string
	for _, c := range h.Calls()[n:] {
		switch c.Op {
		case "write-atomic", "write-in-place", "remove", "removeall", "rename", "mkdir", "chmod", "chown", "append":
			if !strings.HasPrefix(c.Path, "/run/hardn") {
				out = append(out, c.Op+" "+c.Path)
			}
		}
	}
	return out
}

// content is name's content on h, or "<absent>".
func content(h *hostfake.System, name string) string {
	e, ok := h.Entry(name)
	if !ok {
		return "<absent>"
	}
	return string(e.Data)
}
