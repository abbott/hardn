// readOnly fails on any call Read must not make: a write, or a command
// other than its three queries.
func readOnly(t *testing.T, h *hostfake.System) {
	t.Helper()
	for _, c := range h.Calls() {
		switch c.Op {
		case "read", "read-nofollow", "stat", "lstat", "readdir", "readlink":
		case "run":
			if a := strings.Join(c.Argv, " "); a != "systemctl is-active "+dns.ResolvedUnit && a != "resolvectl --no-pager dns" {
				t.Errorf("Read ran %q", a)
			}
		default:
			t.Errorf("Read made %s", c)
		}
	}
}

// TestRead: each supported platform's stock layout gives its manager and
// what it holds, from reads and two queries only.
func TestRead(t *testing.T) {
	tests := []struct {
		fixture  string
		manager  dns.Manager
		ns       []string
		search   []string
		global   []string
		rewrites detect.Tri
		dhcp     []string
	}{
		{"ubuntu-26.04", dns.ManagerResolved, nil, nil, []string{"192.0.2.99"}, detect.Unknown, nil},
		{"debian-12-cloud", dns.ManagerResolved, nil, nil, []string{"192.0.2.99"}, detect.Unknown, nil},
		{"debian-13", dns.ManagerFile, []string{dhcpNS}, []string{"example.net"}, nil, detect.Unknown, []string{"/usr/sbin/dhcpcd"}},
		{"alpine-3.24", dns.ManagerFile, []string{dhcpNS}, []string{"example.net"}, nil, detect.Yes, nil},
		{"proxmox", dns.ManagerProxmox, []string{dhcpNS}, []string{"example.net"}, nil, detect.Unknown, nil},
	}
	for _, tt := range tests {
		t.Run(tt.fixture, func(t *testing.T) {
			w := newWorld(t, tt.fixture)
			s := w.read(t)
			if s.Err != nil || s.Manager != tt.manager {
				t.Fatalf("manager %s, err %v", s.Manager, s.Err)
			}
			if !slices.Equal(s.Nameservers, tt.ns) || !slices.Equal(s.Search, tt.search) || !slices.Equal(s.Resolved.Global, tt.global) {
				t.Errorf("got %q %q %q", s.Nameservers, s.Search, s.Resolved.Global)
			}
			if s.UDHCPC.Rewrites != tt.rewrites || !slices.Equal(s.DHCPClients, tt.dhcp) {
				t.Errorf("udhcpc %s, dhcp %q", s.UDHCPC.Rewrites, s.DHCPClients)
			}
			readOnly(t, w.h)
		})
	}
}

// TestReadManagers: /etc/resolv.conf's link target or first line names its
// manager; a file a running systemd-resolved reads is another package's;
// what cannot be told is Unknown.
func TestReadManagers(t *testing.T) {
	tests := []struct {
		name    string
		seed    func(w *world)
		manager dns.Manager
		err     bool
	}{
		{"resolvconf link", func(w *world) { w.h.AddSymlink(dns.ResolvConf, "../run/resolvconf/resolv.conf") }, dns.ManagerResolvconf, false},
		{"NetworkManager link", func(w *world) { w.h.AddSymlink(dns.ResolvConf, "/run/NetworkManager/resolv.conf") }, dns.ManagerNetworkManager, false},
		{"unknown link", func(w *world) { w.h.AddSymlink(dns.ResolvConf, "/etc/resolv.conf.local") }, dns.ManagerForeign, false},
		{"NetworkManager file", func(w *world) {
			w.h.AddFile(dns.ResolvConf, []byte("# Generated by NetworkManager\nnameserver 192.0.2.1\n"), 0o644, 0, 0)
		}, dns.ManagerNetworkManager, false},
		{"openresolv file", func(w *world) {
			w.h.AddFile(dns.ResolvConf, []byte("# Generated by resolvconf\nnameserver 192.0.2.1\n"), 0o644, 0, 0)
		}, dns.ManagerResolvconf, false},
		{"file read by a running resolved", func(w *world) { w.active = "active" }, dns.ManagerForeign, false},
		{"absent", func(w *world) { _ = w.h.RemoveAll(context.Background(), dns.ResolvConf) }, dns.ManagerFile, false},
		{"directory", func(w *world) {
			_ = w.h.RemoveAll(context.Background(), dns.ResolvConf)
			w.h.AddDir(dns.ResolvConf, 0o755, 0, 0)
		}, dns.ManagerUnknown, true},
		{"resolved link, resolved stopped", func(w *world) {
			w.h.AddSymlink(dns.ResolvConf, "../run/systemd/resolve/stub-resolv.conf")
		}, dns.ManagerResolved, false},
		{"resolved's state unrecognised", func(w *world) { w.active = "activating" }, dns.ManagerUnknown, true},
		{"init not established", func(w *world) { w.f.Init = detect.Init{} }, dns.ManagerUnknown, true},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			w := newWorld(t, "debian-13")
			tt.seed(w)
			s := w.read(t)
			if s.Manager != tt.manager || (s.Err != nil) != tt.err {
				t.Fatalf("manager %s, err %v", s.Manager, s.Err)
			}
		})
	}
}

// TestReadLaterDropIns: a drop-in sorting after hardn's (C byte order,
// across the four directories) that sets DNS= or Domains= is named; one
// sorting before it, one of the same name, a hidden one and one that sets
// something else are not.
func TestReadLaterDropIns(t *testing.T) {
	w := newWorld(t, "ubuntu-26.04")
	w.h.AddFile("/usr/lib/systemd/resolved.conf.d/zzz-vendor.conf", []byte("[Resolve]\nDNS=192.0.2.7\n"), 0o644, 0, 0)
	w.h.AddFile("/run/systemd/resolved.conf.d/zz-i.conf", []byte("[Resolve]\n Domains=example.net\n"), 0o644, 0, 0)
	w.h.AddFile("/etc/systemd/resolved.conf.d/~late.conf", []byte("[Resolve]\nDNSSEC=no\n"), 0o644, 0, 0)
	w.h.AddFile("/etc/systemd/resolved.conf.d/99-site.conf", []byte("[Resolve]\nDNS=192.0.2.8\n"), 0o644, 0, 0)
	w.h.AddFile("/run/systemd/resolved.conf.d/"+dns.DropInName, []byte("[Resolve]\nDNS=192.0.2.9\n"), 0o644, 0, 0)
	w.h.AddFile("/etc/systemd/resolved.conf.d/.zzz.conf", []byte("[Resolve]\nDNS=192.0.2.10\n"), 0o644, 0, 0)
	s := w.read(t)
	want := []string{"/run/systemd/resolved.conf.d/zz-i.conf", "/usr/lib/systemd/resolved.conf.d/zzz-vendor.conf"}
	if s.Err != nil || !slices.Equal(s.Resolved.Later, want) {
		t.Fatalf("later %q, err %v", s.Resolved.Later, s.Err)
	}
	if _, err := dns.PlanDNS(s, dns.Config{Nameservers: []string{ns1}}); !errors.Is(err, dns.ErrOverridden) {
		t.Errorf("plan: %v, want ErrOverridden", err)
	}
}

// TestReadResolvectl: wrapped lines continue the one before; output in any
// other form is Unknown, never an empty list.
func TestReadResolvectl(t *testing.T) {
	tests := []struct {
		name, out string
		global    []string
		links     int
		ok        bool
	}{
		{"wrapped", "Global: 192.0.2.53 192.0.2.54\n        2001:db8::53\nLink 2 (eth0): 192.0.2.1\nLink 3 (ens4):\n", []string{ns1, ns2, ns6}, 2, true},
		{"a delegate (systemd 259)", "Global: 192.0.2.53\nDelegate corp: 192.0.2.2\nLink 2 (eth0):\n", []string{ns1}, 2, true},
		{"no global", "Link 2 (eth0): 192.0.2.1\n", nil, 0, false},
		{"other text", "Global: 192.0.2.53\nDNS Servers: 192.0.2.1\n", nil, 0, false},
		{"coloured", "\x1b[0;1;39mGlobal\x1b[0m: 192.0.2.53\n", nil, 0, false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			w := newWorld(t, "ubuntu-26.04")
			w.h.Handler = func(argv []string, stdin []byte) hostfake.Response {
				if strings.Join(argv, " ") == "resolvectl --no-pager dns" {
					return hostfake.Response{Stdout: tt.out}
				}
				return w.answer(argv, stdin)
			}
			s := w.read(t)
			if (s.Err == nil) != tt.ok || !slices.Equal(s.Resolved.Global, tt.global) || len(s.Resolved.Links) != tt.links {
				t.Fatalf("global %q, links %v, err %v", s.Resolved.Global, s.Resolved.Links, s.Err)
			}
			if !tt.ok && !errors.Is(s.Err, detect.ErrUnrecognised) {
				t.Errorf("err %v, want ErrUnrecognised", s.Err)
			}
		})
	}
}

// TestReadUDHCPC: udhcpc rewrites /etc/resolv.conf unless RESOLV_CONF is
// "no", "NO", empty or another path; a line the shell could act on makes it
// Unknown, which is a finding, not a refusal, until the plan would change
// the file.
func TestReadUDHCPC(t *testing.T) {
	tests := []struct {
		conf     string
		rewrites detect.Tri
	}{
		{`RESOLV_CONF="no"`, detect.No},
		{`RESOLV_CONF=NO`, detect.No},
		{`RESOLV_CONF=""`, detect.No},
		{`RESOLV_CONF='/tmp/resolv.conf'`, detect.No},
		{`RESOLV_CONF='"no"'`, detect.Unknown}, // the value is "no" with its quotes: a relative path
		{`RESOLV_CONF="/etc/resolv.conf"`, detect.Yes},
		{"NO_DNS=\"eth1\"\n", detect.Yes},
		{`RESOLV_CONF=resolv.conf`, detect.Unknown},
		{`RESOLV_CONF=$(echo no)`, detect.Unknown},
		{`[ -f /x ] && RESOLV_CONF=no`, detect.Unknown},
	}
	for _, tt := range tests {
		t.Run(tt.conf, func(t *testing.T) {
			w := newWorld(t, "alpine-3.24")
			w.h.AddFile(dns.UDHCPCConf, []byte(tt.conf+"\n"), 0o644, 0, 0)
			s := w.read(t)
			if s.Err != nil || s.UDHCPC.Rewrites != tt.rewrites || (s.UDHCPC.Err != nil) != (tt.rewrites == detect.Unknown) {
				t.Fatalf("rewrites %s, udhcpc err %v, err %v", s.UDHCPC.Rewrites, s.UDHCPC.Err, s.Err)
			}
			p, err := dns.PlanDNS(s, dns.Config{Nameservers: []string{ns1}})
			if err != nil || (tt.rewrites != detect.No) != slices.Contains(kinds(p), "dns-udhcpc") {
				t.Errorf("plan: %v, findings %q", err, kinds(p))
			}
			_, err = dns.PlanDNS(s, dns.Config{Nameservers: []string{ns1}, UDHCPCNoResolv: true})
			if (tt.rewrites == detect.Unknown) != errors.Is(err, dns.ErrUnknown) {
				t.Errorf("plan with UDHCPCNoResolv: %v", err)
			}
		})
	}
}

// TestHostOfRefuses: a distribution or container fact that is not
// established, another distribution and a container are refused before
// anything is read.
func TestHostOfRefuses(t *testing.T) {
	tests := []struct {
		name string
		edit func(f *detect.Facts)
		want error
	}{
		{"distribution unknown", func(f *detect.Facts) { f.Platform = detect.Platform{} }, dns.ErrUnknown},
		{"another distribution", func(f *detect.Facts) { f.Platform.Distro = detect.DistroOther }, dns.ErrUnsupported},
		{"container", func(f *detect.Facts) { f.Container = detect.Container{Detected: detect.Yes, Signal: "/.dockerenv"} }, dns.ErrContainer},
		{"container unknown", func(f *detect.Facts) { f.Container = detect.Container{} }, dns.ErrUnknown},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			w := newWorld(t, "debian-13")
			tt.edit(&w.f)
			if _, err := dns.Read(context.Background(), w.h, w.f); !errors.Is(err, tt.want) {
				t.Fatalf("err %v, want %v", err, tt.want)
			}
			if len(w.h.Calls()) != 0 {
				t.Errorf("calls %v", w.h.Calls())
			}
		})
	}
}
