// TestReadLaterDropIns: a drop-in sorting after hardn's (C byte order,
// across the four directories) that assigns DNS= or Domains=, however
// spaced or continued, is named; one sorting before it, one of the same
// name, a hidden one, one that sets something else or only comments, and
// one /etc hides or masks are not. One that assigns DNS= refuses a plan;
// one that assigns only Domains= refuses a plan that sets them.
func TestReadLaterDropIns(t *testing.T) {
	const etc, run, lib = dns.DropInDir + "/", "/run/systemd/resolved.conf.d/", "/usr/lib/systemd/resolved.conf.d/"
	w := newWorld(t, "ubuntu-26.04")
	for name, data := range map[string]string{
		lib + "zzz-vendor.conf": "[Resolve]\nDNS=192.0.2.7\n",
		run + "zz-i.conf":       "[Resolve]\n Domains = example.net\n",
		etc + "~late.conf":      "[Resolve]\nDNSSEC=no\n# DNS=192.0.2.11\n ; Domains=lan\nLLMNR=no \\\nDNS=192.0.2.12\n",
		etc + "~later.conf":     "[Resolve]\nLLMNR=a\\\\\nDNS \\\n= 192.0.2.13\n",
		etc + "99-site.conf":    "[Resolve]\nDNS=192.0.2.8\n",
		run + dns.DropInName:    "[Resolve]\nDNS=192.0.2.9\n",
		etc + ".zzz.conf":       "[Resolve]\nDNS=192.0.2.10\n",
		lib + "zzz-hidden.conf": "[Resolve]\nDNS=192.0.2.14\n",
		etc + "zzz-hidden.conf": "[Resolve]\nLLMNR=no\n",
		lib + "zzz-masked.conf": "[Resolve]\nDNS=192.0.2.15\n",
	} {
		w.h.AddFile(name, []byte(data), 0o644, 0, 0)
	}
	w.h.AddSymlink(etc+"zzz-masked.conf", "/dev/null")
	s := w.read(t)
	want := []dns.Override{
		{Path: etc + "~later.conf", DNS: true},
		{Path: run + "zz-i.conf", Domains: true},
		{Path: lib + "zzz-vendor.conf", DNS: true},
	}
	if s.Err != nil || !slices.Equal(s.Resolved.Later, want) {
		t.Fatalf("later %+v, err %v", s.Resolved.Later, s.Err)
	}
	if _, err := dns.PlanDNS(s, dns.Config{Nameservers: []string{ns1}}); !errors.Is(err, dns.ErrOverridden) {
		t.Errorf("plan: %v, want ErrOverridden", err)
	}
	s.Resolved.Later = want[1:2]
	if _, err := dns.PlanDNS(s, dns.Config{Nameservers: []string{ns1}}); err != nil {
		t.Errorf("Domains= only, search kept: %v", err)
	}
	if _, err := dns.PlanDNS(s, dns.Config{Nameservers: []string{ns1}, ReplaceSearch: true}); !errors.Is(err, dns.ErrOverridden) {
		t.Errorf("Domains= only, search set: %v, want ErrOverridden", err)
	}
}

// TestReadResolvectl: wrapped lines continue the one before; output in any
// other form is Unknown, never an empty list.
func TestReadResolvectl(t *testing.T) {
	tests := []struct {
		name, out string
		global    []string
		links     int
		ok        bool
	}{
		{"wrapped", "Global: 192.0.2.53 192.0.2.54\n        2001:db8::53\nLink 2 (eth0): 192.0.2.1\nLink 3 (ens4):\n", []string{ns1, ns2, ns6}, 2, true},
		{"a delegate (systemd 259)", "Global: 192.0.2.53\nDelegate corp: 192.0.2.2\nLink 2 (eth0):\n", []string{ns1}, 2, true},
		{"no global", "Link 2 (eth0): 192.0.2.1\n", nil, 0, false},
		{"other text", "Global: 192.0.2.53\nDNS Servers: 192.0.2.1\n", nil, 0, false},
		{"coloured", "\x1b[0;1;39mGlobal\x1b[0m: 192.0.2.53\n", nil, 0, false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			w := newWorld(t, "ubuntu-26.04")
			w.h.Handler = func(argv []string, stdin []byte) hostfake.Response {
				if strings.Join(argv, " ") == "resolvectl --no-pager dns" {
					return hostfake.Response{Stdout: tt.out}
				}
				return w.answer(argv, stdin)
			}
			s := w.read(t)
			if (s.Err == nil) != tt.ok || !slices.Equal(s.Resolved.Global, tt.global) || len(s.Resolved.Links) != tt.links {
				t.Fatalf("global %q, links %v, err %v", s.Resolved.Global, s.Resolved.Links, s.Err)
			}
			if !tt.ok && !errors.Is(s.Err, detect.ErrUnrecognised) {
				t.Errorf("err %v, want ErrUnrecognised", s.Err)
			}
		})
	}
}

// TestReadLinkDomains: each link's search domains are read from
// resolvectl domain beside its servers, the global ones kept apart; a link
// with domains and no servers is kept, and its servers' finding is not
// made; a per-link finding names its link (next/s2-control, D4).
func TestReadLinkDomains(t *testing.T) {
	w := newWorld(t, "ubuntu-26.04")
	w.links = append(w.links, dns.Link{Index: 3, Name: "ens4"})
	w.h.Handler = func(argv []string, stdin []byte) hostfake.Response {
		if strings.Join(argv, " ") == "resolvectl --no-pager domain" {
			return hostfake.Response{Stdout: "Global: corp.example.net\nLink 2 (eth0): example.net\n        ~lan.example.net\nLink 3 (ens4):\nLink 4 (wg0): vpn.example.net\n"}
		}
		return w.answer(argv, stdin)
	}
	s := w.read(t)
	readOnly(t, w.h)
	want := []dns.Link{{Index: 2, Name: "eth0", Servers: []string{dhcpNS}, Domains: []string{"example.net", "~lan.example.net"}},
		{Index: 3, Name: "ens4"}, {Index: 4, Name: "wg0", Domains: []string{"vpn.example.net"}}}
	if s.Err != nil || !slices.Equal(s.Resolved.Domains, []string{"corp.example.net"}) || len(s.Resolved.Links) != len(want) {
		t.Fatalf("domains %q, links %+v, err %v", s.Resolved.Domains, s.Resolved.Links, s.Err)
	}
	for i, l := range s.Resolved.Links {
		if l.Index != want[i].Index || l.Name != want[i].Name || !slices.Equal(l.Servers, want[i].Servers) || !slices.Equal(l.Domains, want[i].Domains) {
			t.Errorf("link %d: %+v, want %+v", i, l, want[i])
		}
	}
	if f := s.Findings(); len(f) != 1 || f[0].Link == nil || f[0].Link.Name != "eth0" || !slices.Equal(f[0].Link.Servers, []string{dhcpNS}) {
		t.Errorf("findings %+v", f)
	}
}

// TestReadUDHCPC: udhcpc rewrites /etc/resolv.conf unless RESOLV_CONF is
// "no", "NO", empty or another path; a line the shell could act on makes it
// Unknown, which is a finding, not a refusal, until the plan would change
// the file.
func TestReadUDHCPC(t *testing.T) {
	tests := []struct {
		conf     string
		rewrites detect.Tri
	}{
		{`RESOLV_CONF="no"`, detect.No},
		{`RESOLV_CONF=NO`, detect.No},
		{`RESOLV_CONF=""`, detect.No},
		{`RESOLV_CONF='/tmp/resolv.conf'`, detect.No},
		{`RESOLV_CONF='"no"'`, detect.Unknown}, // the value is "no" with its quotes: a relative path
		{`RESOLV_CONF="/etc/resolv.conf"`, detect.Yes},
		{"NO_DNS=\"eth1\"\n", detect.Yes},
		{`RESOLV_CONF=resolv.conf`, detect.Unknown},
		{`RESOLV_CONF=$(echo no)`, detect.Unknown},
		{`[ -f /x ] && RESOLV_CONF=no`, detect.Unknown},
	}
	for _, tt := range tests {
		t.Run(tt.conf, func(t *testing.T) {
			w := newWorld(t, "alpine-3.24")
			w.h.AddFile(dns.UDHCPCConf, []byte(tt.conf+"\n"), 0o644, 0, 0)
			s := w.read(t)
			if s.Err != nil || s.UDHCPC.Rewrites != tt.rewrites || (s.UDHCPC.Err != nil) != (tt.rewrites == detect.Unknown) {
				t.Fatalf("rewrites %s, udhcpc err %v, err %v", s.UDHCPC.Rewrites, s.UDHCPC.Err, s.Err)
			}
			p, err := dns.PlanDNS(s, dns.Config{Nameservers: []string{ns1}})
			if err != nil || (tt.rewrites != detect.No) != slices.Contains(kinds(p), "dns-udhcpc") {
				t.Errorf("plan: %v, findings %q", err, kinds(p))
			}
			_, err = dns.PlanDNS(s, dns.Config{Nameservers: []string{ns1}, UDHCPCNoResolv: true})
			if (tt.rewrites == detect.Unknown) != errors.Is(err, dns.ErrUnknown) {
				t.Errorf("plan with UDHCPCNoResolv: %v", err)
			}
		})
	}
}

