// uplinkFile is systemd-resolved's file listing the servers it knows, for
// programs that read /etc/resolv.conf and bypass it.
const uplinkFile = "/run/systemd/resolve/resolv.conf"

// linkManagers are the files a manager links /etc/resolv.conf to.
var linkManagers = map[string]Manager{
	"/run/systemd/resolve/stub-resolv.conf":   ManagerResolved,
	uplinkFile:                                ManagerResolved,
	"/usr/lib/systemd/resolv.conf":            ManagerResolved,
	"/run/resolvconf/resolv.conf":             ManagerResolvconf,
	"/run/NetworkManager/resolv.conf":         ManagerNetworkManager,
	"/run/NetworkManager/no-stub-resolv.conf": ManagerNetworkManager,
}

// headers are the first lines a manager writes into a regular file.
// cloud-init's is its sysconfig renderer's (cloud-init 24.4,
// cloudinit/net/sysconfig.py, "Created by cloud-init automatically, do
// not edit." behind resolv.conf's ";"), as on rhel9-test-115, where it
// also set NetworkManager's dns = none (el-rhel.md §6).
var headers = map[string]Manager{
	"# Generated by NetworkManager":                       ManagerNetworkManager,
	"# Generated by resolvconf":                           ManagerResolvconf,
	"; Created by cloud-init automatically, do not edit.": ManagerCloudInit,
}

// dhcpClients may rewrite /etc/resolv.conf on a lease.
var dhcpClients = []string{"dhclient", "dhcpcd"}

// UDHCPCDir is where Alpine's udhcpc script looks for udhcpc.conf and its
// hook directories.
const UDHCPCDir = "/etc/udhcpc"

// udhcpcHookDirs are where udhcpc's script runs every executable regular
// file, before and after it handles a deconfig, bound or renew event.
var udhcpcHookDirs = func() []string {
	var ds []string
	for _, when := range []string{"pre", "post"} {
		for _, ev := range []string{"deconfig", "bound", "renew"} {
			ds = append(ds, UDHCPCDir+"/"+when+"-"+ev)
		}
	}
	return ds
}()

// Resolved is systemd-resolved's side of the state.
type Resolved struct {
	Active detect.Tri // systemctl is-active ResolvedUnit
	Dir    detect.Tri // DropInDir is a directory
	DropIn Entry
	// Later are the drop-ins sorting after DropInName that assign DNS= or
	// Domains=: for each name, the file systemd reads (the first of the
	// directories that has it, unless it is a link to /dev/null).
	Later   []Override
	Global  []string // the global servers resolved uses now
	Domains []string // the global search domains it uses now ("~" for route-only)
	Links   []Link   // per-link servers and search domains
}

// Override is a drop-in sorting after hardn's, and which of its lists it
// assigns.
type Override struct {
	Path         string
	DNS, Domains bool
}

// UDHCPC is Alpine's udhcpc side of the state.
type UDHCPC struct {
	// InUse: udhcpc is the DHCP client ifupdown-ng runs for an auto
	// interface of Interfaces, which Alpine's networking service brings up
	// (Yes), none runs it and no udhcpc pid file is there (No), or that is
	// not established (Unknown). Its findings, and a plan's step, are only
	// where it is Yes. Omitted from JSON when Unknown, its zero value, so
	// that a kept plan off Alpine is journalled as before.
	InUse detect.Tri `json:",omitempty"`
	// InUseErr is why InUse is Unknown, the file it is about its finding's
	// path: a finding, and a plan's refusal where the plan is asked to
	// stop udhcpc (Config.UDHCPCNoResolv). Not marshalled.
	InUseErr error `json:"-"`
	Conf     Entry
	// Rewrites: udhcpc's script rewrites /etc/resolv.conf on a lease, as
	// RESOLV_CONF in Conf decides; Hooks aside. Unknown also where an
	// interface runs udhcpc with another script than its default, or with
	// options that may name one (dhcp-script, udhcpc-opts).
	Rewrites detect.Tri
	NoDNS    string // the interfaces it skips
	// Hooks are the executables the script runs around each event, which
	// may rewrite the file whatever RESOLV_CONF says: a finding.
	Hooks []string
	// Err is why Rewrites is Unknown. It stops a plan only when the plan
	// would change UDHCPCConf; otherwise it is a finding. Not marshalled:
	// a finding's Detail keeps its text.
	Err error `json:"-"`
}

// State is the host's DNS configuration as read.
type State struct {
	Host       Host
	Manager    Manager
	ResolvConf Entry
	// Nameservers and Search are what /etc/resolv.conf lists, for a file
	// manager; Resolved.Global is resolved's.
	Nameservers, Search []string
	Resolved            Resolved
	UDHCPC              UDHCPC
	DHCPClients         []string // DHCP clients found in host.SearchPath
	// Err joins why Manager or a field the plan needs is Unknown. PlanDNS
	// refuses a state with one, so a plan's From has none to marshal.
	Err error `json:"-"`
}

// HostOf takes from detect's facts what Read needs, refusing a
// distribution that is not established (ErrUnknown) or not of the Debian,
// Ubuntu, Alpine, Proxmox VE or EL family (Rocky Linux, AlmaLinux and RHEL,
// whose resolv.conf hardn only reports) (ErrUnsupported; the release's
// support level is the engine's gate), and a container, detected
// (ErrContainer) or not established (ErrUnknown). Systemd is Yes only for
// a host systemd booted, No for OpenRC, else Unknown.
func HostOf(f detect.Facts) (Host, error) {
	switch d := f.Platform.Distro; d {
	case detect.DistroDebian, detect.DistroUbuntu, detect.DistroAlpine, detect.DistroProxmox, detect.DistroRocky, detect.DistroAlma, detect.DistroRHEL:
	case detect.DistroUnknown:
		return Host{}, fmt.Errorf("dns: distribution: %w: %w", ErrUnknown, errOr(f.Platform.Err, detect.ErrNoSignal))
	default:
		return Host{}, fmt.Errorf("dns: %q: %w", d, ErrUnsupported)
	}
	switch f.Container.Detected {
	case detect.Yes:
		return Host{}, fmt.Errorf("dns: %s: %w", f.Container.Signal, ErrContainer)
	case detect.Unknown:
		return Host{}, fmt.Errorf("dns: container: %w: %w", ErrUnknown, errOr(f.Container.Err, detect.ErrNoSignal))
	}
	h := Host{Distro: f.Platform.Distro, Systemd: detect.Unknown}
	switch {
	case f.Init.Kind == detect.Systemd && f.Init.Running == detect.Yes:
		h.Systemd = detect.Yes
	case f.Init.Kind == detect.OpenRC: // detect found no systemd run directory
		h.Systemd = detect.No
	}
	return h, nil
}

// Read reads the host's DNS configuration, taking detect's facts (HostOf)
// and never re-detecting. It only reads: /etc/resolv.conf (Lstat, then
// Readlink or ReadFileNoFollow), on a systemd-booted host `systemctl
// is-active systemd-resolved.service`, and for the manager found its
// files: systemd-resolved's drop-ins and `resolvectl --no-pager dns` and
// `domain`; for a file, whether dhclient or dhcpcd is installed, and on
// Alpine whether udhcpc is the DHCP client ifupdown-ng runs (DHCPExecutor,
// the networking service's file in /etc/conf.d, Interfaces, the clients it
// tries and udhcpc's pid files in /var/run), UDHCPCConf and udhcpc's
// hooks. What could not be read is in State.Err, with Manager or the field
// Unknown; udhcpc's own errors are kept apart (UDHCPC.InUseErr, Err).
func Read(ctx context.Context, sys host.System, f detect.Facts) (State, error) {
	h, err := HostOf(f)
	if err != nil {
		return State{}, err
	}
	if err := ctx.Err(); err != nil {
		return State{}, fmt.Errorf("dns: %w", err)
	}
	return read(ctx, sys, h), nil
}

func read(ctx context.Context, sys host.System, h Host) State {
	s := State{Host: h}
	var errs []error
	add := func(err error) {
		if err != nil {
			errs = append(errs, err)
		}
	}
	var err error
	s.ResolvConf, err = readEntry(ctx, sys, ResolvConf)
	add(err)
	s.Resolved.Active, err = resolvedActive(ctx, sys, h)
	add(err)
	s.Manager, err = classify(s.ResolvConf, s.Resolved.Active, h)
	add(err)
	switch s.Manager {
	case ManagerResolved:
		if s.Resolved.Active == detect.Yes {
			add(readResolved(ctx, sys, &s.Resolved))
		}
	case ManagerFile, ManagerProxmox:
		s.Nameservers, s.Search = ParseResolvConf(s.ResolvConf.Data)
		if h.Distro == detect.DistroAlpine {
			u := udhcpcInUse(ctx, sys)
			s.UDHCPC.InUse, s.UDHCPC.InUseErr = u.tri, u.err
			s.UDHCPC.Err = readUDHCPC(ctx, sys, &s.UDHCPC)
			if u.script != nil { // RESOLV_CONF is the default script's
				s.UDHCPC.Rewrites, s.UDHCPC.Err = detect.Unknown, errors.Join(s.UDHCPC.Err, u.script)
			}
			s.UDHCPC.Hooks, err = udhcpcHooks(ctx, sys)
			add(err)
		}
		s.DHCPClients, err = lookPath(ctx, sys, dhcpClients)
		add(err)
	}
	s.Err = errors.Join(errs...)
	return s
}

// readEntry reads name without following a symlink there.
func readEntry(ctx context.Context, sys host.System, name string) (Entry, error) {
	fi, err := sys.Lstat(ctx, name)
	switch {
	case errors.Is(err, fs.ErrNotExist):
		return Entry{Kind: EntryAbsent}, nil
	case err != nil:
		return Entry{}, err
	case fi.Mode()&fs.ModeSymlink != 0:
		t, err := sys.Readlink(ctx, name)
		if err != nil {
			return Entry{}, err
		}
		return Entry{Kind: EntrySymlink, Target: t}, nil
	case !fi.Mode().IsRegular():
		return Entry{Kind: EntryOther}, nil
	}
	data, fi, err := sys.ReadFileNoFollow(ctx, name)
	if err != nil {
		return Entry{}, err
	}
	uid, gid, ok := host.Owner(fi)
	if !ok {
		return Entry{}, &fs.PathError{Op: "owner", Path: name, Err: fs.ErrInvalid}
	}
	return Entry{Kind: EntryFile, Data: data, Mode: fi.Mode().Perm(), UID: uid, GID: gid}, nil
}

// resolvedActive asks systemd whether ResolvedUnit is active: No without
// systemd, Unknown when it is not established that systemd booted the
// host or systemctl's answer is not a state it documents.
func resolvedActive(ctx context.Context, sys host.System, h Host) (detect.Tri, error) {
	switch h.Systemd {
	case detect.No:
		return detect.No, nil
	case detect.Unknown:
		return detect.Unknown, fmt.Errorf("dns: init system: %w", ErrUnknown)
	}
	res, err := sys.Run(ctx, "systemctl", "is-active", ResolvedUnit)
	if xe := (*host.ExitError)(nil); err != nil && !errors.As(err, &xe) {
		return detect.Unknown, fmt.Errorf("dns: %w", err)
	}
	word := strings.TrimSpace(string(res.Stdout))
	t := detect.UnitState{Active: word}.IsActive()
	if t == detect.Unknown {
		return t, fmt.Errorf("dns: systemctl is-active %s: %q: %w", ResolvedUnit, word, detect.ErrUnrecognised)
	}
	return t, nil
}

// classify names the manager of /etc/resolv.conf: a symlink by its target,
// a regular file by its first line, else a file hardn writes, unless
// systemd-resolved runs: it then reads the file as another package's
// (systemd-resolved.service(8), "foreign" mode).
func classify(e Entry, active detect.Tri, h Host) (Manager, error) {
	switch e.Kind {
	case EntrySymlink:
		p, err := host.JoinLinkTarget(path.Dir(ResolvConf), e.Target)
		if err != nil {
			return ManagerUnknown, err
		}
		if m, ok := linkManagers[p]; ok {
			return m, nil
		}
		return ManagerForeign, nil
	case EntryFile:
		first, _, _ := strings.Cut(string(e.Data), "\n")
		if m, ok := headers[strings.TrimSpace(first)]; ok {
			return m, nil
		}
	case EntryAbsent:
	case EntryOther:
		return ManagerUnknown, fmt.Errorf("dns: %s: neither a file nor a symlink: %w", ResolvConf, ErrUnknown)
	default:
		return ManagerUnknown, nil // its read error is already in the state
	}
	switch active {
	case detect.Yes:
		return ManagerForeign, nil
	case detect.Unknown:
		return ManagerUnknown, nil // resolvedActive said why
	}
	if h.Distro == detect.DistroProxmox {
		return ManagerProxmox, nil
	}
	return ManagerFile, nil
}

// readResolved reads hardn's drop-in, the drop-ins that sort after it and
// what resolved uses now. A name in one of dropInDirs hides the same name
// in those after it, and a link to /dev/null there masks it
// (standard-conf(5)): only the file systemd reads is looked at.
func readResolved(ctx context.Context, sys host.System, r *Resolved) error {
	var errs []error
	switch fi, err := sys.Lstat(ctx, DropInDir); {
	case errors.Is(err, fs.ErrNotExist):
		r.Dir = detect.No
	case err != nil:
		errs = append(errs, err)
	case fi.IsDir():
		r.Dir = detect.Yes
	default:
		errs = append(errs, fmt.Errorf("dns: %s: not a directory: %w", DropInDir, ErrUnknown))
	}
	var err error
	if r.DropIn, err = readEntry(ctx, sys, DropIn); err != nil {
		errs = append(errs, err)
	}
	seen := map[string]bool{}
	for _, dir := range dropInDirs {
		des, err := sys.ReadDir(ctx, dir)
		if errors.Is(err, fs.ErrNotExist) {
			continue
		}
		if err != nil {
			errs = append(errs, err)
			continue
		}
		for _, de := range des {
			n, name := de.Name(), dir+"/"+de.Name()
			if !strings.HasSuffix(n, ".conf") || strings.HasPrefix(n, ".") || seen[n] {
				continue
			}
			seen[n] = true
			if n <= DropInName {
				continue
			}
			if de.Type()&fs.ModeSymlink != 0 {
				switch t, err := sys.Readlink(ctx, name); {
				case err != nil:
					errs = append(errs, err)
					continue
				case t == "/dev/null":
					continue
				}
			}
			data, err := sys.ReadFile(ctx, name)
			if err != nil {
				errs = append(errs, err)
				continue
			}
			if d, m := resolvedSets(data); d || m {
				r.Later = append(r.Later, Override{Path: name, DNS: d, Domains: m})
			}
		}
	}
	if r.Global, r.Links, err = resolvectl(ctx, sys, "dns"); err != nil {
		errs = append(errs, err)
	}
	var domains []Link
	if r.Domains, domains, err = resolvectl(ctx, sys, "domain"); err != nil {
		errs = append(errs, err)
	}
	r.Links = withDomains(r.Links, domains)
	return errors.Join(errs...)
}

// withDomains is links with each link's search domains from domains, the
// links resolvectl domain lists (their Servers the domains), matched by
// index and name; a link with domains that resolvectl dns did not list is
// added with no servers.
func withDomains(links, domains []Link) []Link {
	for _, d := range domains {
		if len(d.Servers) == 0 {
			continue
		}
		i := slices.IndexFunc(links, func(l Link) bool { return l.Index == d.Index && l.Name == d.Name })
		if i < 0 {
			links, i = append(links, Link{Index: d.Index, Name: d.Name}), len(links)
		}
		links[i].Domains = d.Servers
	}
	return links
}

// resolvectl runs `resolvectl --no-pager verb` (dns or domain, with no
// argument: it only shows) and returns the global list and the links'.
func resolvectl(ctx context.Context, sys host.System, verb string) ([]string, []Link, error) {
	res, err := sys.Run(ctx, "resolvectl", "--no-pager", verb)
	if err != nil {
		return nil, nil, fmt.Errorf("dns: %w", err)
	}
	global, links, err := parseResolvectl(res.Stdout)
	if err != nil {
		return nil, nil, fmt.Errorf("dns: %s: %w", verb, err)
	}
	return global, links, nil
}

// udhcpcHooks are the files udhcpc's script runs from udhcpcHookDirs:
// those `[ -f ] && [ -x ]` accept for root (a regular file, symlinks
// followed, with an execute bit), from the glob "$dir"/*, which skips
// hidden names.
func udhcpcHooks(ctx context.Context, sys host.System) ([]string, error) {
	var hooks []string
	for _, dir := range udhcpcHookDirs {
		switch fi, err := sys.Stat(ctx, dir); {
		case errors.Is(err, fs.ErrNotExist):
			continue
		case err != nil:
			return nil, err
		case !fi.IsDir():
			continue
		}
		des, err := sys.ReadDir(ctx, dir)
		if err != nil {
			return nil, err
		}
		for _, de := range des {
			if strings.HasPrefix(de.Name(), ".") {
				continue
			}
			switch fi, err := sys.Stat(ctx, dir+"/"+de.Name()); {
			case errors.Is(err, fs.ErrNotExist): // a dangling link
			case err != nil:
				return nil, err
			case fi.Mode().IsRegular() && fi.Mode().Perm()&0o111 != 0:
				hooks = append(hooks, dir+"/"+de.Name())
			}
		}
	}
	return hooks, nil
}

// readUDHCPC reads what udhcpc's script will do with /etc/resolv.conf.
func readUDHCPC(ctx context.Context, sys host.System, u *UDHCPC) error {
	var err error
	if u.Conf, err = readEntry(ctx, sys, UDHCPCConf); err != nil {
		return err
	}
	switch u.Conf.Kind {
	case EntryAbsent:
		u.Rewrites = udhcpcRewrites("", false)
		return nil
	case EntryFile:
	default:
		return fmt.Errorf("dns: %s: not a regular file: %w", UDHCPCConf, ErrUnknown)
	}
	v, set, noDNS, err := udhcpc(u.Conf.Data)
	if err != nil {
		return err
	}
	u.NoDNS = noDNS
	if u.Rewrites = udhcpcRewrites(v, set); u.Rewrites == detect.Unknown {
		return fmt.Errorf("dns: %s: RESOLV_CONF=%q: %w", UDHCPCConf, v, detect.ErrUnrecognised)
	}
	return nil
}

// lookPath returns where each name is, as host.Real would resolve it: the
// first regular file with an execute bit in host.SearchPath.
func lookPath(ctx context.Context, sys host.System, names []string) ([]string, error) {
	var found []string
	for _, n := range names {
		for _, dir := range strings.Split(host.SearchPath, ":") {
			fi, err := sys.Stat(ctx, dir+"/"+n)
			if errors.Is(err, fs.ErrNotExist) {
				continue
			}
			if err != nil {
				return nil, err
			}
			if fi.Mode().IsRegular() && fi.Mode().Perm()&0o111 != 0 {
				found = append(found, dir+"/"+n)
				break
			}
		}
	}
	return found, nil
}
