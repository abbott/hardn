// The reader of this slice's goldens (Slice.Reader;
// docs/engine/parity-system-details.md §2), in their four layouts, each a
// header of "# " lines, the screen as printed between two "# ----" lines, and
// a trailer:
//
//   - readReport: System Details' screen runs (TestLegacyMenuSystemDetails),
//     and its two renderer goldens, which have no trailer;
//   - readLog: the Logs screen and logging.PrintLogs (TestLegacyMenuLogs);
//   - readParser: GetLogs on the lines hardn writes (TestLegacyLogsParser).
//
// It lives here and not in internal/parity because every line it knows is
// these two screens'. A section, a call or a line it does not know fails the
// test, so that no golden reads as a run that did nothing.

// golden is a characterization golden in its three parts.
type golden struct{ header, body, trailer []string }

// goldenHeader are the header lines these layouts have, each the start of a
// line: what was run and how it reads, not an end state.
var goldenHeader = []string{"# origin/main behaviour", "# Generated by ", "# Screen: ", "# Renderer: ", "# Operation: ",
	"# Script: ", "# Tools on PATH (stand-ins): ", "# dryRun ", "# Masked, read from ", "# Pauses: ", "# Widest line printed: ",
	"# logFile: ", "# $PAGER: ", "# Log: ", "# Writers: ", "# KNOWN-DEFECT: ", "# NOTE: ", "# The screen as printed",
	"# The date and time are masked."}

const goldenRule = "# ----"

func splitGolden(data []byte) (golden, error) {
	var g golden
	parts := []*[]string{&g.header, &g.body, &g.trailer}
	at := 0
	for _, l := range strings.Split(strings.TrimSuffix(string(data), "\n"), "\n") {
		if l == goldenRule {
			if at++; at == len(parts) {
				return g, errors.New("a third rule: a layout this reader does not know")
			}
			continue
		}
		*parts[at] = append(*parts[at], l)
	}
	if at != 2 {
		return g, errors.New("not two rules: a layout this reader does not know")
	}
	for _, l := range g.header {
		if !slices.ContainsFunc(goldenHeader, func(p string) bool { return strings.HasPrefix(l, p) }) {
			return g, fmt.Errorf("a header line the reader does not know: %q", l)
		}
	}
	return g, nil
}

// has is the first header line starting with prefix, past it.
func (g golden) has(prefix string) (string, bool) {
	for _, l := range g.header {
		if v, ok := strings.CutPrefix(l, prefix); ok {
			return v, true
		}
	}
	return "", false
}

// readGolden is Slice.Reader: the layout by the golden's name.
func readGolden(data []byte, rel string) (parity.LegacyRead, error) {
	g, err := splitGolden(data)
	if err != nil {
		return parity.LegacyRead{}, err
	}
	switch base := path.Base(rel); {
	case base == "logs_parser.golden":
		return readParser(g)
	case strings.HasPrefix(base, "system_details_"):
		return readReport(g)
	case strings.HasPrefix(base, "logs_"):
		return readLog(g)
	}
	return parity.LegacyRead{}, errors.New("a golden of no layout this reader knows")
}

var (
	sgr       = regexp.MustCompile(`\\x1b\[[0-9;?]*[A-Za-z]`)
	shownMask = "<read from the host>"
)

// plain is a line of the screen with its escapes, its end marker and its
// padding gone.
func plain(l string) (string, error) {
	v, ok := strings.CutSuffix(l, "$")
	if !ok {
		return "", fmt.Errorf("a line of the screen with no end marker: %q", l)
	}
	return strings.TrimRight(sgr.ReplaceAllString(v, ""), " "), nil
}

// The System Details screen's lines (pkg/system/display.go; pkg/menu
// system_details_menu.go), past plain.
var (
	reportTitle = regexp.MustCompile(`^System Details(?: Error)? ─+╮$`)
	reportShade = regexp.MustCompile(`^░ System Details(?: Error)? ░+$`)
	reportItem  = regexp.MustCompile(`^(?:Select an option|\s*[012]\) (?:Refresh Information|Export Information|Return)\b.*|❯ Enter selection \[0-[12] or q\]:|❯ Press Enter to continue\.\.\.)$`)
	reportAsk   = "-  Enter filename to export system status (default: system_status.txt):"
	reportSaid  = regexp.MustCompile(`^(?:✓ (Machine status exported to \S+)|✗ (Failed to write file: .+)|ℹ (\[DRY-RUN\] Would write system status to \S+))$`)
	reportError = regexp.MustCompile(`^(?:✗ Error retrieving system status|Error): (.+)$`)
	reportWords = []string{"Failed to retrieve system status information.", "Please check system permissions and try again."}
	reportBar   = regexp.MustCompile(`^([█░]+) \(([0-9.]+)\)$`)
	asked       = regexp.MustCompile(`^#   (\d+)x (read|exec)\s+(\S.*?) -> (.+)$`)
	toolRead    = regexp.MustCompile(`^(?:nproc|lscpu|lastlog -u <the test's user>|zpool status -x|zfs get -Hp (?:available|used) \S+)$`)
	mockRead    = regexp.MustCompile(`^(?:uname -r|df -k|cat /proc/meminfo)$`)
	dirEntry    = regexp.MustCompile(`^#   (\S+?)(/?) mode=(\d{4})$`)
)

// reportLabels are the rows of origin/main's report, in its order, those that
// hold a list of "- " lines under them too.
var reportLabels = []string{"OS", "Kernel", "Hostname", "Domain", "IP Addresses", "Client IP", "DNS IP 1", "DNS IP 2", "User",
	"Non-System Users", "Processor", "Cores", "Hypervisor", "CPU Freq", "Load 1m", "Load 5m", "Load 15m",
	"Volume", "Disk Usage", "ZFS Health", "Memory", "Usage", "Last Login", "From", "Uptime"}

// maskedLabels are the rows the screen goldens' "Masked" line names, read from
// the machine the characterization ran on; Domain goes altogether.
var maskedLabels = []string{"OS", "Hostname", "IP Addresses", "User", "Load 1m", "Load 5m", "Load 15m"}

// readReport reads a System Details golden: each row of the first draw (a later
// draw must print the same rows), the report lost where a collector failed, what
// an export said, the masked rows, and the trailer. A screen with neither rows
// nor an error fails.
func readReport(g golden) (parity.LegacyRead, error) {
	var out parity.LegacyRead
	var draws [][]parity.Row
	var bars [][]string // each draw's, as its rows
	var said []string
	lost, list, printed := "", "", 0
	_, masks := g.has("# Masked, read from ")
	for _, raw := range g.body {
		l, err := plain(raw)
		if err != nil {
			return out, err
		}
		add := func(name, value string, masked bool) error {
			if len(draws) == 0 {
				return fmt.Errorf("a row before the screen's title: %q", raw)
			}
			d := &draws[len(draws)-1]
			*d = append(*d, parity.Row{Name: name, Value: value, Masked: masked})
			return nil
		}
		m := reportError.FindStringSubmatch(l)
		s := reportSaid.FindStringSubmatch(l)
		label, value, isRow := strings.Cut(l, ":")
		value = strings.TrimSpace(value)
		isRow = isRow && slices.Contains(reportLabels, label)
		switch {
		case l == "", reportShade.MatchString(l), reportItem.MatchString(l), l == reportAsk, slices.Contains(reportWords, l):
		case reportTitle.MatchString(l):
			if !strings.Contains(l, "Error") {
				draws, bars = append(draws, nil), append(bars, nil)
			}
			list = ""
		case m != nil:
			if lost != "" && lost != m[1] {
				return out, fmt.Errorf("a second error: %q", l)
			}
			lost, printed = m[1], printed+1
		case s != nil:
			said = append(said, s[1]+s[2]+s[3])
		case list != "" && strings.HasPrefix(l, "- "):
			d := draws[len(draws)-1]
			r := &d[len(d)-1]
			if r.Value != "" {
				r.Value += ", "
			}
			r.Value += strings.TrimPrefix(l, "- ")
			r.Masked = r.Value == shownMask
		case isRow:
			list = ""
			switch label {
			case "IP Addresses", "Non-System Users":
				list = label
			case "Load 1m", "Load 5m", "Load 15m":
				if value != shownMask {
					b := reportBar.FindStringSubmatch(value)
					if b == nil {
						return out, fmt.Errorf("a load line the reader does not know: %q", l)
					}
					if len(bars) == 0 {
						return out, fmt.Errorf("a row before the screen's title: %q", raw)
					}
					bars[len(bars)-1] = append(bars[len(bars)-1], strings.TrimPrefix(label, "Load ")+" "+b[1])
					value = b[2]
				}
			}
			if value == "" && list == "" {
				value = "blank"
			}
			if err := add(label, value, value == shownMask); err != nil {
				return out, err
			}
		default:
			return out, fmt.Errorf("a line of the screen the reader does not know: %q", l)
		}
	}
	switch {
	case len(draws) == 0 && lost == "":
		return out, errors.New("no draw of the report and no error: a run that did nothing")
	case lost != "" && printed != 2:
		return out, fmt.Errorf("the error printed %d times, where the reader takes it printed twice", printed)
	case lost != "" && slices.ContainsFunc(draws, func(d []parity.Row) bool { return len(d) > 0 }):
		return out, errors.New("a report and an error: the reader takes the error to lose the report")
	}
	var rows []parity.Row
	if lost != "" {
		rows = []parity.Row{{Name: reportRow, Value: "lost: " + lost}}
	} else {
		rows = append([]parity.Row{{Name: reportRow, Value: reportWhole}}, draws[0]...)
		for i, d := range draws[1:] {
			if !slices.Equal(d, draws[0]) || !slices.Equal(bars[i+1], bars[0]) {
				return out, errors.New("a draw whose rows differ from the first's, which the reader does not compare")
			}
		}
		for _, r := range rows {
			if r.Masked && (!masks || !slices.Contains(maskedLabels, r.Name)) {
				return out, fmt.Errorf("the %s row masked, which the golden's Masked line does not name", r.Name)
			}
		}
		for _, name := range maskedLabels {
			i := slices.IndexFunc(rows, func(r parity.Row) bool { return r.Name == name })
			if i < 0 || masks != rows[i].Masked {
				return out, fmt.Errorf("the %s row: masked %t, where the golden's Masked line says %t", name, i >= 0 && rows[i].Masked, masks)
			}
		}
		if masks {
			rows = append(rows, parity.Row{Name: "Domain", Value: "<dropped>", Masked: true})
		}
		if len(bars[0]) > 0 {
			rows = append(rows, parity.Row{Name: "Load bars", Value: strings.Join(bars[0], ", ")})
		}
	}
	if len(said) > 0 {
		rows = append(rows, parity.Row{Name: exportRow, Value: strings.Join(said, "; ")})
	}
	out.Live.Rows = rows
	if _, renderer := g.has("# Renderer: "); renderer {
		if len(g.trailer) != 0 {
			return out, fmt.Errorf("a renderer golden with a trailer: %q", g.trailer[0])
		}
		out.Start = "a synthetic report, no calls"
		return out, nil
	}
	return out, readReportTrailer(g, &out)
}

const (
	reportRow   = "report"
	reportWhole = "whole"
	exportRow   = "export"
)

// readReportTrailer reads a screen run's four sections, in their order: what the
// mocks were asked and the tools run, which must only read, and are recorded,
// with their counts; the working directory, whose change is what the run wrote.
func readReportTrailer(g golden, out *parity.LegacyRead) error {
	sections := []string{"# What the host-info service asked of the mocks", "# The tools the screen ran itself", "# The working directory before:", "# The working directory afterwards:"}
	part := -1
	tools := map[string]int{}
	var toolOrder, start []string
	var entries [2][]dirItem
	var last *dirItem
	for _, l := range g.trailer {
		if part+1 < len(sections) && strings.HasPrefix(l, sections[part+1]) {
			part, last = part+1, nil
			continue
		}
		switch part {
		case 0:
			m := asked.FindStringSubmatch(l)
			if m == nil {
				return fmt.Errorf("a call of the mocks the reader does not know: %q", l)
			}
			if m[2] == "exec" && m[4] != "ok" {
				return fmt.Errorf("a command that failed, which the reader does not compare: %q", l)
			}
			if m[2] == "exec" && !mockRead.MatchString(m[3]) {
				return fmt.Errorf("a command the reader does not take to only read: %q", l)
			}
			if m[2] == "read" {
				start = append(start, m[3]+" -> "+m[4])
			}
			out.Live.Probes = append(out.Live.Probes, m[1]+"x "+m[2]+" "+m[3]+" -> "+m[4])
		case 1:
			name, ok := strings.CutPrefix(l, "#   ")
			switch {
			case !ok || !toolRead.MatchString(name):
				if name != "(none)" {
					return fmt.Errorf("a tool the reader does not take to only read: %q", l)
				}
			default:
				if tools[name] == 0 {
					toolOrder = append(toolOrder, name)
				}
				tools[name]++
			}
		case 2, 3:
			if c, ok := strings.CutPrefix(l, "#     | "); ok && last != nil {
				last.lines = append(last.lines, c)
				continue
			}
			if l == "#   (none)" {
				continue
			}
			m := dirEntry.FindStringSubmatch(l)
			if m == nil {
				return fmt.Errorf("a working directory line the reader does not know: %q", l)
			}
			mode, err := strconv.ParseUint(m[3], 8, 32)
			if err != nil {
				return err
			}
			d := dirItem{path: m[1], dir: m[2] == "/", mode: fs.FileMode(mode)}
			entries[part-2] = append(entries[part-2], d)
			last = &entries[part-2][len(entries[part-2])-1]
		default:
			return fmt.Errorf("a trailer line the reader does not know: %q", l)
		}
	}
	if part != len(sections)-1 {
		return fmt.Errorf("no %q section", sections[part+1])
	}
	for _, name := range toolOrder {
		out.Live.Probes = append(out.Live.Probes, fmt.Sprintf("%dx tool %s", tools[name], name))
	}
	for _, b := range entries[0] {
		start = append(start, "./"+b.path+" "+fmt.Sprintf("%04o", uint32(b.mode)))
		if !slices.ContainsFunc(entries[1], func(a dirItem) bool { return a.path == b.path }) {
			return fmt.Errorf("%s gone afterwards, which the reader does not compare", b.path)
		}
	}
	for _, a := range entries[1] {
		switch i := slices.IndexFunc(entries[0], func(b dirItem) bool { return b.path == a.path }); {
		case i >= 0 && slices.Equal(entries[0][i].lines, a.lines) && entries[0][i].mode == a.mode:
		case a.dir:
			out.Live.Dirs = append(out.Live.Dirs, fmt.Sprintf("%s %04o", a.path, uint32(a.mode)))
		default:
			out.Live.Files = append(out.Live.Files, parity.FileWrite{Path: a.path, Mode: a.mode, Lines: a.lines})
		}
	}
	out.Start = strings.Join(start, "; ")
	return nil
}

// dirItem is one entry of a working directory section.
type dirItem struct {
	path  string
	dir   bool
	mode  fs.FileMode
	lines []string
}

// The Logs screen's lines (pkg/menu logs_menu.go; file_logs_repository.go) and
// logging.PrintLogs', past plain.
var (
	logFileLine = regexp.MustCompile(`^/tmp-root(\S+); hardn writes /tmp-root/var/log/hardn\.log \(/tmp-root stands for /\)$`)
	logCount    = regexp.MustCompile(`^(\d+) lines, (\d+) bytes;`)
	logFrame    = regexp.MustCompile(`^(?:~+|View Logs|Log Contents:|-+|-  Press Enter to return to the main menu\.\.\.)$`)
	logPath     = regexp.MustCompile(`^-  Log file: /tmp-root(\S+)$`)
	logContents = regexp.MustCompile(`^# Contents of /tmp-root(\S+):$`)
	logFailed   = regexp.MustCompile(`^(?:✗ (Error displaying logs: .+)|(\[ERROR\] Failed to read log file .+))$`)
	logElided   = regexp.MustCompile(`^<(\d+) lines this golden leaves out>$`)
	logCall     = regexp.MustCompile(`^\s+\d+ (stat|read)\s+(\S+) -> (.+)$`)
	logBytes    = regexp.MustCompile(`^(\d+) bytes$`)
	logStamp    = regexp.MustCompile(`\d{4}/\d{2}/\d{2} \d{2}:\d{2}:\d{2}`)
)

const (
	pagerLine     = "less, on PATH, a stand-in that records being run; not run."
	startupLine   = "<date> <time> INFO: Line written at start-up"
	logStampMask  = "<date> <time>"
	logCallsLine  = "# The repository's calls:"
	logHeldLine   = "# What hardn's log holds afterwards, the date and time masked:"
	logRawEscape  = `\x1b`
	rowFile       = "file read"
	rowState      = "state"
	rowSize       = "size"
	rowShown      = "lines shown"
	rowLines      = "lines"
	rowRaw        = "raw escape"
	rowPager      = "pager"
	rowHeading    = "-p heading"
	rowWritten    = "log written"
	rowElsewhere  = "logFile elsewhere"
	stateLines    = "lines"
	stateNoWords  = "no words"
	rowParseKept  = "parser lines kept"
	rowParseLevel = "parser levels"
	rowParseLong  = "parser long line"
)

// lastLines is lines as a row: all of a short log, or the end of a long one, as
// the golden keeps it.
func lastLines(lines []string, total int) string {
	if total > 8 {
		return "... " + strings.Join(lines[len(lines)-3:], "; ")
	}
	return strings.Join(lines, "; ")
}

// readLog reads a Logs golden: the file read, what was shown or said, the
// repository's calls, and what hardn's log held after. A line or a call it does
// not know fails, and so does a golden with no $PAGER line, which says the pager
// did not run, or no log's heading and no failure.
func readLog(g golden) (parity.LegacyRead, error) {
	var out parity.LegacyRead
	v, _ := g.has("# logFile: ")
	m := logFileLine.FindStringSubmatch(v)
	if m == nil {
		return out, fmt.Errorf("no logFile line the reader knows: %q", v)
	}
	logFile := m[1]
	if v, _ := g.has("# $PAGER: "); v != pagerLine {
		return out, fmt.Errorf("no $PAGER line the reader knows: %q", v)
	}
	_, flag := g.has("# Operation: ")
	const (
		before = iota
		heading
		inLog
		after
	)
	part := before
	var lines []string
	shown, failed := false, ""
	total := 0
	for _, raw := range g.body {
		text, ok := strings.CutSuffix(raw, "$")
		if !ok {
			return out, fmt.Errorf("a line of the screen with no end marker: %q", raw)
		}
		switch part {
		case heading:
			if text != "" {
				return out, fmt.Errorf("no blank line after the log's heading: %q", raw)
			}
			part = inLog
			continue
		case inLog:
			if text == "" {
				part = after
				continue
			}
			if e := logElided.FindStringSubmatch(text); e != nil {
				n, err := strconv.Atoi(e[1])
				if err != nil {
					return out, err
				}
				total += n
				continue
			}
			lines, total = append(lines, text), total+1
			continue
		}
		l, err := plain(raw)
		if err != nil {
			return out, err
		}
		c, f := logContents.FindStringSubmatch(l), logFailed.FindStringSubmatch(l)
		p := logPath.FindStringSubmatch(l)
		switch {
		case l == "", logFrame.MatchString(l):
		case p != nil && p[1] == logFile:
		case c != nil && c[1] == logFile && part == before:
			part, shown = heading, true
		case f != nil && part == before && failed == "":
			failed = strings.ReplaceAll(f[1]+f[2], "/tmp-root", "")
		default:
			return out, fmt.Errorf("a line of the screen the reader does not know: %q", raw)
		}
	}
	if shown == (failed != "") {
		return out, errors.New("neither the log's heading nor a failure, or both: a run the reader does not compare")
	}
	if v, ok := g.has("# Log: "); ok {
		c := logCount.FindStringSubmatch(v)
		if c == nil || c[1] != strconv.Itoa(total) {
			return out, fmt.Errorf("the Log line says %q, and the screen holds %d lines", v, total)
		}
	}
	rows := []parity.Row{{Name: rowFile, Value: logFile}}
	switch {
	case failed != "":
		rows = append(rows, parity.Row{Name: rowState, Value: failed})
	case total == 0:
		rows = append(rows, parity.Row{Name: rowState, Value: stateNoWords})
	default:
		rows = append(rows, parity.Row{Name: rowState, Value: stateLines},
			parity.Row{Name: rowShown, Value: fmt.Sprintf("all %d", total)},
			parity.Row{Name: rowLines, Value: lastLines(lines, total)},
			parity.Row{Name: rowRaw, Value: rawWord(strings.Contains(strings.Join(lines, "\n"), logRawEscape))})
	}
	rows = append(rows, parity.Row{Name: rowPager, Value: "$PAGER less set, not run"})
	if flag && shown {
		rows = append(rows, parity.Row{Name: rowHeading, Value: "# Contents of " + logFile + ":"})
	}
	var held []string
	section := ""
	if calls := countOf(g.trailer, logCallsLine); calls > 1 || flag == (calls == 1) {
		return out, fmt.Errorf("%d sections of the repository's calls, where -p is %t", calls, flag)
	}
	if countOf(g.trailer, logHeldLine) > 1 {
		return out, errors.New("two sections of what hardn's log holds")
	}
	for _, l := range g.trailer {
		if l == logCallsLine || l == logHeldLine {
			section = l
			continue
		}
		switch section {
		case logCallsLine:
			c := logCall.FindStringSubmatch(l)
			if c == nil {
				return out, fmt.Errorf("a call the reader does not know: %q", l)
			}
			if strings.TrimPrefix(c[2], "/tmp-root") != logFile {
				return out, fmt.Errorf("a call on another file than logFile, %s: %q", logFile, l)
			}
			res := strings.ReplaceAll(c[3], "/tmp-root", "")
			out.Live.Probes = append(out.Live.Probes, c[1]+" "+strings.TrimPrefix(c[2], "/tmp-root")+" -> "+res)
			if b := logBytes.FindStringSubmatch(res); b != nil && c[1] == "read" {
				rows = append(rows, parity.Row{Name: rowSize, Value: res})
				out.Start = "the file read holds " + res
			}
		case logHeldLine:
			h, ok := strings.CutPrefix(l, "#   ")
			if !ok {
				return out, fmt.Errorf("a line of the log the reader does not know: %q", l)
			}
			held = append(held, strings.ReplaceAll(h, "/tmp-root", ""))
		default:
			return out, fmt.Errorf("a trailer line the reader does not know: %q", l)
		}
	}
	if slices.Contains(g.trailer, logHeldLine) {
		var wrote []string
		for _, h := range held {
			printed := slices.ContainsFunc(lines, func(p string) bool { return logStamp.ReplaceAllString(p, logStampMask) == h })
			if h != startupLine && !printed {
				wrote = append(wrote, h)
			}
		}
		rows = append(rows, parity.Row{Name: rowWritten, Value: parity.Joined(wrote)})
	}
	out.Live.Rows = rows
	return out, nil
}

// countOf is how many of lines are line.
func countOf(lines []string, line string) int {
	n := 0
	for _, l := range lines {
		if l == line {
			n++
		}
	}
	return n
}

// rawWord says whether a line's escape reaches the output as it is.
func rawWord(raw bool) string {
	if raw {
		return "raw"
	}
	return "none"
}

// parserEntry is an entry of GetLogs as its golden prints it: unknown fields fail.
type parserEntry struct{ Level, Message, Time string }

// readEntry is the JSON line l, an entry.
func readEntry(l string) (parserEntry, error) {
	var e parserEntry
	dec := json.NewDecoder(strings.NewReader(l))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&e); err != nil {
		return e, fmt.Errorf("%q: %w", l, err)
	}
	return e, nil
}

// splitEntries is what GetLogs makes of written lines, a line split on its first
// two spaces, and one with fewer than three words dropped (file_logs_repository.go:51-57).
func splitEntries(written []string) []parserEntry {
	var out []parserEntry
	for _, w := range written {
		if f := strings.SplitN(w, " ", 3); len(f) == 3 {
			out = append(out, parserEntry{Time: f[0], Level: f[1], Message: f[2]})
		}
	}
	return out
}

// readParser reads logs_parser: for each block, the lines written and GetLogs'
// entries, each held to its line's split, the first block's levels and how many
// lines it kept, the second's long line, where the entries stop at that line; then
// the callers, recorded. Its lines' date and time are masked.
func readParser(g golden) (parity.LegacyRead, error) {
	var out parity.LegacyRead
	type block struct {
		written []string
		said    int
		entries []parserEntry
	}
	var blocks []*block
	inEntries := false
	for _, l := range g.body {
		var n int
		var failed string
		switch {
		case l == "# Written, line by line:":
			blocks, inEntries = append(blocks, &block{}), false
		case len(blocks) == 0:
			return out, fmt.Errorf("a line before the first block: %q", l)
		case !inEntries && strings.HasPrefix(l, `"`):
			w, err := strconv.Unquote(l)
			if err != nil {
				return out, fmt.Errorf("%q: %w", l, err)
			}
			blocks[len(blocks)-1].written = append(blocks[len(blocks)-1].written, w)
		case strings.HasPrefix(l, "# GetLogs: "):
			if _, err := fmt.Sscanf(l, "# GetLogs: %d entries, error %s", &n, &failed); err != nil || failed != "<nil>" {
				return out, fmt.Errorf("a GetLogs line the reader does not know: %q", l)
			}
			blocks[len(blocks)-1].said, inEntries = n, true
		case inEntries && strings.HasPrefix(l, "{"):
			e, err := readEntry(l)
			if err != nil {
				return out, err
			}
			blocks[len(blocks)-1].entries = append(blocks[len(blocks)-1].entries, e)
		default:
			return out, fmt.Errorf("a line of the parser's record the reader does not know: %q", l)
		}
	}
	if len(blocks) != 2 {
		return out, fmt.Errorf("%d blocks, where the reader takes two: the lines hardn writes, and the long line", len(blocks))
	}
	for _, b := range blocks {
		if len(b.entries) != b.said {
			return out, fmt.Errorf("GetLogs says %d entries, and the record holds %d", b.said, len(b.entries))
		}
		if split := splitEntries(b.written); len(b.entries) > len(split) || !slices.Equal(b.entries, split[:len(b.entries)]) {
			return out, fmt.Errorf("the entries %+v are not the written lines' split, %+v", b.entries, split)
		}
	}
	a, long := blocks[0], blocks[1]
	var levels []string
	for _, e := range a.entries {
		levels = append(levels, e.Level)
	}
	out.Start = strings.Join(a.written, "; ")
	out.Live.Rows = []parity.Row{
		{Name: rowParseKept, Value: fmt.Sprintf("%d of %d lines", a.said, len(a.written))},
		{Name: rowParseLevel, Value: levelCounts(levels)},
		{Name: rowParseLong, Value: fmt.Sprintf("%d of %d lines, no error", long.said, len(long.written))},
	}
	for _, l := range g.trailer {
		v, ok := strings.CutPrefix(l, "#   ")
		switch {
		case ok:
			out.Live.Probes = append(out.Live.Probes, "the code calls "+v)
		case !strings.HasPrefix(l, "# The calls of GetLogs and PrintLogs"):
			return out, fmt.Errorf("a trailer line the reader does not know: %q", l)
		}
	}
	return out, nil
}

// levelCounts is levels, each once with its count, in the order first seen.
func levelCounts(levels []string) string {
	count := map[string]int{}
	var order []string
	for _, l := range levels {
		if count[l] == 0 {
			order = append(order, l)
		}
		count[l]++
	}
	var out []string
	for _, l := range order {
		out = append(out, fmt.Sprintf("%s %d", parity.OrElse(l, "none"), count[l]))
	}
	return strings.Join(out, ", ")
}

