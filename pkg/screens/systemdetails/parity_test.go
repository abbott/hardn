// holdOneRead fails unless each draw of the run from the nth call on read each of
// paths once, and ran each of the commands the readers run once where it ran it at
// all: a driver held to one read a draw, where origin/main reads each four times
// (defect 20).
func holdOneRead(t *testing.T, h *hostfake.System, n, draws int, paths ...string) {
	t.Helper()
	count := map[string]int{}
	for _, c := range h.Calls()[n:] {
		switch {
		case c.Op == "read" || c.Op == "scan-lines":
			count[c.Path]++
		case c.Op == "run" && slices.Contains(oneADraw, c.Argv[0]):
			count[c.Argv[0]]++
		}
	}
	for _, p := range paths {
		if count[p] != draws {
			t.Errorf("%s read %d times in %d draws", p, count[p], draws)
		}
	}
	for _, tool := range oneADraw {
		if got := count[tool]; got != 0 && got != draws {
			t.Errorf("%s ran %d times in %d draws", tool, got, draws)
		}
	}
}

