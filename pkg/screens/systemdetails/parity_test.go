// TestTiesCiteTheirGoldens: an entry citing a KNOWN-DEFECT line cites one that
// every cell's golden holds, by a phrase of it.
func TestTiesCiteTheirGoldens(t *testing.T) {
	cited := regexp.MustCompile(`KNOWN-DEFECT \(([^)]+)\)`)
	golden := map[string]string{}
	for _, sc := range sdParity.Scenarios {
		golden[sc.Name] = sc.Golden
	}
	for _, e := range table() {
		for _, m := range cited.FindAllStringSubmatch(e.source, -1) {
			for _, s := range e.scenarios {
				data, err := os.ReadFile(filepath.Join(legacyDir, filepath.FromSlash(golden[s])))
				if err != nil {
					t.Fatal(err)
				}
				if !slices.ContainsFunc(strings.Split(string(data), "\n"), func(l string) bool {
					return strings.HasPrefix(l, "# KNOWN-DEFECT: ") && strings.Contains(l, m[1])
				}) {
					t.Errorf("%s, %s: cites a KNOWN-DEFECT line with %q, which %s does not hold", s, e.aspect, m[1], golden[s])
				}
			}
		}
	}
}
