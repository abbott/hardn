// setuidTools adds the setuid bit hostfake's Stat cannot show, as a real sudo and
// doas have it (details_test.go's fakeHost).
type setuidTools struct{ *hostfake.System }

func (h setuidTools) Stat(ctx context.Context, name string) (fs.FileInfo, error) {
	fi, err := h.System.Stat(ctx, name)
	if err == nil && (name == "/usr/bin/sudo" || name == "/usr/bin/doas") {
		return setuidInfo{fi}, nil
	}
	return fi, err
}

type setuidInfo struct{ fs.FileInfo }

func (i setuidInfo) Mode() fs.FileMode { return i.FileInfo.Mode() | fs.ModeSetuid }

