// readOps are the calls that only read.
var readOps = []string{"read", "read-nofollow", "scan-lines", "stat", "lstat", "readdir", "readlink", "resolve-symlink", "lookup-user", "lookup-group", "run"}

// recordOf is what h's record holds from the nth call on, holding it to reads:
// any other call fails the test, a pager run among them. A run is one of
// readCommands, or the cell's commands aspect differs.
func recordOf(t *testing.T, h *hostfake.System, n int) string {
	t.Helper()
	var ops []string
	for _, c := range h.Calls()[n:] {
		if !slices.Contains(readOps, c.Op) {
			t.Errorf("a call that does not only read: %s", c)
		}
		if !slices.Contains(ops, c.Op) {
			ops = append(ops, c.Op)
		}
	}
	slices.Sort(ops)
	return "hostfake's record: " + parity.Joined(ops) + "; nothing written"
}

// writtenContent is what both wrote: no cell, as the new path writes nothing; a
