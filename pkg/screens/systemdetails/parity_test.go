// cpuinfo is /proc/cpuinfo for n logical CPUs on sockets sockets. The golden's
// file holds one processor line (75 bytes) and its nproc and lscpu stand-ins say 2
// and 1, which origin/main's row takes; the new path reads this file alone, so
// it says what they said.
func cpuinfo(model string, n, sockets int) string {
	var b strings.Builder
	for i := range n {
		fmt.Fprintf(&b, "processor\t: %d\nmodel name\t: %s\nphysical id\t: %d\n\n", i, model, i%sockets)
	}
	return b.String()
}

// zfsRoot makes the root a dataset of the pool, zpool answering ONLINE.
func zfsRoot(dataset string) func(*fixture) {
	return func(f *fixture) {
		pool, _, _ := strings.Cut(dataset, "/")
		f.pool, f.dataset = pool, dataset
		f.mounts = "proc /proc proc rw,nosuid,nodev,noexec,relatime 0 0\n" + dataset + " / zfs rw,relatime,xattr,noacl 0 0\n"
	}
}

