// holdsWhole says that e holds line: a logger's line in its parts, any other in
// Message alone.
func holdsWhole(line string, e logview.Entry) bool {
	if e.Level == "" {
		return e.Time == "" && e.Message == line
	}
	return e.Time+" "+e.Level+": "+e.Message == line
}

