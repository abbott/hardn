// reportHost is f on d: the golden's files, and what only the new path reads.
func reportHost(f *fixture, d parity.Distro) *hostfake.System {
	h := hostfake.New(host.Options{})
	add := func(p, data string) { h.AddFile(p, []byte(data), 0o644, 0, 0) }
	add(detect.EtcOSRelease, f.osRelease)
	add(details.CPUInfoFile, f.cpu)
	add(details.LoadAvgFile, f.load)
	add(details.SelfStatusFile, rootStatus)
	add("/proc/uptime", f.uptime)
	add("/proc/sys/kernel/osrelease", f.kernel)
	add("/proc/sys/kernel/hostname", f.hostname)
	add(detect.SelfMounts, f.mounts)
	add("/etc/passwd", f.passwd)
	add("/etc/group", f.group)
	if !f.noMemInfo {
		add(details.MemInfoFile, f.memInfo)
	}
	alpine := d.Name == alpine323.Name
	dpkg := hostfake.Response{Stderr: "dpkg-query: no packages found matching pve-manager\n", ExitCode: 1}
	if alpine {
		dpkg = hostfake.Response{Err: fmt.Errorf("host: %q: not in %s: %w", "dpkg-query", host.SearchPath, host.ErrNotFound)}
	}
	h.Respond(dpkg, "dpkg-query", "--show", "--showformat=${Status}\\t${Version}\\n", "pve-manager")
	cmds := map[string]hostfake.Response{
		"ip -o addr show scope global": {Stdout: f.addrs},
		"df -kP /":                     {Stdout: f.df},
	}
	if f.pool != "" {
		cmds["zpool list -H -o health "+f.pool] = hostfake.Response{Stdout: "ONLINE\n"}
		cmds["zfs get -Hp -o value used,available "+f.dataset] = hostfake.Response{Stdout: zfsFigures}
	}
	if alpine {
		h.AddFile("/usr/bin/doas", []byte("ELF"), 0o4755, 0, 0)
		h.AddFile("/etc/doas.conf", []byte("permit persist alice\n"), 0o640, 0, 0)
		h.AddDir("/etc/doas.d", 0o750, 0, 0)
		cmds["doas -C /etc/doas.conf"] = hostfake.Response{}
	} else {
		h.AddFile("/usr/bin/sudo", []byte("ELF"), 0o4755, 0, 0)
		h.AddFile("/etc/sudoers", []byte(sudoersOn), 0o440, 0, 0)
		h.AddDir("/etc/sudoers.d", 0o750, 0, 0)
		h.AddFile(details.WtmpFile, []byte(wtmpRecord), 0o664, 0, 43)
		cmds["sudo --version"] = hostfake.Response{Stdout: "Sudo version 1.9.16p2\n"}
		cmds["visudo -c"] = hostfake.Response{Stdout: "/etc/sudoers: parsed OK\n"}
	}
	h.Handler = func(argv []string, _ []byte) hostfake.Response {
		if argv[0] == "lslogins" {
			if alpine {
				return hostfake.Response{Err: fmt.Errorf("host: %q: not in %s: %w", "lslogins", host.SearchPath, host.ErrNotFound)}
			}
			var b strings.Builder
			for _, name := range strings.Split(argv[len(argv)-1], ",") {
				if l, ok := f.logins[name]; ok {
					b.WriteString(name + " " + l + "\n")
				} else {
					b.WriteString(name + "   \n")
				}
			}
			return hostfake.Response{Stdout: b.String()}
		}
		if r, ok := cmds[strings.Join(argv, " ")]; ok {
			return r
		}
		return hostfake.Response{Err: fmt.Errorf("%s: %w", argv[0], hostfake.ErrUnscripted)}
	}
	return h
}

