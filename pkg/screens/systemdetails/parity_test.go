// logRun is logview on r: Read, Elsewhere and, where there are lines, Pager, as
// the Logs screen is to; for -p off a terminal, Each. The log's bytes are held to
// be as they were, from hostfake's record.
func logRun(t *testing.T, c parity.Cell, r logRowSpec) parity.NewRun {
	t.Helper()
	h := logHost(r, c.Distro)
	ctx := context.Background()
	n := len(h.Calls())
	var sys host.System = h
	if r.refused {
		sys = refusingScan{h}
	}
	var rows []parity.Row
	var reading logview.Reading
	var lines []string
	via := "logview.Read, logview.Elsewhere"
	if r.flag {
		via = "logview.Each, logview.Elsewhere"
		reading = logview.Each(ctx, sys, func(l logview.Line) bool {
			lines = append(lines, l.Text)
			return true
		})
	} else {
		reading = logview.Read(ctx, sys)
		for _, l := range reading.Last {
			lines = append(lines, l.Text)
		}
	}
	var each []string
	logview.Each(ctx, sys, func(l logview.Line) bool {
		each = append(each, l.Text)
		return true
	})
	if !slices.Equal(each[max(0, len(each)-logview.MaxLast):], lines) {
		t.Errorf("Each's last lines are not Read's: %d lines against %d", len(each), len(lines))
	}
	rows = append(rows, parity.Row{Name: rowFile, Value: reading.Path})
	switch reading.State {
	case logview.Lines:
		shown := fmt.Sprintf("last %d of %d", len(lines), reading.Total)
		if r.flag {
			shown = fmt.Sprintf("all %d", len(lines))
		}
		rows = append(rows, parity.Row{Name: rowState, Value: stateLines}, parity.Row{Name: rowShown, Value: shown},
			parity.Row{Name: rowLines, Value: lastLines(lines, reading.Total)},
			parity.Row{Name: rowRaw, Value: rawWord(strings.ContainsAny(strings.Join(lines, "\n"), "\x1b\x07"))})
	case logview.NoLog:
		rows = append(rows, parity.Row{Name: rowState, Value: "NoLog"})
	case logview.Empty:
		rows = append(rows, parity.Row{Name: rowState, Value: "Empty"})
	case logview.Unreadable:
		rows = append(rows, parity.Row{Name: rowState, Value: "Unreadable: " + reading.Reason})
	}
	if !r.flag && (reading.State == logview.Lines || reading.State == logview.Empty) {
		rows = append(rows, parity.Row{Name: rowSize, Value: fmt.Sprintf("%d bytes", reading.Size)})
	}
	if !r.flag && reading.State == logview.Lines {
		via += ", logview.Pager"
		if p, ok := logview.Pager(ctx, sys, "xterm-256color"); ok {
			rows = append(rows, parity.Row{Name: rowPager, Value: strings.Join(p.Argv, " ") + "; " + strings.Join(p.Env, " ")})
		}
	}
	if e := logview.Elsewhere(r.logFile); e != "" {
		rows = append(rows, parity.Row{Name: rowElsewhere, Value: e})
	}
	if e, ok := h.Entry(logview.File); ok && string(e.Data) != r.log {
		rows = append(rows, parity.Row{Name: rowWritten, Value: "the file changed"})
	}
	s := parity.NewState(t, h, n, readCommands, "")
	s.Rows = rows
	return parity.NewRun{Live: s, Via: via + "; " + recordOf(t, h, n)}
}

