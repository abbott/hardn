// factRows are the report's facts by readers-system-details.md §7's map, under
// the label of origin/main's row each replaces, in origin/main's form where the
// fact is the same, so that the same numbers agree. The first is the report.
func factRows(r details.Report) []parity.Row {
	var rows []parity.Row
	add := func(name, value string) {
		if value != "" {
			rows = append(rows, parity.Row{Name: name, Value: value})
		}
	}
	os := strings.TrimSpace(r.OS.OS.Name + " " + r.OS.OS.Version + " " + r.OS.OS.Codename)
	add("OS", os)
	add("Kernel", r.OS.Kernel)
	add("Hostname", r.Host.Hostname)
	var ips []string
	for _, a := range r.Host.Addresses {
		ips = append(ips, a.Interface+" "+a.Address)
	}
	add("IP Addresses", strings.Join(ips, ", "))
	var users []string
	for _, u := range r.Users.List {
		tool, grant := u.Admin()
		switch grant {
		case detect.Yes:
			users = append(users, u.Name+" ("+tool+")")
		case detect.No:
			users = append(users, u.Name+" (No "+r.Users.Tool+")")
		default:
			users = append(users, u.Name+" (Not known)")
		}
	}
	add("Non-System Users", strings.Join(users, ", "))
	add("Processor", r.CPU.Model)
	if r.CPU.CPUs > 0 {
		add("Cores", fmt.Sprintf("%d vCPU(s) / %d Socket(s)", r.CPU.CPUs, r.CPU.Sockets))
	}
	add("Load 1m", r.CPU.Load[0])
	add("Load 5m", r.CPU.Load[1])
	add("Load 15m", r.CPU.Load[2])
	if r.Disk.Source != "" {
		add("/", r.Disk.Source+" "+r.Disk.Type)
	}
	if r.Disk.Known {
		add("Volume", sizes(r.Disk.Used, r.Disk.Total))
	}
	if r.Disk.Pool != "" {
		add("ZFS Health", r.Disk.Pool+" "+r.Disk.Health)
	}
	if used, ok := r.Memory.Used(); ok {
		add("Memory", sizes(used, r.Memory.Total))
	}
	var when, from []string
	if r.Logins.State == details.LoginsNoTool {
		when = append(when, loginsNoTool)
	}
	for _, l := range r.Logins.List {
		switch l.State {
		case details.LoginAt:
			when = append(when, l.User+" "+l.When)
			if l.From != "" {
				from = append(from, l.User+" "+l.From)
			}
		case details.LoginNone:
			when = append(when, l.User+" LoginNone")
		default:
			when = append(when, l.User+" LoginUnknown")
		}
	}
	add("Last Login", strings.Join(when, ", "))
	add("From", strings.Join(from, ", "))
	if r.OS.Uptime.Known {
		add("Uptime", output.FormatUptime(r.OS.Uptime.Duration))
	}
	return append([]parity.Row{{Name: reportRow, Value: keptWords(r, rows)}}, rows...)
}

// sizes is used and total in GiB and the percentage, in origin/main's form, GiB
// for its Volume row's mislabelled GB.
func sizes(used, total uint64) string {
	const gib = 1024 * 1024 * 1024
	return fmt.Sprintf("%.2f/%.2f GiB [%.2f%%]", float64(used)/gib, float64(total)/gib, 100*float64(used)/float64(total))
}

// loginsNoTool is the state with no lslogins, no fact of a login.
const loginsNoTool = "LoginsNoTool"

// keptWords says what the report kept: whole, or the rows that hold a fact and what
// of which section it could not read, in readers §9's section words.
func keptWords(r details.Report, rows []parity.Row) string {
	var not []string
	for _, s := range []struct {
		name   string
		unread []details.Unread
	}{{"os and kernel", r.OS.Unread}, {"host and ips", r.Host.Unread}, {"users", r.Users.Unread}, {"cpu and load", r.CPU.Unread},
		{"disk", r.Disk.Unread}, {"memory", r.Memory.Unread}, {"last login", r.Logins.Unread}} {
		for _, u := range s.unread {
			not = append(not, s.name+": "+u.Source)
		}
	}
	if len(not) == 0 {
		return reportWhole
	}
	var kept []string
	for _, row := range rows {
		if row.Value != loginsNoTool {
			kept = append(kept, row.Name)
		}
	}
	return "kept " + strings.Join(kept, ", ") + "; not read: " + strings.Join(not, ", ")
}

