// isRead: a command that only reads, recorded and not compared.
func isRead(cmd string) bool {
	for _, p := range []string{"ufw status", "ss ", "systemctl is-enabled ", "systemctl is-active ", "systemctl show ", "dpkg-query ", "apk info ", "apt-get install -s ", "apk add --simulate ", "sshd -T", "/usr/sbin/sshd -T"} {
		if strings.HasPrefix(cmd, p) {
			return true
		}
	}
	return false
}

// stateOf is the end state h's calls from the nth on left.
func stateOf(t *testing.T, h *fwHost, n int) parity.EndState {
	t.Helper()
	var reads []string
	for _, c := range h.Calls()[n:] {
		if c.Op == "run" {
			if f := host.FormatArgv(c.Argv); isRead(f) {
				reads = append(reads, f)
			}
		}
	}
	s := parity.NewState(t, h.System, n, reads, yml)
	s.Actions = slices.DeleteFunc(s.Actions, timerCommand)
	return s
}

// rowsOf are the new path's rows from h as the run left it.
func rowsOf(h *fwHost, s parity.EndState, asks string) []parity.Row {
	state := "inactive"
	switch {
	case h.missing:
		state = "not installed"
	case h.active:
		state = "active"
	}
	lines, added := 0, []string{}
	for _, r := range h.rules {
		if r.start {
			lines += 2
		} else {
			added = append(added, r.words())
		}
	}
	return endRows(state, rulesAfter(lines, added), s.Actions, h.fail, asks)
}

// newEngine is a change's engine on h, as cmd/hardn builds it.
func newEngine(h *fwHost) func(progress func(engine.Event)) *engine.Engine {
	return func(progress func(engine.Event)) *engine.Engine {
		return engine.New(h, engine.Options{
			Revert:   revert.Options{Now: clock, Hardn: hardnBinary},
			Detect:   func(context.Context, host.System) (detect.Facts, error) { return h.facts, nil },
			Hold:     func() func() { return func() {} },
			PID:      5000,
			Session:  h.session(),
			Backups:  backup.Settings{Path: backup.DefaultPath, Enabled: true},
			Progress: progress,
		})
	}
}

