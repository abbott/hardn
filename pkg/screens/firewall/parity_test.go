// TestOpenDifferences: what firewall_open_status_fails_reads_inactive and
// firewall_open_port_* show, which are not rows (no end state): a failing status
// reads Inactive on origin/main; here ufw's state is not established, and Enable
// refuses. The SSH Port row is cfg.SshPort's on origin/main; here what is read of
// sshd, whatever hardn.yml says, and no port is called better than another.
func TestOpenDifferences(t *testing.T) {
	ctx := context.Background()
	h := newHost(t, "debian", start{statusFails: true})
	r := firewall.Read(ctx, h, h.facts, loaded(t, h, start{}), h.session())
	if r.StateErr == nil || r.First != firewall.ItemEnable || output.CodeOf(r.PlanErr) != "UFW_STATE_UNKNOWN" {
		t.Errorf("a failing status: state error %v, item %d, plan %v", r.StateErr, r.First, r.PlanErr)
	}
	h = newHost(t, "debian", start{sshd: 22})
	r = firewall.Read(ctx, h, h.facts, loaded(t, h, start{sshd: 22}), h.session())
	if got := r.Sockets.Ports(); !slices.Equal(got, []uint16{22}) {
		t.Errorf("sshd on 22, cfg.SshPort 2230: the row reads %v", got)
	}
}

// TestNotRowKeys: three of TestParityGoldens' not-rows through the screen,
// each changing nothing. With no ufw, origin/main's hidden items still ran: key
// 2, its Configure firewall (no-ufw-item2's), and key 3, its profiles, which
// opened (firewall_profiles_not_installed_hidden_still_runs); each is now
// refused as no item, and no sub-screen opens. A number no profile has, 9, is
// refused at Remove's Select and asked again (firewall_profiles_remove_bad_number).
func TestNotRowKeys(t *testing.T) {
	for _, tt := range []struct {
		st      start
		lines   []string
		exits   int
		refused string
	}{
		{start{missing: true}, []string{"2"}, 1, nav.InvalidOption},
		{start{missing: true}, []string{"3"}, 1, nav.InvalidOption},
		{start{profiles: 2}, []string{"2", "2", "9", "0"}, 2, nav.InvalidOption},
	} {
		h := newHost(t, "debian", tt.st)
		cfg := loaded(t, h, tt.st)
		n := len(h.Calls())
		_, out, ran := runScreen(t, h, cfg, false, tt.lines, tt.exits)
		if len(ran) != 0 || strings.Contains(out, "Manage UFW Application Profiles") != (tt.st.profiles > 0) || len(writes(h, n)) > 0 {
			t.Errorf("%q: %d runs, wrote %v:\n%s", tt.lines, len(ran), writes(h, n), out)
		}
		if tt.st.missing && strings.Count(out, tt.refused) != 1 {
			t.Errorf("%q: not refused as no item:\n%s", tt.lines, out)
		}
		if tt.st.profiles > 0 && (inOrder(out, "Remove which profile?", "Enter your choice [1-2, 0 or q]: 9", tt.refused, "Enter your choice") != "" || strings.Contains(out, "[y/N")) {
			t.Errorf("%q: 9 not refused at the Select:\n%s", tt.lines, out)
		}
	}
}

// TestParityGoldens: every golden of origin/main's Firewall is a row of the table
// or a not-row with why, and every one named is there.
func TestParityGoldens(t *testing.T) {
	rowGoldens := map[string]bool{}
	for _, sc := range scenarios {
		for _, d := range distros {
			rowGoldens[strings.ReplaceAll(sc.Golden, "{d}", d.Name)] = true
		}
	}
	var all []string
	for _, pattern := range []string{"menu/firewall_*.golden", "ops/configure_secure_firewall/*.golden", "ops/configure_secure_firewall_profiles/*.golden"} {
		m, err := filepath.Glob(filepath.Join(legacyDir, filepath.FromSlash(pattern)))
		if err != nil {
			t.Fatal(err)
		}
		for _, p := range m {
			rel, err := filepath.Rel(legacyDir, p)
			if err != nil {
				t.Fatal(err)
			}
			all = append(all, filepath.ToSlash(rel))
		}
	}
	if len(all) != 57 {
		t.Errorf("%d goldens, not 49 and 8", len(all))
	}
	for _, g := range all {
		if rowGoldens[g] == (notRows[g] != "") {
			t.Errorf("%s: a row %t, a not-row %t: each golden is one or the other", g, rowGoldens[g], notRows[g] != "")
		}
	}
	for g := range rowGoldens {
		if !slices.Contains(all, g) {
			t.Errorf("row golden %s: not there", g)
		}
	}
	for g := range notRows {
		if !slices.Contains(all, g) {
			t.Errorf("not-row golden %s: not there", g)
		}
	}
}

