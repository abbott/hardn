func (st start) sshdPorts() []uint16 {
	if st.sshd != 0 {
		return []uint16{st.sshd}
	}
	return []uint16{2230}
}

// fixture is the hardn.yml the start holds.
func (st start) fixture() string {
	return []string{"none.yml", "one.yml", "two.yml"}[st.profiles]
}

// words is st as origin/main's golden says it (parity.Cell.LegacyStart).
func (st start) words(d string) string {
	if st.ops {
		return fmt.Sprintf("%s; cfg.SshPort 2230; %d profiles", opsHost[d], st.profiles)
	}
	on := "Debian 13"
	if st.pve {
		on = "Proxmox VE on Debian 13 (/etc/pve there, osdetect saying so)"
	}
	ufwWords := "inactive, no rules"
	switch {
	case st.missing:
		ufwWords = "not installed"
	case st.active && st.ruleOn22:
		ufwWords = "active, rule lines: 2"
	case st.active:
		ufwWords = "active, no rules"
	}
	return fmt.Sprintf("%s; ufw %s; cfg.SshPort 2230; %d profiles; dryRun %t", on, ufwWords, st.profiles, st.dry)
}

// step is one change the row makes: the action, its edit of hardn.yml, the
// answer where it is not the flow's (y, or the hostname typed), and whether the
// screen offers it, as what Read says of item 1. A save is Add's, its answers
// typed, or Remove's of the first profile.
type step struct {
	action firewall.Action
	edit   func(*config.Config)
	answer string
	hidden bool   // no item leads here: the key is typed, and refused as no item
	key    string // the key a hidden step types; "" is 1
	add    *config.UfwAppProfile
	field  string // the field of Add's form that refuses the answer
}

// adding is Add's step with p's answers; field, when set, the field that
// refuses its answer.
func adding(p config.UfwAppProfile, field string) step {
	return step{action: firewall.ActionSaveProfiles, edit: addProfile(p), add: &p, field: field}
}

// removing is Remove's step, of the first profile.
func removing(answer string) step {
	return step{action: firewall.ActionSaveProfiles, edit: dropFirst, answer: answer}
}

// row is a scenario, its start and its steps; flag runs Incoming{ActionEnable}
// as -w, the row's Lines nil. No steps: the open screen, Read alone.
type row struct {
	sc    parity.Scenario
	st    start
	steps []step
	flag  bool
}

func addProfile(p config.UfwAppProfile) func(*config.Config) {
	return func(c *config.Config) { c.UfwAppProfiles = append(slices.Clone(c.UfwAppProfiles), p) }
}

func dropFirst(c *config.Config) {
	c.UfwAppProfiles = slices.Delete(slices.Clone(c.UfwAppProfiles), 0, 1)
}

