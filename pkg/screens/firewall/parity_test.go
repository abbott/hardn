var sshAllow = regexp.MustCompile(`^ufw allow (\d+/tcp)( comment "SSH access")?$`)

// endRows are what a run left of ufw, from its state and commands; failed, the
// command that failed, added nothing, and "commands" still shows it. The default
// policy is no row: no golden says what a start held (parity-firewall.md §2).
func endRows(state, rules string, actions []string, failed, asks string) []parity.Row {
	var ssh []string
	comment, starts, boot, pkgs := "", "", "not changed", "none"
	for _, a := range actions {
		if a == failed {
			continue
		}
		switch {
		case a == `sh -c "yes | ufw enable"`, a == "ufw --force enable":
			starts = a
		case a == "rc-update add ufw default", a == "systemctl enable ufw.service":
			boot = a
		case a == "apt-get install -y ufw", a == "apk add ufw":
			pkgs = "ufw"
		}
		if m := sshAllow.FindStringSubmatch(a); m != nil {
			ssh = append(ssh, m[1])
			if m[2] != "" {
				comment = "SSH access"
			}
		}
	}
	rows := []parity.Row{{Name: rowUFW, Value: state}, {Name: rowRules, Value: rules},
		{Name: rowSSH, Value: parity.Joined(ssh)}, {Name: rowBoot, Value: boot}, {Name: rowPackages, Value: pkgs}, {Name: rowAsks, Value: asks}}
	if comment != "" {
		rows = append(rows, parity.Row{Name: rowComment, Value: comment})
	}
	if starts != "" {
		rows = append(rows, parity.Row{Name: rowStarts, Value: starts})
	}
	return rows
}

// rulesAfter is a run's rules: the lines of the start it kept (each rule two,
// IPv4 and IPv6, as the fixture counts them), then what it added, sorted, as
// both paths add them in another order.
func rulesAfter(lines int, added []string) string {
	sorted := slices.Sorted(slices.Values(added))
	if lines > 0 {
		sorted = append([]string{fmt.Sprintf("the start's %d lines", lines)}, sorted...)
	}
	return parity.Joined(sorted)
}

// profileContent is the profile file's lines, none where a path did not write
// it (parity.Slice.Content).
func profileContent(add func(name, legacy, new string), l, n []parity.FileWrite) {
	lines := func(fs []parity.FileWrite) string {
		for _, f := range fs {
			if f.Path == ufw.ProfileFile {
				return strings.Join(slices.DeleteFunc(slices.Clone(f.Lines), func(s string) bool { return s == "" }), " / ")
			}
		}
		return "none"
	}
	add("profile file", lines(l), lines(n))
}

