// words is st as origin/main's golden says it (parity.Cell.LegacyStart).
func (st start) words(d string) string {
	if st.ops {
		return fmt.Sprintf("%s; cfg.SshPort 2230; %d profiles", opsHost[d], st.profiles)
	}
	on := "Debian 13"
	if st.pve {
		on = "Proxmox VE on Debian 13 (/etc/pve there, osdetect saying so)"
	}
	ufwWords := "inactive, no rules"
	switch {
	case st.missing:
		ufwWords = "not installed"
	case st.active && st.ruleOn22:
		ufwWords = "active, rule lines: 2"
	case st.active:
		ufwWords = "active, no rules"
	}
	return fmt.Sprintf("%s; ufw %s; cfg.SshPort 2230; %d profiles; dryRun %t", on, ufwWords, st.profiles, st.dry)
}

