// cellNote is where origin/main's golden stands for the cell in part: a Debian
// 13 fixture on another distribution, or an ops fixture's other release.
func cellNote(c parity.Cell) string {
	switch {
	case c.Scenario.Name == "install" && c.Distro.Name != "debian", c.Scenario.Name == "install-stock":
		return "origin/main's Debian 13 fixture stands for this distribution: the stub reads no host (firewall_menu.go:186, read)"
	case strings.HasPrefix(c.Scenario.Golden, "ops/") && c.Distro.Name == "ubuntu":
		return "its fixture's host line says Ubuntu 24.04 (noble); the new path runs 26.04, ssh.socket listening, the control's tests' host"
	case c.Scenario.Name == "configure":
		return "origin/main's fixture and sshd disagree (cfg.SshPort 2230, Port 22 in sshd_config): the new path's host says what sshd does, on 22"
	}
	return ""
}

// tie is a parity.Tie written positionally, as the table reads.
type tie struct {
	scenarios, distros  []string
	aspect, source, why string
	pending             bool
}

func ties(table []tie) []parity.Tie {
	out := make([]parity.Tie, len(table))
	for i, e := range table {
		out[i] = parity.Tie{Scenarios: e.scenarios, Distros: e.distros, Aspect: e.aspect, Source: e.source, Why: e.why, Pending: e.pending}
	}
	return out
}

