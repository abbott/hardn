// cellNote is where origin/main's golden stands for the cell in part: a Debian
// 13 fixture on another distribution, or an ops fixture's other release.
func cellNote(c parity.Cell) string {
	switch {
	case c.Scenario.Name == "install" && c.Distro.Name != "debian", c.Scenario.Name == "install-stock":
		return "origin/main's Debian 13 fixture stands for this distribution: the stub reads no host (firewall_menu.go:186, read)"
	case strings.HasPrefix(c.Scenario.Golden, "ops/") && c.Distro.Name == "ubuntu":
		return "its fixture's host line says Ubuntu 24.04 (noble); the new path runs 26.04, ssh.socket listening, the control's tests' host"
	case c.Scenario.Name == "configure":
		return "origin/main's fixture and sshd disagree (cfg.SshPort 2230, Port 22 in sshd_config): the new path's host says what sshd does, on 22"
	}
	return ""
}

// tie is a parity.Tie written positionally, as the table reads.
type tie struct {
	scenarios, distros  []string
	aspect, source, why string
	pending             bool
}

func ties(table []tie) []parity.Tie {
	out := make([]parity.Tie, len(table))
	for i, e := range table {
		out[i] = parity.Tie{Scenarios: e.scenarios, Distros: e.distros, Aspect: e.aspect, Source: e.source, Why: e.why, Pending: e.pending}
	}
	return out
}

const yml = "/etc/hardn/hardn.yml"

var clock = func() time.Time { return time.Date(2026, 11, 2, 12, 0, 0, 0, time.UTC) }

// isRead: a command that only reads, recorded and not compared.
func isRead(cmd string) bool {
	for _, p := range []string{"ufw status", "ss ", "systemctl is-enabled ", "systemctl is-active ", "systemctl show ", "dpkg-query ", "apk info ", "apt-get install -s ", "apk add --simulate ", "sshd -T", "/usr/sbin/sshd -T"} {
		if strings.HasPrefix(cmd, p) {
			return true
		}
	}
	return false
}

// stateOf is the end state h's calls from the nth on left.
func stateOf(t *testing.T, h *fwHost, n int) parity.EndState {
	t.Helper()
	var reads []string
	for _, c := range h.Calls()[n:] {
		if c.Op == "run" {
			if f := host.FormatArgv(c.Argv); isRead(f) {
				reads = append(reads, f)
			}
		}
	}
	s := parity.NewState(t, h.System, n, reads, yml)
	s.Actions = slices.DeleteFunc(s.Actions, timerCommand)
	return s
}

// rowsOf are the new path's rows from h as the run left it.
func rowsOf(h *fwHost, s parity.EndState, asks string) []parity.Row {
	state := "inactive"
	switch {
	case h.missing:
		state = "not installed"
	case h.active:
		state = "active"
	}
	lines, added := 0, []string{}
	for _, r := range h.rules {
		if r.start {
			lines += 2
		} else {
			added = append(added, r.words())
		}
	}
	return endRows(state, rulesAfter(lines, added), s.Actions, asks)
}

// newEngine is a change's engine on h, as cmd/hardn builds it.
func newEngine(h *fwHost) func(progress func(engine.Event)) *engine.Engine {
	return func(progress func(engine.Event)) *engine.Engine {
		return engine.New(h, engine.Options{
			Revert:   revert.Options{Now: clock, Hardn: hardnBinary},
			Detect:   func(context.Context, host.System) (detect.Facts, error) { return h.facts, nil },
			Hold:     func() func() { return func() {} },
			PID:      5000,
			Session:  h.session(),
			Backups:  backup.Settings{Path: backup.DefaultPath, Enabled: true},
			Progress: progress,
		})
	}
}

// loaded is the row's hardn.yml on h, read as hardn reads it.
func loaded(t *testing.T, h *fwHost, st start) *config.Config {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(fixtures, st.fixture()))
	if err != nil {
		t.Fatal(err)
	}
	h.AddFile(yml, data, 0o600, 0, 0)
	cfg, err := config.Read(context.Background(), h, yml)
	if err != nil {
		t.Fatal(err)
	}
	if cfg.SshPort != 2230 || len(cfg.UfwAppProfiles) != st.profiles {
		t.Fatalf("hardn.yml: port %d, %d profiles", cfg.SshPort, len(cfg.UfwAppProfiles))
	}
	return cfg
}

// plans of a step: the action with its edit, as the flow plans it; whether it
// refuses; and whether it is lockout-risk.
func preview(ctx context.Context, h *fwHost, cfg *config.Config, s step) (changes []engine.Change, err error) {
	edited := *cfg
	if s.edit != nil {
		s.edit(&edited)
	}
	return firewall.Incoming{Action: s.action}.Plan(ctx, h, engine.Input{Facts: h.facts, Config: &edited, Session: h.session()})
}

// offered reports whether r, Read's, offers s: Install or Enable as item 1,
// Disable as item 1 or beside it. Profiles' items are the sub-screen's.
func offered(r firewall.Reading, s step) bool {
	switch s.action {
	case firewall.ActionInstall:
		return r.First == firewall.ItemInstall
	case firewall.ActionEnable:
		return r.First == firewall.ItemEnable
	case firewall.ActionDisable:
		return r.First == firewall.ItemDisable || r.DisableBeside
	}
	return r.State.Installed
}

var actionWords = map[firewall.Action]string{firewall.ActionInstall: "Install", firewall.ActionEnable: "Enable", firewall.ActionDisable: "Disable",
	firewall.ActionSaveProfiles: "the save", firewall.ActionApplyProfiles: "Apply"}

// screenRun is the row through the screen's path, as unit (c) is to run it:
// firewall.Read for what it would offer or refuse, then each step: refused before
// asking where its plan refuses, else through screenkit.Session.Change, answered
// y/N where plain and with the hostname typed where lockout-risk; under plan only
// it stops at the plan. It returns the end state and how it ran.
func screenRun(t *testing.T, c parity.Cell, rw row) (parity.EndState, string) {
	t.Helper()
	ctx := context.Background()
	h := newHost(t, c.Distro.Name, rw.st)
	cfg := loaded(t, h, rw.st)
	n := len(h.Calls())
	var findings, via, plans []string
	pending := false
	refusal, asks := "", "nothing"
	onPVE := h.facts.Proxmox.Installed == detect.Yes
	r := firewall.Read(ctx, h, h.facts, cfg, h.session())
	if onPVE && (!r.OnPVE || r.First != firewall.ItemNone) {
		t.Errorf("Proxmox VE: on PVE %t, item %d", r.OnPVE, r.First)
	}
	if len(rw.steps) == 0 {
		via = append(via, "firewall.Read alone: the read-only screen, Return alone")
	}
	for i, s := range rw.steps {
		if i > 0 && pending {
			// A later change waits for hardn confirm.
			if _, err := revert.Confirm(ctx, h, revert.Session{Source: "no SSH_CONNECTION"}, revert.Options{Now: clock, Hardn: hardnBinary}); err != nil {
				t.Fatal(err)
			}
			via = append(via, "hardn confirm, from a console")
		}
		r = firewall.Read(ctx, h, h.facts, cfg, h.session())
		if !onPVE && !s.hidden && !offered(r, s) {
			t.Fatalf("%s: not offered: item %d, beside %t, installed %t", actionWords[s.action], r.First, r.DisableBeside, r.State.Installed)
		}
		pre, err := preview(ctx, h, cfg, s)
		if (s.action == firewall.ActionEnable && r.First == firewall.ItemEnable || s.action == firewall.ActionInstall && r.First == firewall.ItemInstall) && output.CodeOf(err) != output.CodeOf(r.PlanErr) {
			t.Errorf("Read's refusal %v, the plan's %v", r.PlanErr, err)
		}
		if err != nil {
			refusal = output.CodeOf(err) + ", before asking"
			via = append(via, actionWords[s.action]+" refused before it asks")
			break
		}
		typed := slices.ContainsFunc(pre, func(c engine.Change) bool { return c.Risk == engine.RiskLockout })
		var lines []string
		answer := s.answer
		switch {
		case rw.st.dry || len(pre) == 0:
		case answer == "" && typed:
			answer = hostName
			lines = []string{answer}
		case answer == "":
			answer = "y"
			lines = []string{answer}
		default:
			lines = []string{answer}
		}
		var out bytes.Buffer
		env := term.Resolve(term.Options{}, term.Facts{Width: 120})
		ty := uitest.NewTypist(&out, lines...)
		var ran []output.Run
		kit := screenkit.Session{Name: "firewall screen", Prompter: nav.Prompter{Ctx: component.NewCtx(env), In: prompt.New(ty, false), Out: env.Writer(&out)},
			System: h, Config: cfg, DryRun: rw.st.dry, LogPath: output.LegacyLogPath, Now: clock, NewEngine: newEngine(h),
			Ran: func(run output.Run) { ran = append(ran, run) }}
		edit := s.edit
		action := s.action
		err = kit.Change(ctx, screenkit.Change{
			Step: screen.WorkflowStep{Title: component.TitleBar{Title: actionWords[action]}},
			Flow: flow.Flow{Confirm: func(p flow.Plan) flow.Confirm {
				if p.Typed() {
					return flow.Confirm{Question: "Enable the firewall?", Label: "Type the hostname", Phrase: hostName}
				}
				return flow.Confirm{Question: actionWords[action] + "?"}
			}},
			Controls: func(edited *config.Config) []engine.Control {
				if edit != nil {
					edit(edited)
				}
				return []engine.Control{firewall.Incoming{Action: action}}
			},
		})
		if err != nil || ty.Unread() != 0 || len(ran) != 1 {
			t.Fatalf("the flow: %v, %d unread, %d runs:\n%s", err, ty.Unread(), len(ran), out.String())
		}
		st := parity.Planned(parity.EndState{}, ran[0].Plan)
		findings = append(findings, st.Findings...)
		if st.Refusal != "" {
			t.Fatalf("the preview planned and the flow refused: %s", st.Refusal)
		}
		how := actionWords[action]
		switch {
		case rw.st.dry:
			how += " under plan only"
			for _, ch := range ran[0].Plan.Changes {
				if len(ch.Commands) == 0 {
					plans = append(plans, ch.Target)
				}
				plans = append(plans, slices.DeleteFunc(slices.Clone(ch.Commands), timerCommand)...)
			}
		case typed:
			how += ", the hostname typed"
			pending = true
			asks = "the hostname typed; the timer armed"
			if !strings.Contains(out.String(), "Type the hostname") || !armed(h, n) {
				t.Errorf("lockout risk: the hostname asked %t, the timer armed %t:\n%s", strings.Contains(out.String(), "Type the hostname"), armed(h, n), out.String())
			}
		case len(pre) == 0:
			how += ", nothing to change"
		default:
			how += ", " + answer
			if asks == "nothing" {
				asks = "y/N"
			}
			if !strings.Contains(out.String(), "[y/N") {
				t.Errorf("a plain change not asked y/N:\n%s", out.String())
			}
		}
		via = append(via, how)
		if ran[0].Err != nil {
			refusal = "failed: " + output.CodeOf(ran[0].Err)
		}
	}
	state := stateOf(t, h, n)
	state.Findings, state.Refusal = findings, refusal
	state.Rows = rowsOf(h, state, asks)
	if len(plans) > 0 {
		state.Rows = append(state.Rows, parity.Row{Name: rowPlan, Value: strings.Join(plans, "; ")})
	}
	if onPVE {
		pveRows(t, h, n, r, &state, rw)
	}
	return state, "firewall.Read, then " + strings.Join(via, "; then ")
}

// pveRows holds Proxmox VE's: no ufw command of any kind, and what the read-only
// screen says of ufw left active (decision 7).
func pveRows(t *testing.T, h *fwHost, n int, r firewall.Reading, s *parity.EndState, rw row) {
	t.Helper()
	for _, c := range h.Calls()[n:] {
		if c.Op == "run" && c.Argv[0] == "ufw" {
			t.Errorf("a ufw call on Proxmox VE: %v", c.Argv)
		}
	}
	switch {
	case strings.Contains(rw.sc.Golden, "proxmox_open"):
		s.Rows = append(s.Rows, parity.Row{Name: rowOffers, Value: "Return alone: pve-firewall read, nothing changed"})
	case rw.st.active:
		if r.PVEUFWEnabled != detect.Yes {
			t.Errorf("ufw left active: read %v, %v", r.PVEUFWEnabled, r.PVEUFWErr)
		}
		s.Rows = append(s.Rows, parity.Row{Name: rowLeft, Value: "a warning row, from ufw.conf; no ufw call"})
	}
}

// armed: the run armed the revert timer, systemd-run on systemd, a detached
// sleeper on OpenRC.
func armed(h *fwHost, n int) bool {
	return slices.ContainsFunc(h.Calls()[n:], func(c hostfake.Call) bool {
		if h.facts.Init.Kind == detect.OpenRC {
			return c.Op == "start-detached" && timerCommand(host.FormatArgv(c.Argv))
		}
		return c.Op == "run" && c.Argv[0] == "systemd-run"
	})
}

// flagRun is -w on c's host, as unit (d) is to run it (cmd/hardn's runControls):
// Incoming{ActionEnable} planned and applied through the engine; decision 4's
// question comes with unit (d): on a terminal the hostname typed, the timer armed;
// off a terminal refused. With dryRun (-n) the plan alone.
func flagRun(t *testing.T, c parity.Cell, rw row, dryRun bool) parity.EndState {
	t.Helper()
	ctx := context.Background()
	h := newHost(t, c.Distro.Name, rw.st)
	cfg := loaded(t, h, rw.st)
	n := len(h.Calls())
	e := newEngine(h)(nil)
	p, err := e.Plan(ctx, []engine.Control{firewall.Incoming{Action: firewall.ActionEnable}}, cfg)
	if err != nil {
		t.Fatal(err)
	}
	var applyErr error
	if p.Err() == nil && !dryRun {
		_, applyErr = e.Apply(ctx, p)
	}
	s := parity.Planned(stateOf(t, h, n), p)
	asks := "nothing"
	switch {
	case p.Err() != nil:
		s.Refusal += ", before asking"
	case dryRun:
	case !armed(h, n):
		t.Errorf("-w: no timer armed")
	default:
		asks = "the timer armed; the hostname typed in unit (d) (decision 4)"
	}
	if applyErr != nil {
		s.Refusal = "failed: " + output.CodeOf(applyErr)
	}
	s.Rows = rowsOf(h, s, asks)
	if rw.st.pve || c.Distro.Name == "proxmox" {
		for _, call := range h.Calls()[n:] {
			if call.Op == "run" && call.Argv[0] == "ufw" {
				t.Errorf("a ufw call on Proxmox VE: %v", call.Argv)
			}
		}
	}
	return s
}

// same is what a run left, for holding the screen's path and -w's equal.
func same(s parity.EndState) string {
	return fmt.Sprintf("%s\nbackups %q\njournal %t\nfindings %q\nrefusal %q", parity.HostText(s), s.Backups, s.Journal, s.Findings, s.Refusal)
}

// runCell is the new path on c, from the start origin/main's golden names, held
// to it (parity.Cell.LegacyStart). A -w row runs the flag's form and its plan
// alone, and holds the screen's Enable equal; a screen's Enable holds -w equal.
func runCell(t *testing.T, c parity.Cell) parity.NewRun {
	t.Helper()
	rw := byName[c.Scenario.Name]
	if got, want := c.LegacyStart(), rw.st.words(c.Distro.Name); got != want {
		t.Fatalf("origin/main's run started from\n%q\nthe new path's host from\n%q", got, want)
	}
	if rw.flag {
		live := flagRun(t, c, rw, false)
		screenSide := rw
		screenSide.steps = []step{{action: firewall.ActionEnable, hidden: true}}
		s, _ := screenRun(t, c, screenSide)
		if a, b := same(live), same(s); a != b {
			t.Errorf("-w left\n%s\nthe screen's Enable left\n%s", a, b)
		}
		dryRun := flagRun(t, c, rw, true)
		if dryRun.Wrote() || dryRun.Journal || len(dryRun.Backups) > 0 || len(dryRun.Actions) > 0 || len(dryRun.Dirs) > 0 {
			t.Errorf("-n -w changed the host: %+v", dryRun)
		}
		d := "the plan alone: nothing written"
		if code, _, _ := strings.Cut(dryRun.Refusal, ", before asking"); code != "" {
			d = "refused (" + code + "): nothing written"
		}
		return parity.NewRun{Live: live, Dry: d, Via: "-w's new form: Incoming{ActionEnable} through the engine as runControls builds it, decision 4's question to come in unit (d); the screen's Enable leaves the same"}
	}
	live, via := screenRun(t, c, rw)
	if len(rw.steps) == 1 && rw.steps[0].action == firewall.ActionEnable && !rw.st.dry {
		if a, b := same(live), same(flagRun(t, c, rw, false)); a != b {
			t.Errorf("the screen's Enable left\n%s\n-w left\n%s", a, b)
		}
		via += "; -w's plan and apply leave the same"
	}
	return parity.NewRun{Live: live, Via: via}
}

