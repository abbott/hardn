func menu(name, golden, long, short, v032 string) parity.Scenario {
	return only(parity.Scenario{Name: name, Golden: "menu/firewall_" + golden + ".golden", Lines: []string{},
		State: parity.HostState{Long: long, Short: short}, V032: v032}, "debian")
}

func dry(name, golden, long, v032 string) parity.Scenario {
	sc := menu(name, golden, long, "plan only", v032)
	sc.DryRun = true
	return sc
}

func ops(name, golden, long, short, v032 string) parity.Scenario {
	return parity.Scenario{Name: name, Golden: "ops/" + golden + "/{d}.golden", State: parity.HostState{Long: long, Short: short}, V032: v032}
}

// opsItem is an ops golden of a menu item. Its cfg.DryRun=true section is what
// the layers below do, which the menu skips (the golden's NOTE): the item's dry
// run is the menu golden's row, dry-configure, so it has no dry run of its own.
func opsItem(name, golden, long, short, v032 string) parity.Scenario {
	sc := ops(name, golden, long, short, v032)
	sc.Lines = []string{}
	return sc
}

func only(sc parity.Scenario, on ...string) parity.Scenario {
	sc.Only = on
	return sc
}

// scenarios and each row's by name.
