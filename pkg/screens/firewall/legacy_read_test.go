// The reader of this slice's goldens (Slice.Reader): the menu layout
// (TestLegacyMenuFirewall, TestLegacyMenuDryRun's firewall_configure_dry_run)
// and the ops layout (TestOperationGoldens), whose failed runs the harness's
// own ops reader does not compare. What it does not know fails: a header line,
// a section, a call, a command, a trailer line. The screen as printed is words
// and rows, unit (c)'s: of it, the reader takes the result lines alone, and the
// menu's items where the Proxmox VE row compares them.

var (
	escape    = regexp.MustCompile(`\\x1b\[[0-9;?]*[A-Za-z]`)
	callLine  = regexp.MustCompile(`^\s*\d+ ([a-z]+)\s+(.*) -> (ok|not-exist|error: .*)$`)
	writeCall = regexp.MustCompile(`^(\S+) mode=(\d{4})$`)
	menuItem  = regexp.MustCompile(`^ +[1-9]\) (.*?)  `)
	endsAs    = regexp.MustCompile(`^(active|inactive), (?:no rules|rule lines: (\d+))$|^not installed$`)
	startUFW  = regexp.MustCompile(`^(?:Debian 13|Proxmox VE on Debian 13 \(/etc/pve there, osdetect saying so\)); ufw (active|inactive|not installed)(?:, (?:no rules|rule lines: (\d+)))?; cfg\.SshPort \d+; \d+ profiles; dryRun (?:true|false)$`)
	allowPort = regexp.MustCompile(`^ufw allow (\d+/tcp)( comment "SSH access")?$`)
	allowApp  = regexp.MustCompile(`^ufw allow from any to any app (\S+)$`)
)

// known header lines of the two layouts.
var headers = []string{"# origin/main behaviour", "# Generated by ", "# Operation: ", "# Reached by: ", "# FIXED ", "# KNOWN-DEFECT: ", "# NOTE: ",
	"# Screen: ", "# Script: ", "# Start: ", "# Pauses: ", "# The screen as printed"}

// readGolden is Slice.Reader: the layout by the golden's path.
func readGolden(data []byte, rel string) (parity.LegacyRead, error) {
	if strings.HasPrefix(rel, "ops/") {
		return readOps(data)
	}
	return readMenu(data, rel)
}

// run is what one run of origin/main did, as the calls say: the changes, the
// probes, what they leave of ufw.
type run struct {
	s      parity.EndState
	active bool // ufw's chains, as the commands leave them
	lines  int  // the start's rule lines, left by no ufw reset
	rules  []string
	last   *parity.FileWrite
}

// probes are origin/main's commands that only read.
func isProbe(cmd string) bool {
	return cmd == "which ufw" || cmd == "ufw status" || strings.HasPrefix(cmd, "dpkg-query ")
}

// call takes one line of the calls; ok is false for a line that is none.
func (r *run) call(l string) (bool, error) {
	if c, ok := strings.CutPrefix(l, "        "); ok && r.last != nil {
		switch {
		case c == "|":
			r.last.Lines = append(r.last.Lines, "")
		case strings.HasPrefix(c, "| "):
			r.last.Lines = append(r.last.Lines, c[2:])
		default:
			return false, fmt.Errorf("a line of a write it does not read: %q", l)
		}
		return true, nil
	}
	m := callLine.FindStringSubmatch(l)
	if m == nil {
		return false, nil
	}
	r.last = nil
	op, arg, res := m[1], m[2], m[3]
	failed, isErr := strings.CutPrefix(res, "error: ")
	switch op {
	case "stat":
		if arg != "/etc/pve" {
			return false, fmt.Errorf("a stat it does not read: %q", l)
		}
	case "mkdir":
		p, mode, _ := strings.Cut(arg, " mode=")
		r.s.Dirs = append(r.s.Dirs, p+" "+mode)
	case "write":
		w := writeCall.FindStringSubmatch(arg)
		if w == nil {
			return false, fmt.Errorf("a write it does not read: %q", l)
		}
		var mode uint32
		if _, err := fmt.Sscanf(w[2], "%o", &mode); err != nil {
			return false, fmt.Errorf("%q: %w", l, err)
		}
		r.s.Files = append(r.s.Files, parity.FileWrite{Path: w[1], Mode: fs.FileMode(mode)})
		r.last = &r.s.Files[len(r.s.Files)-1]
	case "exec":
		if isProbe(arg) {
			r.s.Probes = append(r.s.Probes, arg+" -> "+res)
			return true, nil
		}
		r.s.Actions = append(r.s.Actions, arg)
		if isErr {
			if r.s.Refusal != "" {
				return false, fmt.Errorf("a second command that failed: %q", l)
			}
			r.s.Refusal = "failed: " + failed
			return true, nil
		}
		return true, r.ufw(arg)
	default:
		return false, fmt.Errorf("an operation it does not read: %q", l)
	}
	if isErr {
		return false, fmt.Errorf("a call that failed, which it does not read: %q", l)
	}
	return true, nil
}

// ufw takes a command that succeeded: what it leaves, as the fixture's fwUFW
// takes it. A command it does not know is an error.
func (r *run) ufw(cmd string) error {
	switch {
	case cmd == "ufw default deny incoming", cmd == "ufw default allow outgoing":
	case cmd == "ufw disable":
		r.active = false
	case cmd == "ufw reset":
		r.lines, r.rules = 0, nil
	case cmd == `sh -c "yes | ufw enable"`:
		r.active = true
	default:
		if m := allowPort.FindStringSubmatch(cmd); m != nil {
			r.rules = append(r.rules, m[1])
			return nil
		}
		if m := allowApp.FindStringSubmatch(cmd); m != nil {
			r.rules = append(r.rules, "app "+m[1])
			return nil
		}
		return fmt.Errorf("a command it does not read: %q", cmd)
	}
	return nil
}

// rows are the run's aspects beyond the harness's own.
func (r *run) rows(installed bool, asks string) []parity.Row {
	ufw := "not installed"
	if installed {
		ufw = "inactive"
		if r.active {
			ufw = "active"
		}
	}
	return endRows(ufw, rulesAfter(r.lines, r.rules), r.s.Actions, asks)
}

// readMenu reads the menu layout.
func readMenu(data []byte, rel string) (parity.LegacyRead, error) {
	var out parity.LegacyRead
	r := &run{}
	installed := false
	sc := bufio.NewScanner(bytes.NewReader(data))
	sc.Buffer(nil, 1<<20)
	const (
		head = iota
		screen
		trailer
		yml
	)
	at := head
	var ymlLines, plans, items []string
	asks, ended, stub := "nothing", "", false
	for sc.Scan() {
		l := sc.Text()
		switch at {
		case head:
			switch {
			case l == "# ----":
				at = screen
				var err error
				if installed, err = r.begin(&out, data); err != nil {
					return out, err
				}
			case strings.HasPrefix(l, "# Start: "):
				out.Start = strings.TrimPrefix(l, "# Start: ")
			case !slices.ContainsFunc(headers, func(h string) bool { return strings.HasPrefix(l, h) }):
				return out, fmt.Errorf("a header line it does not read: %q", l)
			}
			continue
		case screen:
			if l == "# ----" {
				at = trailer
				continue
			}
			words := strings.TrimSuffix(escape.ReplaceAllString(l, ""), "$")
			if m := menuItem.FindStringSubmatch(words); m != nil && !slices.Contains(items, m[1]) {
				items = append(items, m[1])
			}
			switch {
			case strings.HasPrefix(words, "✗ "):
				if err := r.refused(strings.TrimPrefix(words, "✗ ")); err != nil {
					return out, err
				}
			case strings.Contains(words, "isn't yet implemented"):
				stub = true
			case strings.Contains(words, "[DRY-RUN] "):
				_, w, _ := strings.Cut(words, "[DRY-RUN] ")
				plans = append(plans, w)
			case strings.Contains(words, "(y/n):"):
				asks = "y/N"
			}
			continue
		case yml:
			ymlLines = append(ymlLines, l)
			continue
		}
		ok, err := r.call(l)
		if err != nil {
			return out, err
		}
		if ok {
			continue
		}
		switch {
		case l == "# The repository's calls, in order:", l == "# ./hardn.yml: not written", l == "# Files it wrote (mock file system): 0":
		case strings.HasPrefix(l, "# Commands the screen ran (mock commander): "):
			for _, c := range strings.Split(strings.TrimPrefix(l, "# Commands the screen ran (mock commander): "), "; ") {
				r.s.Probes = append(r.s.Probes, c+" -> ok")
			}
		case strings.HasPrefix(l, "# ufw as the fixture ends: "):
			ended = strings.TrimPrefix(l, "# ufw as the fixture ends: ")
		case strings.HasPrefix(l, "# Files under / afterwards: "):
			if err := r.afterwards(strings.TrimPrefix(l, "# Files under / afterwards: ")); err != nil {
				return out, err
			}
		case l == "# ./hardn.yml as written:":
			at = yml
		default:
			return out, fmt.Errorf("a trailer line it does not read: %q", l)
		}
	}
	if err := sc.Err(); err != nil {
		return out, err
	}
	if at == head || at == screen {
		return out, errors.New("no Start line or no screen, or no trailer: a layout it does not read")
	}
	if err := r.heldTo(ended, installed); err != nil {
		return out, err
	}
	if stub {
		if r.s.Refusal != "" {
			return out, errors.New("a stub and a refusal")
		}
		r.s.Refusal = "stub: isn't yet implemented"
	}
	if ymlLines != nil {
		r.s.YML = &parity.FileWrite{Path: "./hardn.yml", Lines: ymlLines, NoMode: true}
		r.s.Memory = true
	}
	r.s.Rows = r.rows(installed, asks)
	if len(plans) > 0 {
		r.s.Rows = append(r.s.Rows, parity.Row{Name: rowPlan, Value: strings.Join(plans, "; ")})
	}
	if strings.Contains(rel, "proxmox_open") {
		r.s.Rows = append(r.s.Rows, parity.Row{Name: rowOffers, Value: strings.Join(items, ", ")})
	}
	if strings.Contains(rel, "proxmox_active") {
		r.s.Rows = append(r.s.Rows, parity.Row{Name: rowLeft, Value: "not said; item 1 is the stub"})
	}
	out.Live = r.s
	return out, nil
}

// refused takes a result's words: a failure, or a refusal.
func (r *run) refused(words string) error {
	if r.s.Refusal != "" {
		return fmt.Errorf("a second result: %q", words)
	}
	for _, p := range []string{"Failed to configure firewall: ", "Failed to enable and configure firewall: "} {
		if v, ok := strings.CutPrefix(words, p); ok {
			if !strings.HasPrefix(v, "failed to add rule ") {
				r.s.Refusal = "failed: " + v
			}
			return nil // a command's failure is the call's, which says it
		}
	}
	r.s.Refusal = "refused: " + words
	return nil
}

// afterwards holds the files under / to what the run wrote: and the sshd_config
// firewall_item2_allows_configured_port_not_sshds seeds.
func (r *run) afterwards(list string) error {
	if list == "none" {
		list = ""
	}
	for _, f := range strings.FieldsFunc(list, func(c rune) bool { return c == ',' || c == ' ' }) {
		if f != "/etc/ssh/sshd_config" && !slices.ContainsFunc(r.s.Files, func(w parity.FileWrite) bool { return w.Path == f }) {
			return fmt.Errorf("a file afterwards the calls do not explain: %s", f)
		}
	}
	return nil
}

// begin takes the start the golden's header says, whether ufw is installed:
// firewall_configure_dry_run's NOTE says it in words of its own
// (menu_dryrun_test.go's case).
func (r *run) begin(out *parity.LegacyRead, data []byte) (bool, error) {
	if out.Start == "" {
		if !bytes.Contains(data, []byte("# NOTE: Debian 13, SSH port 2230; ufw installed and inactive")) {
			return false, errors.New("no Start line")
		}
		out.Start = "Debian 13; ufw inactive, no rules; cfg.SshPort 2230; 0 profiles; dryRun true"
	}
	m := startUFW.FindStringSubmatch(out.Start)
	if m == nil {
		return false, fmt.Errorf("a start it does not read: %q", out.Start)
	}
	r.active = m[1] == "active"
	r.lines, _ = strconv.Atoi(m[2]) // the pattern's digits, or none
	return m[1] != "not installed", nil
}

// heldTo fails unless the fixture ended as the commands leave it: "active, rule
// lines: 6"; each allow is two lines. firewall_configure_dry_run says nothing.
func (r *run) heldTo(ended string, installed bool) error {
	if ended == "" {
		return nil
	}
	m := endsAs.FindStringSubmatch(ended)
	if m == nil {
		return fmt.Errorf("an end it does not read: %q", ended)
	}
	n, _ := strconv.Atoi(m[2]) // the pattern's digits, or none
	if want := r.lines + 2*len(r.rules); ended != "not installed" && (n != want || (m[1] == "active") != r.active) || (ended == "not installed") == installed {
		return fmt.Errorf("the fixture ended %q; the commands leave active %t, %d lines", ended, r.active, want)
	}
	return nil
}

// readOps reads the ops layout. The fixture's ufw answers every command, its
// start not said; the new path's host holds it installed and inactive.
func readOps(data []byte) (parity.LegacyRead, error) {
	var out parity.LegacyRead
	live, dry := &run{}, &run{}
	var cur *run
	var hostLine, port, profiles string
	section := ""
	sc := bufio.NewScanner(bytes.NewReader(data))
	sc.Buffer(nil, 1<<20)
	for sc.Scan() {
		l := sc.Text()
		switch {
		case strings.HasPrefix(l, "# "):
			if !slices.ContainsFunc(headers, func(h string) bool { return strings.HasPrefix(l, h) }) {
				return out, fmt.Errorf("a header line it does not read: %q", l)
			}
			continue
		case l == "":
			continue
		case l == "== fixture", l == "== cfg.DryRun=false", l == "== cfg.DryRun=true", strings.HasPrefix(l, "== hardn -n "):
			section, cur = l, nil
			switch l {
			case "== cfg.DryRun=false":
				cur = live
			case "== cfg.DryRun=true":
				cur = dry
			}
			continue
		case strings.HasPrefix(l, "cfg.DryRun=true section identical"):
			continue
		}
		switch {
		case section == "== fixture":
			if v, ok := strings.CutPrefix(l, "host: "); ok {
				hostLine = v
			}
			if v, ok := strings.CutPrefix(l, "config (DefaultConfig plus overrides): "); ok {
				for _, f := range strings.Fields(v) {
					if p, ok := strings.CutPrefix(f, "sshPort="); ok {
						port = p
					}
					if p, ok := strings.CutPrefix(f, "ufwAppProfiles="); ok {
						profiles = p
					}
				}
			}
		case strings.HasPrefix(section, "== hardn -n "):
			switch {
			case strings.HasPrefix(l, "refused: "):
				out.CLI = append(out.CLI, strings.TrimPrefix(l, "refused: "))
			case strings.HasPrefix(l, "stderr: ") && len(out.CLI) > 0:
				out.CLI[len(out.CLI)-1] += ": " + strings.TrimPrefix(l, "stderr: ")
			case !strings.HasPrefix(l, "trace: "):
				return out, fmt.Errorf("a line of hardn -n it does not read: %q", l)
			}
		case cur != nil:
			if v, ok := strings.CutPrefix(l, "result "); ok {
				_, res, _ := strings.Cut(v, ": ")
				if e, ok := strings.CutPrefix(res, "error: "); ok {
					cur.s.Refusal = "failed: " + e
				} else if res != "ok" {
					return out, fmt.Errorf("a result it does not read: %q", l)
				}
				continue
			}
			if l == "trace:" || l == "    (no calls)" {
				continue
			}
			ok, err := cur.call(l)
			if err != nil {
				return out, err
			}
			if !ok {
				return out, fmt.Errorf("a trace line it does not read: %q", l)
			}
		default:
			return out, fmt.Errorf("a line outside any section: %q", l)
		}
	}
	if err := sc.Err(); err != nil {
		return out, err
	}
	if hostLine == "" || port == "" || profiles == "" {
		return out, errors.New("no fixture's host or config line: a layout it does not read")
	}
	out.Start = fmt.Sprintf("%s; cfg.SshPort %s; %s profiles", hostLine, port, profiles)
	live.s.Rows = live.rows(true, "nothing")
	out.Live, out.Dry = live.s, dry.s
	return out, nil
}

// TestReaderRefuses: what the reader does not compare fails.
func TestReaderRefuses(t *testing.T) {
	data, err := os.ReadFile(filepath.Join(legacyDir, "menu", "firewall_item2_profiles.golden"))
	if err != nil {
		t.Fatal(err)
	}
	opsData, err := os.ReadFile(filepath.Join(legacyDir, "ops", "configure_secure_firewall", "debian.golden"))
	if err != nil {
		t.Fatal(err)
	}
	if _, err := readGolden(data, "menu/firewall_item2_profiles.golden"); err != nil {
		t.Fatal(err)
	}
	if _, err := readGolden(opsData, "ops/configure_secure_firewall/debian.golden"); err != nil {
		t.Fatal(err)
	}
	for name, tc := range map[string]struct {
		ops      bool
		from, to string
		want     string
	}{
		"a header line":  {from: "# Pauses: ", to: "# Paused: ", want: "a header line"},
		"no screen":      {from: "# ----\n", to: "", want: "a header line"},
		"an operation":   {from: "write  /etc/ufw/applications.d/hardn", to: "chmod  /etc/ufw/applications.d/hardn", want: "an operation"},
		"a command":      {from: "ufw reset -> ok", to: "ufw reload -> ok", want: "a command"},
		"a second fail":  {from: "ufw reset -> ok", to: "ufw reset -> error: x\n 9 exec   ufw disable -> error: y", want: "a second command"},
		"a trailer line": {from: "# Files under / afterwards", to: "# Files beside / afterwards", want: "a trailer line"},
		"a file unsaid":  {from: "afterwards: /etc/ufw/applications.d/hardn", to: "afterwards: /etc/hosts", want: "a file afterwards"},
		"a wrong end":    {from: "active, rule lines: 6", to: "active, rule lines: 8", want: "the fixture ended"},
		"an ops line":    {ops: true, from: "trace:\n", to: "traced:\n", want: "a trace line"},
		"an ops section": {ops: true, from: "== fixture\n", to: "", want: "a line outside"},
	} {
		t.Run(name, func(t *testing.T) {
			src, rel := data, "menu/firewall_item2_profiles.golden"
			if tc.ops {
				src, rel = opsData, "ops/configure_secure_firewall/debian.golden"
			}
			changed := bytes.ReplaceAll(src, []byte(tc.from), []byte(tc.to))
			if bytes.Equal(changed, src) {
				t.Fatalf("%q is not in the golden", tc.from)
			}
			if _, err := readGolden(changed, rel); err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Errorf("got %v, want %q", err, tc.want)
			}
		})
	}
}
