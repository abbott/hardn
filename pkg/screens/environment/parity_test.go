// elevation is a supported release's facts, its init running, with the
// tool given installed ("sudo" of flavor, "doas") and the other not.
func elevation(distro detect.Distro, version string, init detect.InitKind, tool string, flavor detect.SudoFlavor) detect.Facts {
	f := detect.Facts{Platform: detect.Platform{Distro: distro, Version: version, Support: detect.Supported},
		Init: detect.Init{Kind: init, Running: detect.Yes}, Container: detect.Container{Detected: detect.No}}
	none := detect.Tool{Present: detect.No}
	f.Elevation = detect.Elevation{Sudo: none, Doas: none}
	switch tool {
	case "sudo":
		f.Elevation.Sudo, f.Elevation.SudoFlavor = detect.Tool{Present: detect.Yes, Path: "/usr/bin/sudo"}, flavor
	case "doas":
		f.Elevation.Doas = detect.Tool{Present: detect.Yes, Path: "/usr/bin/doas"}
	}
	return f
}

// toolOf is the tool the control takes on d (sudoers.Choose).
