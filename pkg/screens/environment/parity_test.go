// isCheck: a command that checks what a run writes before it takes effect
// (parity.Slice.Check): visudo's and doas's checks.
func isCheck(argv string) bool {
	return strings.HasPrefix(argv, "visudo ") || strings.HasPrefix(argv, "doas -C ")
}

// envContent are what the elevation tool's files either path wrote hold
// (those under /etc/sudoers.d and /etc/doas.d; another file written is in
// the files aspect, its content in parity.golden), line by line, none
// where one alone wrote (Slice.Either): the lines that keep a variable
// (sudo's env_keep, doas's setenv), the other rules, and the comments.
func envContent(add func(name, legacy, new string), l, n []parity.FileWrite) {
	lk, lr, lc := elevationLines(l)
	nk, nr, nc := elevationLines(n)
	add("keep lines", parity.Joined(lk), parity.Joined(nk))
	add("rules", parity.Joined(lr), parity.Joined(nr))
	add("comments", parity.Joined(lc), parity.Joined(nc))
}

// elevationLines are fs's lines under the tool's directories: those that
// keep a variable, the other rules, the comments (a line starting with #;
// none here is sudoers' #include or #<uid>).
func elevationLines(fs []parity.FileWrite) (keep, rules, comments []string) {
	for _, f := range fs {
		if !strings.HasPrefix(f.Path, sudoers.DropInDir+"/") && !strings.HasPrefix(f.Path, sudoers.DoasDir+"/") {
			continue
		}
		for _, l := range f.Lines {
			switch {
			case strings.TrimSpace(l) == "":
			case strings.HasPrefix(l, "#"):
				comments = append(comments, l)
			case strings.Contains(l, "env_keep") || strings.Contains(l, "setenv"):
				keep = append(keep, l)
			default:
				rules = append(rules, l)
			}
		}
	}
	return keep, rules, comments
}

// debianMain is Debian 13's /etc/sudoers in shape, as the control's tests
// have it: the %sudo rule, then the includedir as the last directive. The
// new path reads it; origin/main never does, so its root has none.
const debianMain = "Defaults\tenv_reset\nroot\tALL=(ALL:ALL) ALL\n%sudo\tALL=(ALL:ALL) ALL\n\n@includedir /etc/sudoers.d\n"

// envHost is d with st's root and, which origin/main never reads, the
// tool's own files and the directories the engine writes in: on sudo
// /etc/sudoers; on doas Alpine 3.23's cloud image's doas.conf and
// wheel.conf, as the control's tests have them. visudo and doas -C pass
// every file, but with st.visudoFails visudo refuses the configuration
// (visudo -c), which includes the file it cannot parse; a copy of
// hardn's file alone it passes (visudo -cf). Any other command is
// unscripted.
func envHost(t *testing.T, d parity.Distro, st start) *hostfake.System {
	t.Helper()
	h := hostfake.New(host.Options{})
	for _, s := range st.seeds {
		switch {
		case s.dir:
			h.AddDir(s.path, s.mode, 0, 0) // the sticky bit is not modelled: nothing here writes under /tmp
		case s.link != "":
			h.AddSymlink(s.path, s.link)
		default:
			h.AddFile(s.path, []byte(s.content), s.mode, 0, 0)
		}
	}
	for _, dir := range []string{"/var/lib", "/var/backups", "/run", "/var/log"} {
		h.AddDir(dir, 0o755, 0, 0)
	}
	switch toolOf(d) {
	case sudoers.ToolSudo:
		h.AddFile(sudoers.MainConfig, []byte(debianMain), 0o440, 0, 0)
	case sudoers.ToolDoas:
		h.AddFile(sudoers.DoasConfig, []byte("# see doas.conf(5) for configuration details\n\n# permit persist :wheel\n"), 0o640, 0, 0)
		h.AddDir(sudoers.DoasDir, 0o750, 0, 0)
		h.AddFile(sudoers.DoasDir+"/wheel.conf", []byte("permit nopass :wheel\n"), 0o640, 0, 0)
	}
	h.Handler = func(argv []string, _ []byte) hostfake.Response {
		switch {
		case strings.Join(argv, " ") == "visudo -c" && st.visudoFails:
			return hostfake.Response{Stderr: sudoers.DropInDir + "/alice:1:21: syntax error\n", ExitCode: 1}
		case strings.Join(argv, " ") == "visudo -c":
			return hostfake.Response{Stdout: sudoers.MainConfig + ": parsed OK\n"}
		case len(argv) == 3 && argv[0] == "visudo" && argv[1] == "-cf":
			return hostfake.Response{Stdout: argv[2] + ": parsed OK\n"}
		case len(argv) == 3 && argv[0] == "doas" && argv[1] == "-C":
			return hostfake.Response{}
		}
		return hostfake.Response{Err: hostfake.ErrUnscripted, ExitCode: -1}
	}
	return h
}

// loaded is hardn.yml as loaded: none, so the defaults (config.DefaultConfig),
// whose backup settings the engine takes, as cmd/hardn's engineOptions
// does with the configuration loaded.
func loaded() *config.Config { return config.DefaultConfig() }

// newEngine is a change's engine on h, as cmd/hardn builds it: its clock,
// d's facts, the backups of the configuration loaded.
func newEngine(h *hostfake.System, d parity.Distro) func(progress func(engine.Event)) *engine.Engine {
	return func(progress func(engine.Event)) *engine.Engine {
		return engine.New(h, engine.Options{
			Revert:   revert.Options{Now: func() time.Time { return now }, Hardn: "/usr/local/bin/hardn"},
			Detect:   func(context.Context, host.System) (detect.Facts, error) { return d.Facts, nil },
			Hold:     func() func() { return func() {} },
			PID:      5000,
			Backups:  loaded().BackupSettings(),
			Progress: progress,
		})
	}
}

// stateOf is the end state h's calls from the nth on left, its checks and
// temp files recorded; no hardn.yml is written.
func stateOf(t *testing.T, h *hostfake.System, n int) parity.EndState {
	t.Helper()
	return parity.NewStateChecked(t, h, n, isCheck, "")
}

// item1 is item 1 on c's host through the Environment screen itself
// (pkg/screens/environment's Run), typed 1, then y where it asks, then 0,
// its change's engine as cmd/hardn builds it, on the cell's facts and
// environment; under plan only, typed 1, then 0. Whether it asks is
// read first with environment.Read, as the screen reads it: where its
// Refusal says so, the screen must say the refusal's words
// (screenkit.RefusalWords, then Reading.Stays) before asking anything,
// planning nothing; else it must ask the decided question, y/N
// (gallery-environment.md §6), and plan once (Options.Ran). It returns
// the end state, with the refusal "<code>, before asking", or "failed:
// <code>" for an apply that failed, and how it was reached: the screen
// and the lines typed, its closing 0 left out, as Backup's says it.
func item1(t *testing.T, c parity.Cell, env map[string]string, dryRun bool) (parity.EndState, string) {
	t.Helper()
	ctx := context.Background()
	h := envHost(t, c.Distro, starts[c.Scenario.Name])
	n := len(h.Calls())
	r := environment.Read(ctx, h, c.Distro.Facts, lookup(env))
	refusal := r.Refusal()
	lines := []string{"1"}
	if refusal == nil && !dryRun {
		lines = append(lines, "y")
	}
	var out bytes.Buffer
	tenv := term.Resolve(term.Options{}, term.Facts{Width: 120})
	ty := uitest.NewTypist(&out, append(slices.Clone(lines), "0")...)
	var runs []output.Run
	err := envscreen.Run(ctx, envscreen.Options{
		Prompter:  nav.Prompter{Ctx: component.NewCtx(tenv), In: prompt.New(ty, false), Out: tenv.Writer(&out)},
		System:    h,
		Facts:     c.Distro.Facts,
		Getenv:    lookup(env),
		NewEngine: newEngine(h, c.Distro),
		DryRun:    dryRun,
		LogPath:   output.LegacyLogPath,
		Now:       func() time.Time { return now },
		Ran:       func(run output.Run) { runs = append(runs, run) },
	})
	if err != nil || ty.Unread() != 0 {
		t.Fatalf("the screen: %v, %d unread:\n%s", err, ty.Unread(), out.String())
	}
	via := typed(lines, dryRun)
	if refusal != nil {
		words := screenkit.RefusalWords(refusal)
		if st := r.Stays(); st != "" {
			words += " " + screenkit.FullStop(st)
		}
		if errors.Is(r.Refused, sudoers.ErrEnvNeedsGrant) && r.Stays() == "" || len(runs) != 0 || inOrder(out.String(), "Warning "+words) != "" || strings.Contains(out.String(), "[y/N") {
			t.Fatalf("item 1's refusal %v: not said before asking in %q, or planned (%d runs):\n%s", refusal, words, len(runs), out.String())
		}
		s := stateOf(t, h, n)
		s.Refusal = output.CodeOf(refusal) + ", before asking"
		untouched(t, h, c)
		return s, via + ", refused before it asks"
	}
	question := "Keep HARDN_CONFIG under %s? [y/N"
	if r.Kept {
		question = "Stop keeping HARDN_CONFIG under %s? [y/N"
	}
	if asked := strings.Contains(out.String(), fmt.Sprintf(question, r.ToolName())); asked == dryRun || strings.Contains(out.String(), "Type the hostname") || len(runs) != 1 {
		t.Fatalf("item 1: asked %t (a lockout-risk plan, which no row here plans, types the hostname), %d runs:\n%s", asked, len(runs), out.String())
	}
	run := runs[0]
	if run.Plan.Err() != nil {
		t.Fatalf("Read asked, and the plan refused: %v:\n%s", run.Plan.Err(), out.String())
	}
	st := parity.Planned(stateOf(t, h, n), run.Plan)
	if run.Err != nil {
		st.Refusal = "failed: " + output.CodeOf(run.Err)
	}
	untouched(t, h, c)
	rootOwned(t, h, st)
	return st, via
}

// typed is how item 1 ran: the Environment screen, under plan only with
// dryRun, the lines typed, its closing 0 left out.
func typed(lines []string, dryRun bool) string {
	screen := "the Environment screen"
	if dryRun {
		screen += " under plan only"
	}
	return screen + ", typed " + strings.Join(lines, ", ")
}

// flagRun is hardn -e on c's host, as unit (d) is to run it
// (control-environment.md §11): environment.Controls planned through the
// engine as cmd/hardn builds it, then applied, asking nothing; with
// dryRun (-n) the plan alone. Its refusal is the plan's code, or
// "failed: <code>" for an apply that failed.
func flagRun(t *testing.T, c parity.Cell, env map[string]string, dryRun bool) parity.EndState {
	t.Helper()
	ctx := context.Background()
	h := envHost(t, c.Distro, starts[c.Scenario.Name])
	n := len(h.Calls())
	e := newEngine(h, c.Distro)(nil)
	p, err := e.Plan(ctx, environment.Controls(lookup(env)), loaded())
	if err != nil {
		t.Fatal(err)
	}
	var applyErr error
	if p.Err() == nil && !dryRun {
		_, applyErr = e.Apply(ctx, p)
	}
	st := parity.Planned(stateOf(t, h, n), p)
	if applyErr != nil {
		st.Refusal = "failed: " + output.CodeOf(applyErr)
	}
	untouched(t, h, c)
	rootOwned(t, h, st)
	return st
}

// rootOwned fails t unless every file s says the run wrote is root's,
// 0:0, on h: the owner, which origin/main's goldens do not record (its
// os.WriteFile as root, read), is checked here rather than compared.
func rootOwned(t *testing.T, h *hostfake.System, s parity.EndState) {
	t.Helper()
	for _, f := range s.Files {
		if e, ok := h.Entry(f.Path); !ok || e.UID != 0 || e.GID != 0 {
			t.Errorf("%s: owned %d:%d, not root's", f.Path, e.UID, e.GID)
		}
	}
}

// untouched fails t unless every file and symlink of c's start is as it
// was, and nothing was called under /tmp (V20): the new path changes
// hardn's own files alone.
func untouched(t *testing.T, h *hostfake.System, c parity.Cell) {
	t.Helper()
	for _, s := range starts[c.Scenario.Name].seeds {
		e, ok := h.Entry(s.path)
		switch {
		case s.dir:
		case s.link != "":
			if !ok || e.Mode&fs.ModeSymlink == 0 || e.Target != s.link {
				t.Errorf("%s: no longer the symlink to %s", s.path, s.link)
			}
		case !ok || string(e.Data) != s.content || e.Mode.Perm() != s.mode.Perm() || e.UID != 0 || e.GID != 0:
			t.Errorf("%s: changed", s.path)
		}
	}
	for _, call := range h.Calls() {
		if call.Path == "/tmp" || strings.HasPrefix(call.Path, "/tmp/") {
			t.Errorf("a call under /tmp: %v", call)
		}
	}
}

// same is what a run left, for holding item 1 and -e equal: the host's
// files and commands, the checks, temp files, backups, journal and
// findings, and the refusal's code.
func same(s parity.EndState) string {
	code, _, _ := strings.Cut(s.Refusal, ", before asking")
	return fmt.Sprintf("%s\nchecks %q\ntemps %q\nbackups %q\njournal %t\nfindings %q\nrefusal %q",
		parity.HostText(s), s.Checks, s.Temps, s.Backups, s.Journal, s.Findings, code)
}

// envRun is the new path on c: from the start origin/main's golden names
// (held to it), item 1 through the screen (item1), -e (flagRun), the two
// held equal, each file either wrote root's (rootOwned); for the root
// row, from SUDO_USER root too, held equal to unset; and plan only, which
// writes nothing on either. A row with lines is item 1's; the grant row, -e's, with its dry
// run, the plan alone.
func envRun(t *testing.T, c parity.Cell) parity.NewRun {
	t.Helper()
	st := starts[c.Scenario.Name]
	if got, want := c.LegacyStart(), st.words(); got != want {
		t.Fatalf("origin/main's run started from\n%q\nthe new path's host from\n%q", got, want)
	}
	env := st.env(c.Distro)
	screenLive, answered := item1(t, c, env, false)
	flagLive := flagRun(t, c, env, false)
	if a, b := same(screenLive), same(flagLive); a != b {
		t.Errorf("item 1 left\n%s\n-e left\n%s", a, b)
	}
	also := ""
	if st.rootToo {
		root := start{sudoUser: "root", user: "root"}.env(c.Distro)
		s, _ := item1(t, c, root, false)
		f := flagRun(t, c, root, false)
		if same(s) != same(screenLive) || same(f) != same(flagLive) {
			t.Errorf("%s root: item 1 left\n%s\n-e left\n%s\nwhere unset, item 1 left\n%s", invokerVar(c.Distro), same(s), same(f), same(screenLive))
		}
		also = "; " + invokerVar(c.Distro) + " root leaves the same"
	}
	screenDry, _ := item1(t, c, env, true)
	flagDry := flagRun(t, c, env, true)
	for _, d := range []parity.EndState{screenDry, flagDry} {
		if d.Wrote() || d.Journal || len(d.Backups) > 0 || len(d.Temps) > 0 || len(d.Checks) > 0 || len(d.Actions) > 0 || len(d.Dirs) > 0 {
			t.Errorf("plan only changed the host: %+v", d)
		}
	}
	dry := "the plan alone: nothing written"
	if code, _, _ := strings.Cut(flagDry.Refusal, ", before asking"); code != "" {
		dry = "refused (" + code + "): nothing written"
	}
	if c.Scenario.Lines == nil {
		return parity.NewRun{Live: flagLive, Dry: dry,
			Via: "-e: the control's plan and apply through the engine; " + answered + ", leaves the same"}
	}
	return parity.NewRun{Live: screenLive,
		Via: answered + "; -e's plan and apply leave the same; under plan only, " + dry + also}
}

// TestParityGoldens: every golden of origin/main's Environment is a row of
// the table or a not-row with why (parity-environment.md §2), and every
// one named is there.
func TestParityGoldens(t *testing.T) {
	rows := map[string]bool{}
	for _, sc := range envScenarios {
		for _, d := range envDistros {
			rows[strings.ReplaceAll(sc.Golden, "{d}", d.Name)] = true
		}
	}
	var all []string
	for _, pattern := range []string{"environment/*.golden", "menu/environment_*.golden", "ops/setup_sudo_preservation/*.golden", "ops/configure_sudo/*.golden"} {
		m, err := filepath.Glob(filepath.Join(legacyDir, filepath.FromSlash(pattern)))
		if err != nil {
			t.Fatal(err)
		}
		for _, p := range m {
			rel, err := filepath.Rel(legacyDir, p)
			if err != nil {
				t.Fatal(err)
			}
			all = append(all, filepath.ToSlash(rel))
		}
	}
	for _, g := range all {
		if rows[g] == (notRows[g] != "") {
			t.Errorf("%s: a row %t, a not-row %t: each golden is one or the other", g, rows[g], notRows[g] != "")
		}
	}
	for g := range rows {
		if !slices.Contains(all, g) {
			t.Errorf("row golden %s: not there", g)
		}
	}
	for g := range notRows {
		if !slices.Contains(all, g) {
			t.Errorf("not-row golden %s: not there", g)
		}
		if _, err := os.Stat(filepath.Join(legacyDir, filepath.FromSlash(g))); err != nil {
			t.Error(err)
		}
	}
}

