// seed is one thing a start's root holds, as pkg/characterization's
// envSeed (retired by unit (d)): a directory, a file and its content, or a symlink, and its mode.
type seed struct {
	path    string
	dir     bool
	content string
	link    string
	mode    fs.FileMode
}

// hostDirs are what every keep_* start holds (pkg/characterization's
// hostDirs, retired by unit (d)): /etc, /etc/sudoers.d as Debian's sudo package leaves it, and
// /tmp, anyone's to write in.
func hostDirs() []seed {
	return []seed{
		{path: "/etc", dir: true, mode: 0o755},
		{path: "/etc/sudoers.d", dir: true, mode: 0o750},
		{path: "/tmp", dir: true, mode: 0o777 | fs.ModeSticky},
	}
}

// withFile is hostDirs and a file at path.
func withFile(path, content string, mode fs.FileMode) []seed {
	return append(hostDirs(), seed{path: path, content: content, mode: mode})
}

// start is what a scenario's run starts from, on both paths: hardn's
// environment (the golden's SUDO_USER and USER, "" unset), the root's
// entries, and whether visudo refuses.
type start struct {
	sudoUser, user string
	seeds          []seed
	// visudoFails: visudo refuses the configuration, as it does a file it
	// cannot parse [I]. origin/main's fixture fails its check of the temp
	// file; the new path's, its check of the whole configuration, which
	// includes the same file (envHost).
	visudoFails bool
	// ops: the start is the ops layout's seed (ops/setup_sudo_preservation),
	// whose environment is in a note, not compared.
	ops bool
	// rootToo: the new path runs from SUDO_USER (DOAS_USER on doas) root
	// too, held equal: a root login is SUDO_USER unset or root, and
	// origin/main reads root from either as keep_root's user
	// (file_environment_repository.go:135-138, read).
	rootToo bool
}

// words is st as origin/main's golden says it (parity.Cell.LegacyStart):
// the root layout's environment and "/ before" section, or the ops
// layout's seed lines, as pkg/characterization wrote them (seedLines,
// describe; retired by unit (d)).
func (st start) words() string {
	val := func(s string) string { return parity.OrElse(s, "unset") }
	var w []string
	if !st.ops {
		w = append(w, fmt.Sprintf("Environment: SUDO_USER %s, USER %s, HARDN_CONFIG unset, TMPDIR unset (os.TempDir() is /tmp)", val(st.sudoUser), val(st.user)))
	}
	for _, s := range st.seeds {
		mode := uint32(s.mode.Perm())
		if s.mode&fs.ModeSticky != 0 {
			mode |= 0o1000
		}
		switch {
		case st.ops && s.dir:
			w = append(w, "seed dir: "+s.path)
		case st.ops:
			w = append(w, "seed file: "+s.path)
		case s.dir:
			w = append(w, fmt.Sprintf("%s: a directory, mode %04o", s.path, mode))
		case s.link != "":
			w = append(w, fmt.Sprintf("%s: a symlink to %s", s.path, s.link))
		default:
			w = append(w, fmt.Sprintf("%s: a file, %d bytes, mode %04o", s.path, len(s.content), mode))
		}
		if !s.dir && s.link == "" {
			for _, l := range strings.Split(strings.TrimSuffix(s.content, "\n"), "\n") {
				w = append(w, strings.TrimSpace("| "+l))
			}
		}
	}
	if st.visudoFails {
		w = append(w, "commands that fail (every other command succeeds with empty output):", "visudo -c -f "+tempFile+" -> fixture: exit status 1")
	}
	return strings.Join(w, "; ")
}

// env is hardn's environment on d for st: the golden's SUDO_USER is the
// user who ran hardn through the host's tool, whom doas names in DOAS_USER
// [I, doas(1); sudoers.md §2.14]; USER as the golden's; HARDN_CONFIG and
// TMPDIR unset.
func (st start) env(d parity.Distro) map[string]string {
	m := map[string]string{}
	if st.sudoUser != "" {
		m[invokerVar(d)] = st.sudoUser
	}
	if st.user != "" {
		m["USER"] = st.user
	}
	return m
}

// invokerVar is the variable that names who ran hardn on d: DOAS_USER on
// doas, else SUDO_USER.
func invokerVar(d parity.Distro) string {
	if toolOf(d) == sudoers.ToolDoas {
		return "DOAS_USER"
	}
	return "SUDO_USER"
}

// lookup is getenv over vars.
func lookup(vars map[string]string) func(string) string {
	return func(k string) string { return vars[k] }
}

