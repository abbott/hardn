// TestScreen: the screen on each host, as read (decisions 2, 3, 4): what
// manages /etc/resolv.conf, the nameservers and search domains in use, a
// link's with the link, Unknown where they were not read (a manager hardn
// only reports, a fact not established, systemd-resolved stopped), and
// hardn.yml's list or the empty item; item 3 only with a list, and the
// screen only reads.
func TestScreen(t *testing.T) {
	tests := []struct {
		host                    string
		list                    []string
		manager, inUse, search  string
		listed                  []string
		removable               bool
		configuredLine, nothing bool
	}{
		{host: debian13, list: configured, manager: "direct (/etc/resolv.conf)", inUse: "192.0.2.1", search: "example.net", removable: true},
		{host: ubuntu2604, list: configured, manager: "systemd-resolved", inUse: "192.0.2.1 (eth0)", search: "example.net (eth0)", removable: true},
		{host: alpine324, list: configured, manager: "direct (/etc/resolv.conf)", inUse: "192.0.2.1", search: "example.net", removable: true},
		{host: pve9, list: configured, manager: "Proxmox VE (/etc/resolv.conf)", inUse: "192.0.2.1", search: "example.net", removable: true},
		{host: configuredHost, list: configured, manager: "direct (/etc/resolv.conf)", inUse: "192.0.2.54, 2001:db8::54", search: "example.net", removable: true},
		{host: networkManager, list: configured, manager: "NetworkManager, reported only", inUse: "Unknown", search: "Unknown", removable: true},
		{host: resolvconf, list: configured, manager: "resolvconf, reported only", inUse: "Unknown", search: "Unknown", removable: true},
		{host: container, list: configured, manager: "container, reported only", inUse: "Unknown", search: "Unknown", removable: true},
		{host: unread, list: configured, manager: "Unknown", inUse: "Unknown", search: "Unknown", removable: true},
		{host: resolvedOff, list: configured, manager: "systemd-resolved", inUse: "Unknown", search: "Unknown", removable: true},
		{host: debian13, manager: "direct (/etc/resolv.conf)", inUse: "192.0.2.1", search: "example.net", nothing: true},
	}
	for _, tt := range tests {
		t.Run(tt.host, func(t *testing.T) {
			h, cfg := newHost(t, tt.host, tt.list)
			p := play(h, cfg, wide, false, "0")
			s := screens(p.out)
			if p.err != nil || len(s) != 1 {
				t.Fatalf("Run = %v, %d screens; want nil, one:\n%s", p.err, len(s), p.out)
			}
			if got := [3]string{row(s[0], "DNS Implementation"), row(s[0], "Nameservers"), row(s[0], "Search Domains")}; got != [3]string{tt.manager, tt.inUse, tt.search} {
				t.Errorf("rows %q; want %q, %q, %q", got, tt.manager, tt.inUse, tt.search)
			}
			for i, ns := range tt.list {
				if !strings.Contains(s[0], "Nameserver "+string(rune('1'+i))+"         "+ns) {
					t.Errorf("hardn.yml's %s not listed as Nameserver %d:\n%s", ns, i+1, s[0])
				}
			}
			if strings.Contains(s[0], "No nameservers configured") != tt.nothing {
				t.Errorf("the empty item shown %t, want %t", !tt.nothing, tt.nothing)
			}
			if strings.Contains(s[0], "3) Remove nameserver") != tt.removable || strings.Contains(p.out, "[0-6 or q]") != tt.removable {
				t.Errorf("item 3 shown and taken %t, want %t:\n%s", !tt.removable, tt.removable, p.out)
			}
			if w := writes(h, 0); len(w) > 0 || p.engines != 0 || len(p.runs) != 0 {
				t.Errorf("drawing the screen wrote %v, made %d engines and %d runs", w, p.engines, len(p.runs))
			}
		})
	}
}

// TestConfigure: Configure DNS applies hardn.yml's list on each platform
// that takes one, through the plan, its findings before the question,
// y/N; saves nothing, the list being hardn.yml's; then the screen is read
// again under the result, the host as it is now. On Alpine the form asks
// first whether to stop udhcpc rewriting the file (decision 6): y stops
// it in the same change, n leaves it and the review warns.
func TestConfigure(t *testing.T) {
	tests := []struct {
		host          string
		lines         []string
		finding       string
		file, content string
		inUse         string
		udhcpc        bool
	}{
		{host: debian13, lines: []string{"1", "y", "0"}, finding: "dhcpcd may rewrite /etc/resolv.conf on a lease",
			file: hostdns.ResolvConf, content: resolvConf(dhcpcdHead, configured...), inUse: "192.0.2.54, 2001:db8::54"},
		{host: ubuntu2604, lines: []string{"1", "y", "0"}, finding: "eth0 still uses its own nameserver 192.0.2.1",
			file: hostdns.DropIn, content: "DNS=192.0.2.54 2001:db8::54\n", inUse: "192.0.2.54, 2001:db8::54, 192.0.2...."}, // eth0's cut
		{host: pve9, lines: []string{"1", "y", "0"}, finding: "Saving Proxmox VE's DNS settings rewrites /etc/resolv.conf",
			file: hostdns.ResolvConf, content: resolvConf("search example.net\n", configured...), inUse: "192.0.2.54, 2001:db8::54"},
		{host: alpine324, lines: []string{"1", "y", "y", "0"}, udhcpc: true,
			file: hostdns.ResolvConf, content: resolvConf("search example.net\n", configured...), inUse: "192.0.2.54, 2001:db8::54"},
		{host: alpine324, lines: []string{"1", "n", "y", "0"}, finding: "udhcpc rewrites /etc/resolv.conf on each lease",
			file: hostdns.ResolvConf, content: resolvConf("search example.net\n", configured...), inUse: "192.0.2.54, 2001:db8::54"},
	}
	for _, tt := range tests {
		t.Run(tt.host+" "+strings.Join(tt.lines, ","), func(t *testing.T) {
			h, cfg := newHost(t, tt.host, configured)
			before := content(h, hardnYML)
			p := play(h, cfg, wide, false, tt.lines...)
			if p.err != nil || p.unread != 0 || len(p.runs) != 1 || p.runs[0].Err != nil || p.runs[0].Result == nil {
				t.Fatalf("Run = %v, %d unread, runs %+v:\n%s", p.err, p.unread, p.runs, p.out)
			}
			if !strings.Contains(content(h, tt.file), tt.content) {
				t.Errorf("%s:\n%s\nwant it to hold\n%s", tt.file, content(h, tt.file), tt.content)
			}
			if content(h, hardnYML) != before || strings.Contains(p.out, "Save the configuration") {
				t.Errorf("hardn.yml saved, its list being the one applied:\n%s", content(h, hardnYML))
			}
			q := strings.Index(p.out, "Configure DNS? [y/N")
			if f := strings.Index(p.out, tt.finding); tt.finding != "" && (f < 0 || f > q) {
				t.Errorf("the finding %q is not listed before the question:\n%s", tt.finding, p.out)
			}
			asked := strings.Contains(p.out, "Stop udhcpc rewriting /etc/resolv.conf? [y/N")
			stopped := strings.Contains(content(h, hostdns.UDHCPCConf), "\nRESOLV_CONF=\"no\"\n")
			if asked != (tt.host == alpine324) || stopped != tt.udhcpc {
				t.Errorf("udhcpc's question asked %t, udhcpc stopped %t; want %t, %t", asked, stopped, tt.host == alpine324, tt.udhcpc)
			}
			s := screens(p.out)
			if len(s) != 2 || row(s[1], "Nameservers") != tt.inUse || strings.Index(p.out, "Operation Successful") > strings.LastIndex(p.out, "# DNS Configuration #") {
				t.Errorf("the screen drawn again under the result shows %q, want %q:\n%s", s, tt.inUse, p.out)
			}
		})
	}
}

// TestAdd: Add nameserver's entry refused in its kind's words, each an
// inline result under the prompt, the field asked again; then the plan
// for the list with it added, y; the host and hardn.yml changed, the
// configuration adopting the file as saved (its list, its bytes), and the
// screen drawn again with both.
func TestAdd(t *testing.T) {
	h, cfg := newHost(t, debian13, configured)
	p := play(h, cfg, wide, false, "2", "", "999.1.1.1", "192.0.2.54", "ff02::1", "192.0.2.053", "2001:DB8::53", "y", "0")
	if p.err != nil || p.unread != 0 || len(p.runs) != 1 || p.runs[0].Err != nil {
		t.Fatalf("Run = %v, %d unread, runs %+v:\n%s", p.err, p.unread, p.runs, p.out)
	}
	want := []string{"(x) Nameserver cannot be empty", "(x) Invalid IP address format", "(x) Nameserver 192.0.2.54 is already configured",
		"(x) Not a usable nameserver address", "(x) Invalid IP address format", "Add nameserver 2001:db8::53? [y/N"}
	at := 0
	for _, w := range want {
		i := strings.Index(p.out[at:], w)
		if i < 0 {
			t.Fatalf("%q not after %d:\n%s", w, at, p.out)
		}
		at += i
	}
	list := []string{"192.0.2.54", "2001:db8::54", "2001:db8::53"}
	if got := listOf(t, h); !slices.Equal(got, list) || !slices.Equal(cfg.Nameservers, list) {
		t.Errorf("hardn.yml lists %q, the configuration %q; want %q", got, cfg.Nameservers, list)
	}
	if data, _, err := h.ReadFileNoFollow(context.Background(), hardnYML); err != nil || !cfg.LoadedFrom(data) || cfg.Path() != hardnYML {
		t.Errorf("the configuration does not record hardn.yml as saved (%v)", err)
	}
	if got := content(h, hostdns.ResolvConf); got != resolvConf(dhcpcdHead, list...) {
		t.Errorf("resolv.conf:\n%s", got)
	}
	if s := screens(p.out); len(s) != 2 || row(s[1], "Nameservers") != "192.0.2.54, 2001:db8::54, 2001:db8..." || !strings.Contains(s[1], "Nameserver 3         2001:db8::53") {
		t.Errorf("the screen drawn again shows %q", s)
	}
}

