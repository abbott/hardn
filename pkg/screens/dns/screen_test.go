// wide is the width the tests play at. The layouts' content stops at 64
// columns whatever the terminal's, so a row's value longer than its 38
// cells is cut with the ellipsis there too: the tests that need a list
// whole read it from the screen's reading (read_test.go).
const wide = 120

// flat is out with each callout's continued lines joined ("\n# "), a
// word broken after its hyphen ("zz-\n# hardn.conf") made whole again, its
// white space as single spaces, so that a wrapped sentence reads whole.
func flat(out string) string {
	out = strings.ReplaceAll(out, "-\n# ", "-")
	return strings.Join(strings.Fields(strings.ReplaceAll(out, "\n# ", " ")), " ")
}

// listOf is the list hardn.yml at its path holds now, read as hardn reads
// it.
func listOf(t *testing.T, h *fakeHost) []string {
	t.Helper()
	c, err := config.Read(context.Background(), h, hardnYML)
	if err != nil {
		t.Fatal(err)
	}
	return c.Nameservers
}

// resolvConf is /etc/resolv.conf with list as its nameservers after head.
func resolvConf(head string, list ...string) string {
	for _, ns := range list {
		head += "nameserver " + ns + "\n"
	}
	return head
}

