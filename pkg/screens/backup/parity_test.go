// at is what is at backupPath when a run starts: pkg/characterization's
// start (menu_backup_test.go), in its words.
type at int

const (
	atNothing  at = iota // nothing there
	atDir                // an empty directory
	atSentinel           // a directory holding the user's .write_test
	atFile               // a regular file
)

// start is what a scenario's run starts from, on both paths.
type start struct {
	enabled, dryRun bool
	at              at
	shared, afile   bool
}

// words is s as pkg/characterization's golden says it on its Start line
// (startWords), its $TMP read as the root.
func (s start) words() string {
	var w string
	switch s.at {
	case atSentinel:
		w = fmt.Sprintf("a directory holding .write_test, %d bytes of the user's", len(sentinel))
	case atDir:
		w = "an empty directory"
	case atFile:
		w = "a regular file"
	default:
		w = "nothing there"
	}
	if s.shared {
		w += "; " + shared + " a directory anyone can write to"
	}
	if s.afile {
		w += "; " + afile + " a regular file"
	}
	return fmt.Sprintf("enableBackups %t, backupPath %s (%s), dryRun %t", s.enabled, backupPath, w, s.dryRun)
}

// The host states, what is at backupPath (/var/backups root's, 0755, on
// every cell).
var (
	stateNothing  = parity.HostState{Long: "backupPath not there; /var/backups root's, 0755", Short: "not there"}
	stateDir      = parity.HostState{Long: "backupPath an empty directory, root's, 0755", Short: "a directory"}
	stateSentinel = parity.HostState{Long: "backupPath a directory holding the user's .write_test", Short: "the user's .write_test"}
	stateFile     = parity.HostState{Long: "backupPath a regular file", Short: "a file"}
	stateShared   = parity.HostState{Long: "backupPath an empty directory; /shared root's, 0777, not sticky", Short: "a directory, /shared 0777"}
	stateAFile    = parity.HostState{Long: "backupPath an empty directory; /afile a regular file", Short: "a directory, /afile a file"}
)

// state is the host state of s.
func (s start) state() parity.HostState {
	switch {
	case s.shared:
		return stateShared
	case s.afile:
		return stateAFile
	}
	return []parity.HostState{stateNothing, stateDir, stateSentinel, stateFile}[s.at]
}

