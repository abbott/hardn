var (
	stateNothing  = parity.HostState{Long: "backupPath not there; /var/backups root's, 0755", Short: "not there"}
	stateDir      = parity.HostState{Long: "backupPath an empty directory, root's, 0755", Short: "a directory"}
	stateSentinel = parity.HostState{Long: "backupPath a directory holding the user's .write_test", Short: "the user's .write_test"}
	stateFile     = parity.HostState{Long: "backupPath a regular file", Short: "a file"}
	stateShared   = parity.HostState{Long: "backupPath an empty directory; /shared root's, 0777, not sticky", Short: "a directory, /shared 0777"}
	stateAFile    = parity.HostState{Long: "backupPath an empty directory; /afile a regular file", Short: "a directory, /afile a file"}
)

// state is the host state of s.
func (s start) state() parity.HostState {
	switch {
	case s.shared:
		return stateShared
	case s.afile:
		return stateAFile
	}
	return []parity.HostState{stateNothing, stateDir, stateSentinel, stateFile}[s.at]
}

