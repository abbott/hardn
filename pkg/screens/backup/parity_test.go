// at is what is at backupPath when a run starts: pkg/characterization's
// start (menu_backup_test.go, retired), in its words.
type at int

const (
	atNothing  at = iota // nothing there
	atDir                // an empty directory
	atSentinel           // a directory holding the user's .write_test
	atFile               // a regular file
)

// start is what a scenario's run starts from, on both paths.
type start struct {
	enabled, dryRun bool
	at              at
	shared, afile   bool
}

// words is s as pkg/characterization's golden says it on its Start line
// (startWords), its $TMP read as the root.
func (s start) words() string {
	var w string
	switch s.at {
	case atSentinel:
		w = fmt.Sprintf("a directory holding .write_test, %d bytes of the user's", len(sentinel))
	case atDir:
		w = "an empty directory"
	case atFile:
		w = "a regular file"
	default:
		w = "nothing there"
	}
	if s.shared {
		w += "; " + shared + " a directory anyone can write to"
	}
	if s.afile {
		w += "; " + afile + " a regular file"
	}
	return fmt.Sprintf("enableBackups %t, backupPath %s (%s), dryRun %t", s.enabled, backupPath, w, s.dryRun)
}

// The host states, what is at backupPath (/var/backups root's, 0755, on
