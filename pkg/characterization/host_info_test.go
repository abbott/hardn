// The main menu's host block reads HostInfoManager, and System Details no longer does
// (pkg/screens/systemdetails, refactor plan slice 1, unit (d)).
//
// TestHostInfoGolden records the seamed half: HostInfoManager.GetHostInfo
// through OSHostInfoRepository and OSUserRepository with the mocks. Hostname,
// Domain and IPAddresses are left out of the golden because the repository
// reads them from os.Hostname and net.Interfaces (os_host_info_repository.go:123,210),
// and so are the `hostname`/`domainname` commands it runs only when the real
// hostname has no dot.
func TestHostInfoGolden(t *testing.T) {
	assertGolden(t, "host_info/debian.golden", hostInfoGolden(t, viaMocks))
}

// TestHostInfoGoldenThroughSystem is TestHostInfoGolden through the legacy
// interfaces' adapters over host.System; compare-only, as
// TestOperationGoldensThroughSystem.
func TestHostInfoGoldenThroughSystem(t *testing.T) {
	if *update {
		t.Skip("compare-only; -update regenerates the golden through TestHostInfoGolden")
	}
	assertGolden(t, "host_info/debian.golden", hostInfoGolden(t, viaSystem))
}

func hostInfoGolden(t *testing.T, via seam) string {
	t.Helper()
	fs := interfaces.NewMockFileSystem()
	mc := interfaces.NewMockCommander()

	fs.Files["/etc/os-release"] = []byte("PRETTY_NAME=\"Debian GNU/Linux 13 (trixie)\"\nNAME=\"Debian GNU/Linux\"\nVERSION_ID=\"13\"\nVERSION=\"13 (trixie)\"\nVERSION_CODENAME=trixie\nID=debian\n")
	fs.Files["/proc/uptime"] = []byte("15724003.25 31000000.00\n")
	fs.Files["/proc/cpuinfo"] = []byte("processor\t: 0\nvendor_id\t: ExampleVendor\nmodel name\t: Example CPU @ 2.00GHz\n")
	fs.Files["/proc/meminfo"] = []byte("MemTotal:        8155528 kB\nMemFree:         4077764 kB\nMemAvailable:    6116646 kB\n")
	fs.Files["/etc/passwd"] = []byte("root:x:0:0:root:/root:/bin/bash\nnobody:x:65534:65534:nobody:/nonexistent:/usr/sbin/nologin\nalice:x:1000:1000:Alice Example,,,:/home/alice:/bin/bash\n")
	fs.Files["/etc/group"] = []byte("root:x:0:\nsudo:x:27:alice\nalice:x:1000:\nexample:x:1001:alice\n")
	fs.Files["/etc/resolv.conf"] = []byte("domain lan\nsearch lan\nnameserver 192.0.2.53\nnameserver 192.0.2.54\n")
	mc.CommandOutputs["uname -r"] = []byte("6.12.0-example-amd64\n")
	mc.CommandOutputs["df -k"] = []byte("Filesystem     1K-blocks    Used Available Use% Mounted on\n/dev/vda1       41251136 6291456  34959680  16% /\ntmpfs            8198468       0   8198468   0% /dev/shm\n/dev/vdb1      103885812 5242880  98642932   6% /srv\n")

	innerFS, innerCmd, seed := legacySeams(via, fs, mc)
	seed()
	log := &trace{}
	provider := &interfaces.Provider{
		FS:        recordingFS{inner: innerFS, log: log},
		Commander: &recordingCommander{inner: innerCmd, log: log},
		Network:   interfaces.NewMockNetworkOperations(),
	}

	osInfo := &osdetect.OSInfo{OsType: "debian", OsVersion: "13", OsCodename: "trixie"}
	factory := infrastructure.NewServiceFactory(provider, osInfo)
	factory.SetConfig(fixtureConfig(false))
	manager := factory.CreateHostInfoManager()

	info, err := manager.GetHostInfo()
	if err != nil {
		t.Fatal(err)
	}

	recorded := struct {
		DNSServers  []string
		Users       any
		Groups      []string
		OSName      string
		OSVersion   string
		Uptime      string
		KernelInfo  string
		CPUInfo     string
		MemoryTotal int64
		MemoryFree  int64
		DiskTotal   map[string]int64
		DiskFree    map[string]int64
	}{
		DNSServers: info.DNSServers, Users: info.Users, Groups: info.Groups,
		OSName: info.OSName, OSVersion: info.OSVersion, Uptime: info.Uptime.String(),
		KernelInfo: info.KernelInfo, CPUInfo: info.CPUInfo,
		MemoryTotal: info.MemoryTotal, MemoryFree: info.MemoryFree,
		DiskTotal: info.DiskTotal, DiskFree: info.DiskFree,
	}
	out, err := json.MarshalIndent(recorded, "", "  ")
	if err != nil {
		t.Fatal(err)
	}

	var filtered trace
	for _, e := range log.entries {
		if strings.HasPrefix(e.text, "exec   domainname ") || strings.HasPrefix(e.text, "exec   hostname ") {
			continue
		}
		filtered.entries = append(filtered.entries, e)
	}

	var b strings.Builder
	b.WriteString(baselineHeader + "\n")
	b.WriteString("# Generated by TestHostInfoGolden (pkg/characterization); regenerate with -update. Do not edit.\n")
	b.WriteString("# Operation: HostInfoManager.GetHostInfo -> OSHostInfoRepository.GetHostInfo (the seamed part of System Details and the main-menu host line)\n")
	b.WriteString("# NOTE: Hostname, Domain and IPAddresses are omitted (read from os.Hostname and net.Interfaces), and so are hostname/domainname commands in the trace.\n")
	b.WriteString("# NOTE: origin/main's pkg/system.GenerateSystemStatus was not recorded: it called exec, os and gopsutil directly. Slice 1's unit (d) deleted it.\n\n")
	b.WriteString("== host info (selected fields)\n")
	b.Write(out)
	b.WriteString("\n\n== trace\n")
	b.WriteString(filtered.String())
	b.WriteString("\n== formatters\n")
	for _, d := range []time.Duration{0, 59 * time.Second, 5*time.Hour + 25*time.Minute, info.Uptime} {
		fmt.Fprintf(&b, "FormatUptime(%s) = %q\n", d, manager.FormatUptime(d))
	}
	for _, n := range []int64{0, 1023, 1536, 1048576, 1610612736, info.MemoryTotal} {
		fmt.Fprintf(&b, "FormatBytes(%d) = %q\n", n, manager.FormatBytes(n))
	}
	return b.String()
}
