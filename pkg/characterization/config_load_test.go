package characterization

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/abbott/hardn/pkg/config"
)

type configCase struct {
	name    string // golden stem
	fixture string // file under testdata/fixtures/config
	viaEnv  bool   // pass the path in HARDN_CONFIG instead of as -f
	notes   []string
	defects []string // KNOWN-DEFECT lines (without the prefix)
}

func configCases() []configCase {
	return []configCase{
		{
			name: "full-flag", fixture: "full.yml",
			notes: []string{
				"LoadConfig keeps dryRun from the file; cmd/hardn/main.go:158 then overwrites it with the -n flag value (V3).",
				"The unknown key notAConfigKey is ignored without a warning.",
				"sshConfigFile is loaded but the SSH adapter never reads it; the drop-in path is hard-coded (file_ssh_repository.go:37-43).",
			},
		},
		{name: "full-hardn-config-env", fixture: "full.yml", viaEnv: true},
		{name: "minimal", fixture: "minimal.yml", notes: []string{"Keys absent from the file keep their DefaultConfig() values."}},
		{name: "comments-only", fixture: "comments-only.yml"},
		{name: "yaml11-bools", fixture: "yaml11-bools.yml", notes: []string{"Records how YAML 1.1 spellings (yes/no/on/off) decode into bool fields."}},
		{name: "type-error", fixture: "type-error.yml"},
		{
			name: "v032-disableroot", fixture: "v032-disableroot.yml",
			defects: []string{"V24 — v0.3.2's disableRoot key is ignored without a warning (origin/main reads disableRootSSH), so DisableRootSSH stays false"},
		},
	}
}

// TestConfigLoadGoldens records config.LoadConfig on fixture files copied into a
// temp dir. The real search path is never consulted: every case names an
// existing file, either as the -f value or in HARDN_CONFIG, and HOME points at
// a temp dir.
func TestConfigLoadGoldens(t *testing.T) {
	for _, tc := range configCases() {
		t.Run(tc.name, func(t *testing.T) {
			dir := t.TempDir()
			t.Setenv("HOME", dir)
			// DetectEnvVarLoss runs `su` when SUDO_UID is set (pkg/config/config.go:290-323).
			t.Setenv("SUDO_UID", "")
			t.Setenv("SUDO_USER", "")
			t.Setenv("HARDN_CONFIG", "")

			src, err := os.ReadFile(filepath.Join("testdata", "fixtures", "config", tc.fixture))
			if err != nil {
				t.Fatal(err)
			}
			path := filepath.Join(dir, "hardn.yml")
			if err := os.WriteFile(path, src, 0o600); err != nil {
				t.Fatal(err)
			}
			// A missing file would fall through to an interactive prompt on stdin.
			if _, err := os.Stat(path); err != nil {
				t.Fatal(err)
			}

			explicit := path
			how := "explicit path (hardn -f <file>, cmd/hardn/main.go:151)"
			if tc.viaEnv {
				explicit = ""
				t.Setenv("HARDN_CONFIG", path)
				how = "HARDN_CONFIG=<file>, no -f (cmd/hardn/main.go:151)"
			}

			cfg, loadErr := config.LoadConfig(explicit)

			var b strings.Builder
			b.WriteString(baselineHeader + "\n")
			b.WriteString("# Generated by TestConfigLoadGoldens (pkg/characterization); regenerate with -update. Do not edit.\n")
			b.WriteString("# Operation: config.LoadConfig (pkg/config/config.go) on a fixture copied to a temp dir\n")
			fmt.Fprintf(&b, "# Fixture: testdata/fixtures/config/%s, passed as %s\n", tc.fixture, how)
			for _, d := range tc.defects {
				fmt.Fprintf(&b, "# KNOWN-DEFECT: %s\n", d)
			}
			for _, n := range tc.notes {
				fmt.Fprintf(&b, "# NOTE: %s\n", n)
			}
			b.WriteString("# Output: the loaded Config as JSON (Go field names), or the error with the temp dir shown as <tmp>.\n\n")
			if loadErr != nil {
				fmt.Fprintf(&b, "error: %s\n", strings.ReplaceAll(loadErr.Error(), dir, "<tmp>"))
			} else {
				out, err := json.MarshalIndent(cfg, "", "  ")
				if err != nil {
					t.Fatal(err)
				}
				b.Write(out)
				b.WriteString("\n")
			}
			if strings.Contains(b.String(), dir) {
				t.Fatalf("golden would contain the temp dir %s", dir)
			}
			assertGolden(t, "config/"+tc.name+".golden", b.String())
		})
	}
}
