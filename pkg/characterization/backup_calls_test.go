// Whether hardn's changes take backups (refactor plan slice 3, unit (a),
// next/s3-gallery; docs/engine/gallery-backup.md §2.7): every origin/main
// operation of the operations goldens, run with backups enabled; and,
// beside them, pkg/host/backup's run of one change. The goldens are
// testdata/golden/backups/*. origin/main's two BackupFile functions, run
// on their own (TestLegacyBackupFile), were retired with them in slice
// 3's unit (d), next/s3-replace; their golden, legacy_backupfile.golden,
// is frozen in pkg/screens/backup/testdata/legacy/backups.

// backupHeader opens every golden of this file.
const backupHeader = baselineHeader + "\n# Generated by %s (pkg/characterization); regenerate with -update. Do not edit.\n"

// TestLegacyOperationsTakeNoBackups runs every operation of the operations
// goldens (TestOperationGoldens) on every cell with backups enabled and
// backupPath at its default, config.DefaultConfig's, and counts what each
// wrote: whether any write, directory or file lands under backupPath or
// is a .bak copy. None does: origin/main's changes take no backups (V18),
// whatever enableBackups says. The count is from the recorded trace, the
// one the goldens of ops/ hold.
func TestLegacyOperationsTakeNoBackups(t *testing.T) {
	t.Setenv("SUDO_USER", fixtureUser)
	t.Setenv("USER", "root")
	t.Setenv("HARDN_CONFIG", "")
	if err := os.Unsetenv("TMPDIR"); err != nil {
		t.Fatal(err)
	}
	def := config.DefaultConfig()
	if !def.EnableBackups || def.BackupPath != backup.DefaultPath {
		t.Fatalf("the defaults are enableBackups %t, backupPath %q", def.EnableBackups, def.BackupPath)
	}
	writeRe := regexp.MustCompile(`^\s*\d+ (write|mkdir)\s+(\S+)`)
	var b strings.Builder
	fmt.Fprintf(&b, backupHeader, "TestLegacyOperationsTakeNoBackups")
	b.WriteString("# KNOWN-DEFECT: V18: nothing is backed up first: no write, directory or file under backupPath, and no .bak copy, in any operation on any cell\n")
	fmt.Fprintf(&b, "# NOTE: every operation of TestOperationGoldens, cfg.DryRun=false, with enableBackups %t and backupPath %s (config.DefaultConfig); the count is the file writes and directories made in the trace\n", def.EnableBackups, def.BackupPath)
	b.WriteString("# NOTE: one operation does write a backup of its own, whatever enableBackups says: apt's sources.list.bak (pkg/adapter/secondary/os_package_respository.go:226-232), which the operations here do not reach (read)\n")
	b.WriteString("\noperation                         cell     writes+dirs  under backupPath  .bak copies\n")
	for _, sc := range opScenarios() {
		for _, cell := range osCells {
			_, section, _ := runCell(t, sc, cell, false, viaMocks)
			writes, under, baks := 0, 0, 0
			for _, line := range strings.Split(section, "\n") {
				m := writeRe.FindStringSubmatch(line)
				if m == nil {
					continue
				}
				writes++
				if p := m[2]; p == backup.DefaultPath || strings.HasPrefix(p, backup.DefaultPath+"/") {
					under++
				}
				if strings.HasSuffix(m[2], ".bak") {
					baks++
				}
			}
			fmt.Fprintf(&b, "%-33s %-8s %-12d %-17d %d\n", sc.name, cell.name, writes, under, baks)
			if under != 0 || baks != 0 {
				t.Errorf("%s on %s wrote under backupPath or a .bak copy: the golden's claim no longer holds", sc.name, cell.name)
			}
		}
	}
	assertGolden(t, "backups/legacy_operations.golden", b.String())
}

// TestEngineBackupRun shows pkg/host/backup's run of one change, as the
// engine takes it, with the Settings of each state of enableBackups: the
// files it makes, their modes, and the manifest, on hostfake. It is the
// other side of the retired TestLegacyBackupFile's table (frozen in
// pkg/screens/backup/testdata/legacy/backups/legacy_backupfile.golden,
// which this golden's header names): the layout <backupPath>/<run-id>/, a
// numbered copy at 0600, manifest.json at 0600.
func TestEngineBackupRun(t *testing.T) {
	ctx := context.Background()
	const runID = "20261020T120000Z-1a2b3c4d"
	createdRe := regexp.MustCompile(`"created": "[^"]*"`)
	var b strings.Builder
	b.WriteString("# pkg/host/backup on next/v0.4, not origin/main: the engine's backups, beside the legacy BackupFile's (backups/legacy_backupfile.golden)\n")
	b.WriteString("# Generated by TestEngineBackupRun (pkg/characterization); regenerate with -update. Do not edit.\n")
	b.WriteString("# NOTE: not origin/main: pkg/host/backup (docs/safety/atomic.md §2), which the engine uses for every change it plans. The change here backs up /etc/ssh/sshd_config, which is there, and /etc/ssh/sshd_config.d/00-hardn.conf, which the change creates.\n")
	for _, s := range []backup.Settings{{Path: backup.DefaultPath, Enabled: true}, {Path: backup.DefaultPath, Enabled: false}} {
		for _, need := range []backup.Need{backup.Optional, backup.RollbackRequired} {
			name := map[backup.Need]string{backup.Optional: "Optional", backup.RollbackRequired: "RollbackRequired"}[need]
			fmt.Fprintf(&b, "\n== enableBackups %t, %s\n", s.Enabled, name)
			f := hostfake.New(host.Options{})
			f.AddDir("/var/backups", 0o755, 0, 0)
			f.AddDir("/etc/ssh/sshd_config.d", 0o755, 0, 0)
			f.AddFile("/etc/ssh/sshd_config", []byte("Port 22\n"), 0o644, 0, 0)
			if err := backup.Check(ctx, f, s, runID, []string{"/etc/ssh/sshd_config", "/etc/ssh/sshd_config.d/00-hardn.conf"}); err != nil {
				t.Fatalf("Check: %v", err)
			}
			run, err := backup.Open(f, s, runID)
			if err != nil {
				t.Fatal(err)
			}
			for _, p := range []string{"/etc/ssh/sshd_config", "/etc/ssh/sshd_config.d/00-hardn.conf"} {
				r, err := run.Backup(ctx, p, need)
				fmt.Fprintf(&b, "Backup %s: outcome %q, %s\n", p, r.Outcome, errText(err))
			}
			var files []string
			entries, rerr := f.ReadDir(ctx, run.Dir())
			if rerr != nil && !errors.Is(rerr, fs.ErrNotExist) {
				t.Fatal(rerr)
			}
			for _, e := range entries {
				en, _ := f.Entry(filepath.Join(run.Dir(), e.Name()))
				files = append(files, fmt.Sprintf("  %s/%s mode=%04o", run.Dir(), e.Name(), en.Mode.Perm()))
			}
			sort.Strings(files)
			if len(files) == 0 {
				files = []string{"  (no run directory: nothing was created)"}
			}
			b.WriteString("files:\n" + strings.Join(files, "\n") + "\n")
			if len(entries) > 0 {
				m, err := backup.Load(ctx, f, run.Dir())
				if err != nil {
					t.Fatal(err)
				}
				data, err := json.MarshalIndent(m, "", "  ")
				if err != nil {
					t.Fatal(err)
				}
				b.WriteString("manifest.json:\n" + createdRe.ReplaceAllString(string(data), `"created": "<run time>"`) + "\n")
			}
		}
	}
	assertGolden(t, "backups/engine_run.golden", b.String())
}
