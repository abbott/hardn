// TestPlanGroupLayout checks the plan group on plain text at the ASCII
// profile: PlanView's lines and the code wrap.
// The widths are at most theme.ContentWidth, where no §3.15 rule changes
// the result.
func TestPlanGroupLayout(t *testing.T) {
	tests := []struct {
		name    string
		vm      renderer
		width   int
		unicode bool
		want    string
	}{
		{"plan: a lockout-risk change, its file headers left out", PlanView{Changes: []PlanChange{sshChange}}, 64, false,
			"  [*] Set Port 2230\n      Lockout risk\n      " + dropIn + "\n      @@ -1,3 +1,3 @@\n       # Managed by hardn\n" +
				"      -Port 22\n      +Port 2230\n       PermitRootLogin no\n      $ sshd -t\n      $ systemctl reload ssh"},
		{"plan: no target keeps the file headers", PlanView{Changes: []PlanChange{{Title: "Set the nameservers", Diff: dnsChange.Diff}}}, 64, true,
			"   -  Set the nameservers\n      --- " + resolv + "\n      +++ " + resolv + "\n      @@ -1,2 +1,3 @@\n       # Generated by hardn\n" +
				"      -nameserver 192.0.2.1\n      +nameserver 192.0.2.53\n      +nameserver 192.0.2.54"},
		{"plan: the dry-run footer", PlanView{Changes: []PlanChange{{Title: "Enable UFW"}}, DryRun: true}, 64, false,
			"   -  Enable UFW\n\n  [i] Info: No actual changes were made to your system."},
		{"plan: code breaks at a space, then inside a word", PlanView{Changes: []PlanChange{{
			Title: "Allow users", After: "AllowUsers alice bob replication-service\n\tMatch",
		}}}, 30, true,
			"   -  Allow users\n      +AllowUsers alice bob\n      ↪replication-service\n      +    Match"},
		{"plan: a word longer than the line", PlanView{Changes: []PlanChange{{Title: "Write", Target: "/var/backups/hardn/web-01.example.net"}}}, 30, false,
			"   -  Write\n      /var/backups/hardn/web-0\n      >1.example.net"},
		{"plan: code keeps its quotes and indent", PlanView{Changes: []PlanChange{{Title: "Echo", Commands: []string{"echo ‘hi’ \x1b[1mbold\x1b[m"}}}}, 64, true,
			"   -  Echo\n      $ echo ‘hi’ bold"},
		{"plan: no changes", PlanView{DryRun: true}, 64, false, ""},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := ansi.Strip(tt.vm.Render(NewCtx(term.Fixed(tt.width, colorprofile.ASCII, tt.unicode, true))))
			if got != tt.want {
				t.Errorf("got\n%s\nwant\n%s", got, tt.want)
			}
		})
	}
}

// TestCodeKeepsText checks the code wrap on long lines at every width
// from 1 to 90: each piece fits and ends in no space, and the pieces hold
// every character of the line but the spaces at the breaks, in order.
func TestCodeKeepsText(t *testing.T) {
	lines := []string{
		"+AllowUsers alice bob backup-replication-service monitoring-agent deploy-bot",
		"     indented    with    runs of spaces and a-very-long-word-that-has-no-space-in-it-at-all",
		"Get:12 http://deb.example.net/debian trixie/main amd64 package-12 [1024 B]",
		"日本語のテキストと English words mixed together in one line of output",
	}
	for _, unicode := range []bool{true, false} {
		for w := 1; w <= 90; w++ {
			c := NewCtx(term.Fixed(w, colorprofile.ASCII, unicode, true))
			glyph := c.Theme.Glyphs.Wrap
			for _, l := range lines {
				var kept strings.Builder
				for i, p := range c.code(theme.LabelCol, l, lipgloss.NewStyle()) {
					where := fmt.Sprintf("width %d, unicode %v, piece %d of %q", w, unicode, i, l)
					if lipgloss.Width(p) > c.width() || strings.HasSuffix(p, " ") {
						t.Fatalf("%s: %q is too wide or ends in a space", where, p)
					}
					p = strings.TrimPrefix(p, strings.Repeat(" ", theme.LabelCol))
					if i > 0 {
						p = strings.TrimPrefix(p, glyph)
					}
					kept.WriteString(p)
				}
				if w <= theme.LabelCol+2 {
					continue // too narrow for a character beside the column: cut
				}
				nospace := func(s string) string { return strings.ReplaceAll(s, " ", "") }
				if got, want := nospace(kept.String()), nospace(l); got != want {
					t.Errorf("width %d, unicode %v: the pieces hold %q, want %q", w, unicode, got, want)
				}
			}
		}
	}
}

// TestPlanGroupStyles checks that each part of the plan group takes its
// slot, and that a lockout-risk change shows a glyph and a word as well as
// a colour.
func TestPlanGroupStyles(t *testing.T) {
	c := NewCtx(term.Fixed(theme.ContentWidth, colorprofile.TrueColor, true, true))
	th, g := c.Theme, c.Theme.Glyphs
	type part struct {
		text  string
		style lipgloss.Style
	}
	tests := []struct {
		name  string
		vm    renderer
		parts []part
	}{
		{"plan", PlanView{Changes: []PlanChange{sshChange, ufwChange}}, []part{
			{g.Risk, th.Plan.LockoutRisk}, {"Set Port 2230", th.Plan.Title}, {lockoutRisk, th.Plan.LockoutRisk},
			{dropIn, th.Plan.Target}, {"@@ -1,3 +1,3 @@", th.Plan.Meta}, {" # Managed by hardn", th.Plan.Context},
			{"-Port 22", th.Plan.Removed}, {"+Port 2230", th.Plan.Added}, {g.Command + " systemctl reload ssh", th.Plan.Command},
			{"-inactive", th.Plan.Removed}, {"+active", th.Plan.Added},
		}},
		{"plan: a change with no title", PlanView{Changes: []PlanChange{{Target: "ufw"}}}, []part{
			{g.Bullet, th.Plan.Context}, {unknown, th.Status.Unknown},
		}},
	}
	for _, tt := range tests {
		got := tt.vm.Render(c)
		for _, want := range tt.parts {
			if !strings.Contains(got, want.style.Render(want.text)) {
				t.Errorf("%s: got %q, want it to hold %q in its style", tt.name, got, want.text)
			}
		}
	}
}
