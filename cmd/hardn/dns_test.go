// The DNS hosts of the DNS item's and -g's tests: hostfake, with a model of
// systemd-resolved that loads hardn's drop-in when reloaded, after
// pkg/screens/dns's tests (helpers_test.go), which a test of another
// package cannot share; written from dns.md §3, not captured from a host.
// The engine and the screen reach them through this package's seams
// (useDNSHost): nothing on this machine is read, run or written.
// Synthetic values only: web-01.example.net, 192.0.2.0/24, example.net.

const (
	dnsTestYML  = "/etc/hardn/hardn.yml"
	dnsTestDHCP = "192.0.2.1"
	dnsTestPID  = 4000
)

// dnsTestList is hardn.yml's list on the hosts.
var dnsTestList = []string{"192.0.2.53", "192.0.2.54"}

var dnsTestNow = time.Date(2026, 10, 23, 12, 0, 0, 0, time.UTC)

// dnsHost is one host: its facts, the fake, and systemd-resolved's state.
type dnsHost struct {
	*hostfake.System
	facts detect.Facts

	mu     sync.Mutex
	active string   // systemctl is-active's word for systemd-resolved
	global []string // the global servers resolved has loaded
	inert  bool     // a reload exits 0 and loads nothing new
}

func dnsFacts(distro detect.Distro, version string, init detect.InitKind) detect.Facts {
	return detect.Facts{Platform: detect.Platform{Distro: distro, Version: version, Support: detect.Supported},
		Init: detect.Init{Kind: init, Running: detect.Yes}, Container: detect.Container{Detected: detect.No}}
}

// newDNSHost returns the host name names, with hardn.yml listing list,
// and hardn.yml as hardn reads it there (config.Read: its path and bytes
// recorded).
func newDNSHost(t *testing.T, name string, list []string) (*dnsHost, *config.Config) {
	t.Helper()
	h := &dnsHost{System: hostfake.New(host.Options{}), active: "inactive", facts: dnsFacts(detect.DistroDebian, "13", detect.Systemd)}
	for _, d := range []string{"/etc", "/etc/hardn", "/var/lib", "/var/backups", "/run", "/var/log"} {
		h.AddDir(d, 0o755, 0, 0)
	}
	file := func(s string) { h.AddFile(hostdns.ResolvConf, []byte(s), 0o644, 0, 0) }
	resolved := func() {
		h.facts, h.active = dnsFacts(detect.DistroUbuntu, "26.04", detect.Systemd), "active"
		h.AddSymlink(hostdns.ResolvConf, "../run/systemd/resolve/stub-resolv.conf")
		h.AddFile("/etc/systemd/resolved.conf", []byte("[Resolve]\n#DNS=\n#Domains=\n"), 0o644, 0, 0)
	}
	switch name {
	case "debian13": // dhcpcd's file
		file("# Generated by dhcpcd from eth0.dhcp\nsearch example.net\nnameserver " + dnsTestDHCP + "\n")
		h.AddFile("/usr/sbin/dhcpcd", nil, 0o755, 0, 0)
	case "ubuntu2604": // resolved's stub link, eth0's server from DHCP
		resolved()
	case "inert": // Ubuntu 26.04, whose reload has no effect
		resolved()
		h.inert = true
	case "alpine324": // udhcpc's file, its stock udhcpc.conf
		h.facts = dnsFacts(detect.DistroAlpine, "3.24", detect.OpenRC)
		file("search example.net\nnameserver " + dnsTestDHCP + "\n")
		h.AddFile(hostdns.UDHCPCConf, []byte("# Do not overwrite /etc/resolv.conf\n#RESOLV_CONF=\"no\"\n"), 0o644, 0, 0)
	case "resolvconf":
		h.AddSymlink(hostdns.ResolvConf, "../run/resolvconf/resolv.conf")
	case "networkmanager":
		h.AddSymlink(hostdns.ResolvConf, "/run/NetworkManager/resolv.conf")
	case "container": // an LXC container
		h.facts.Container = detect.Container{Detected: detect.Yes, Signal: "/proc/1/environ", Manager: "lxc"}
		file("nameserver " + dnsTestDHCP + "\n")
	case "unread": // Debian 13 whose container fact is not established
		file("nameserver " + dnsTestDHCP + "\n")
		h.facts.Container = detect.Container{Detected: detect.Unknown}
	default:
		t.Fatalf("no host %q", name)
	}
	var yml strings.Builder
	yml.WriteString("# hardn's configuration (web-01.example.net)\nusername: alice\nsshPort: 2230\nnameservers:")
	if len(list) == 0 {
		yml.WriteString(" []")
	}
	yml.WriteString("\n")
	for _, ns := range list {
		yml.WriteString("  - " + ns + "\n")
	}
	h.AddFile(dnsTestYML, []byte(yml.String()), 0o644, 0, 0)
	h.Handler = h.answer
	cfg, err := config.Read(context.Background(), h, dnsTestYML)
	if err != nil {
		t.Fatal(err)
	}
	return h, cfg
}

// answer is the host's commands: systemctl and resolvectl, as
// systemd-resolved answers them in the model.
func (h *dnsHost) answer(argv []string, _ []byte) hostfake.Response {
	h.mu.Lock()
	defer h.mu.Unlock()
	switch cmd := strings.Join(argv, " "); cmd {
	case "systemctl is-active " + hostdns.ResolvedUnit:
		if h.active == "active" {
			return hostfake.Response{Stdout: "active\n"}
		}
		return hostfake.Response{Stdout: h.active + "\n", ExitCode: 3}
	case "resolvectl --no-pager dns", "resolvectl --no-pager domain":
		if h.active != "active" {
			return hostfake.Response{Stderr: "Failed to get global data: Unit dbus-org.freedesktop.resolve1.service not found.\n", ExitCode: 1}
		}
		if strings.HasSuffix(cmd, "dns") {
			return hostfake.Response{Stdout: "Global:" + strings.Join(append([]string{""}, h.global...), " ") + "\nLink 2 (eth0): " + dnsTestDHCP + "\n"}
		}
		return hostfake.Response{Stdout: "Global:\nLink 2 (eth0): example.net\n"}
	case "systemctl try-reload-or-restart " + hostdns.ResolvedUnit, "systemctl reload-or-restart " + hostdns.ResolvedUnit:
		if !h.inert {
			h.load()
		}
		return hostfake.Response{}
	}
	return hostfake.Response{Err: hostfake.ErrUnscripted}
}

// load is systemd-resolved reading hardn's drop-in: its DNS= lines
// collect, an empty one resets them.
func (h *dnsHost) load() {
	h.global = nil
	e, ok := h.Entry(hostdns.DropIn)
	if !ok {
		return
	}
	for _, l := range strings.Split(string(e.Data), "\n") {
		if v, ok := strings.CutPrefix(strings.TrimSpace(l), "DNS="); ok {
			if v == "" {
				h.global = nil
			}
			h.global = append(h.global, strings.Fields(v)...)
		}
	}
}

// content is name's content on h, or "<absent>".
func (h *dnsHost) content(name string) string {
	e, ok := h.Entry(name)
	if !ok {
		return "<absent>"
	}
	return string(e.Data)
}

// writes are the calls that changed something outside /run/hardn, the
// engine's run directory: what a run left on the host.
func (h *dnsHost) writes() []string {
	var out []string
	for _, c := range h.Calls() {
		switch c.Op {
		case "write-atomic", "write-in-place", "remove", "removeall", "rename", "mkdir", "chmod", "chown", "append":
			if !strings.HasPrefix(c.Path, "/run/hardn") {
				out = append(out, c.Op+" "+c.Path)
			}
		}
	}
	return out
}

// dnsSeams is what useDNSHost points the seams at: the screen's and the
// report's output, and the holds the engine took.
type dnsSeams struct {
	out  bytes.Buffer
	held int
}

// useDNSHost points the engine's and the screens' seams at h until the
// test ends: its facts, a hold that counts, the user typing lines, plain
// output at 80 columns into the returned buffer, and revert's clock,
// pid, environment and hardn's path fixed.
func useDNSHost(t *testing.T, h *dnsHost, lines ...string) *dnsSeams {
	t.Helper()
	s := &dnsSeams{}
	hostWas, detectWas, holdWas, inputWas, stdoutWas, envWas := engineHost, engineDetect, engineHold, engineInput, engineStdout, stdoutEnv
	nowWas, pidWas, getenvWas, executableWas := revertNow, revertPID, revertGetenv, revertExecutable
	t.Cleanup(func() {
		engineHost, engineDetect, engineHold, engineInput, engineStdout, stdoutEnv = hostWas, detectWas, holdWas, inputWas, stdoutWas, envWas
		revertNow, revertPID, revertGetenv, revertExecutable = nowWas, pidWas, getenvWas, executableWas
	})
	in := prompt.New(uitest.NewTypist(&s.out, lines...), false)
	engineHost = func() host.System { return h }
	engineDetect = func(context.Context, host.System) (detect.Facts, error) { return h.facts, nil }
	engineHold = func() func() { s.held++; return func() {} }
	engineInput = func() *prompt.Reader { return in }
	engineStdout = &s.out
	stdoutEnv = func() term.Env { return term.Resolve(term.Options{}, term.Facts{Width: 80}) }
	revertNow = func() time.Time { return dnsTestNow }
	revertPID = func() int { return dnsTestPID }
	revertGetenv = func(string) string { return "" }
	revertExecutable = func() (string, error) { return revertTestHardn, nil }
	return s
}

// TestDNSScreen: the main menu's DNS item runs the DNS screen on the host
// hardn builds, through the engine with engineOptions: Add nameserver on
// Debian 13 plans, asks, applies the host's file and saves hardn.yml, and
// the configuration the main menu holds adopts the list as saved; 0 goes
// back (nil), q quits (nav.ErrQuit), the end of the input aborts
// (prompt.ErrAborted); a dry run, as the configuration says when the item
// is chosen, writes nothing. No audit record is written.
func TestDNSScreen(t *testing.T) {
	added := append(slices.Clone(dnsTestList), "192.0.2.55")
	for _, tc := range []struct {
		name    string
		dryRun  bool
		lines   []string
		want    error    // what the screen returns: nil, nav.ErrQuit, prompt.ErrAborted
		list    []string // the configuration's list afterwards
		written bool
	}{
		{"add, then return", false, []string{"2", "192.0.2.55", "y", "0"}, nil, added, true},
		{"add as a dry run", true, []string{"2", "192.0.2.55", "0"}, nil, dnsTestList, false},
		{"add declined", false, []string{"2", "192.0.2.55", "n", "0"}, nil, dnsTestList, false},
		{"quit", false, []string{"q"}, nav.ErrQuit, dnsTestList, false},
		{"the end of the input", false, nil, prompt.ErrAborted, dnsTestList, false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			h, cfg := newDNSHost(t, "debian13", dnsTestList)
			s := useDNSHost(t, h, tc.lines...)
			cfg.DryRun = tc.dryRun // as the Dry-Run item or -n leaves it before 3 is chosen
			err := runDNSScreen(context.Background(), cfg)
			if tc.want == nil && err != nil || tc.want != nil && !errors.Is(err, tc.want) {
				t.Fatalf("runDNSScreen = %v, want %v; screen:\n%s", err, tc.want, s.out.String())
			}
			if !slices.Equal(cfg.Nameservers, tc.list) {
				t.Errorf("the main menu's configuration lists %q, want %q", cfg.Nameservers, tc.list)
			}
			got := h.writes()
			if !tc.written {
				if len(got) > 0 {
					t.Errorf("wrote %q", got)
				}
				return
			}
			want := []string{"write-atomic " + hostdns.ResolvConf, "write-atomic " + dnsTestYML}
			for _, w := range want {
				if !slices.Contains(got, w) {
					t.Errorf("writes %q lack %q", got, w)
				}
			}
			for _, ns := range added {
				if !strings.Contains(h.content(hostdns.ResolvConf), "nameserver "+ns+"\n") {
					t.Errorf("/etc/resolv.conf lacks %s:\n%s", ns, h.content(hostdns.ResolvConf))
				}
			}
			if yml := h.content(dnsTestYML); !strings.Contains(yml, "192.0.2.55") || !strings.HasPrefix(yml, "# hardn's configuration") {
				t.Errorf("hardn.yml not saved with the list, its comment kept:\n%s", yml)
			}
			if !cfg.LoadedFrom([]byte(h.content(dnsTestYML))) {
				t.Error("the configuration does not record hardn.yml as saved, so the next save would be refused CONFIG_CHANGED")
			}
			for _, c := range got {
				if strings.HasPrefix(c, "append ") {
					t.Errorf("an audit record was written: %s", c)
				}
			}
		})
	}
}
